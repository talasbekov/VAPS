import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('n_meldebekov')
await page.goto(`http://localhost:3106/statuses?forcesRequest=${encodeURIComponent(run.allocationId)}`)
await page.waitForLoadState('networkidle'); await sleep(1200)
const banner = page.getByRole('status', { name: `Запрос на ${run.code}`, exact: true })
const search = page.getByPlaceholder('Поиск по ФИО, отделу, должности...')
// физнаряд: Байжанов (есть учётка) + Есимов (без учётки)
for (const s of ['Байжанов', 'Есимов']) {
  await search.fill(s); await sleep(900)
  const row = page.getByRole('row').filter({ hasText: s }).first()
  console.log(s, ':', (await row.innerText()).replace(/\n+/g, ' · ').slice(0, 90))
  await row.getByRole('checkbox').check()
}
await search.fill(''); await sleep(600)
const btn = banner.getByRole('button', { name: /Добавить в общий резерв/ })
console.log('кнопка:', (await btn.allInnerTexts()).join('|'))
await shot(page, 'meldebekov-two-selected-physical')
const rp = page.waitForResponse(x => /forces\/(requests|directorate)/.test(x.url()) && x.request().method() === 'POST')
await btn.first().click()
const r = await rp; console.log('POST', r.url().replace(/^.*\/api/, '/api'), r.status(), (await r.text()).slice(0, 200))
await sleep(1200)
console.log('отчёт выбора:', (await banner.locator('[data-slot="select-report"]').innerText().catch(() => '—')).replace(/\n+/g, ' | '))
await shot(page, 'meldebekov-physical-reserved')
// группа: Нурланов → Группы → Группа досмотра → специальность
await search.fill('Нурланов'); await sleep(900)
await page.getByRole('row').filter({ hasText: 'Нурланов' }).first().getByRole('checkbox').check()
await banner.getByRole('group', { name: 'Подгруппа участия ОМ', exact: true }).getByRole('button', { name: 'Группы', exact: true }).click(); await sleep(600)
await shot(page, 'meldebekov-groups-branch')
console.log('ветка Группы:', (await banner.innerText()).replace(/\n+/g, ' | ').slice(-600))
const own = page.getByRole('combobox', { name: 'Свои группы', exact: true })
console.log('свои группы combobox:', await own.count())
if (await own.count()) { await own.click(); await sleep(400); console.log('опции своих:', (await page.getByRole('option').allInnerTexts()).join(' | ')); await page.keyboard.press('Escape') }
const other = page.getByRole('button', { name: 'Выбрать другую группу другого подразделения', exact: true })
console.log('кнопка других групп:', await other.count())
const kinds = await api('n_meldebekov', 'GET', '/api/ops/dictionaries/EVENT_PARTICIPATION_KINDS/entries/')
const kind = kinds.body.results.find(k => k.code === 'SCREENING_GROUP')
console.log('SCREENING_GROUP:', JSON.stringify({ label: kind?.label, isOwn: kind?.isOwn, owner: kind?.ownerDivisionName ?? kind?.ownerDivision }))
if (kind?.isOwn) { await own.click(); await page.getByRole('option', { name: new RegExp(kind.label) }).click() }
else {
  await other.click(); await sleep(400)
  await page.getByRole('textbox', { name: 'Поиск другой группы', exact: true }).fill('досмотр'); await sleep(800)
  const opts = page.getByRole('listbox', { name: 'Другие группы', exact: true }).getByRole('option')
  console.log('другие группы по «досмотр»:', (await opts.allInnerTexts()).map(s => s.replace(/\n/g, ' ')).join(' | '))
  await shot(page, 'meldebekov-other-groups-search')
  await opts.first().click()
}
await sleep(500)
const spec = page.getByRole('combobox', { name: 'Специальность', exact: true })
console.log('специальность combobox:', await spec.count())
if (await spec.count()) { await spec.click(); await sleep(400); const o = page.getByRole('option'); console.log('специальности:', (await o.allInnerTexts()).join(' | ')); await o.first().click() }
console.log('поле мероприятия:', (await banner.innerText()).replace(/\n+/g, ' | ').slice(-400))
await shot(page, 'meldebekov-group-selected')
const gbtn = banner.getByRole('button', { name: new RegExp(`Выделить на ${run.code}`) })
console.log('кнопка группы:', (await gbtn.allInnerTexts()).join('|'), await gbtn.count() ? await gbtn.first().isEnabled() : '')
const rp2 = page.waitForResponse(x => /forces\/(requests|directorate)/.test(x.url()) && x.request().method() === 'POST')
await gbtn.first().click()
const r2 = await rp2; console.log('POST', r2.url().replace(/^.*\/api/, '/api'), r2.status(), (await r2.text()).slice(0, 200))
await sleep(1200)
await shot(page, 'meldebekov-group-allocated')
const st = await api('n_meldebekov', 'GET', `/api/operations/statuses/?employee_id=25`)
console.log('статусы Нурланова:', JSON.stringify(st.body).slice(0, 400))
const res = await api('n_meldebekov', 'GET', '/api/ops/security-events/forces/campaign-reserves/')
console.log('резерв:', JSON.stringify(res.body).slice(0, 400))
await close()
