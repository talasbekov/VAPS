import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('u_musakhan')
await page.goto(`http://localhost:3106/security-ops/events?search=${encodeURIComponent('Проходка №1142')}`)
await page.waitForLoadState('networkidle')
const row = page.getByRole('row').filter({ hasText: run.code })
console.log('строка найдена:', await row.count())
const btn = row.getByRole('button', { name: `Назначить старшего наряда ${run.code}` })
console.log('кнопка назначения старшего у создателя:', await btn.count())
if (await btn.count()) {
  await btn.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Поиск сотрудника' }).fill('Оралбаев Арман')
  await sleep(900)
  const cands = dialog.getByRole('button', { name: /Оралбаев/ })
  const n = await cands.count()
  console.log('кандидатов по «Оралбаев Арман»:', n)
  for (let i = 0; i < Math.min(n, 6); i++) console.log('  ', (await cands.nth(i).innerText()).replace(/\n/g, ' · '), '| attrs:', await cands.nth(i).evaluate(el => JSON.stringify(Object.fromEntries([...el.attributes].filter(a => /data-|value|id/.test(a.name)).map(a => [a.name, a.value])))))
  await shot(page, 'musakhan-reassign-chief-search')
  await cands.first().click()
  const resp = page.waitForResponse(r => r.url().includes(`/security-events/${run.eventId}/chief/`) && r.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Назначить', exact: true }).click()
  console.log('POST chief', (await resp).status())
  await sleep(800)
}
const ev = await api('u_musakhan', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('chief теперь:', ev.body.chiefEmployeeId, ev.body.chiefName)
await shot(page, 'musakhan-registry-after-chief')
await close()
