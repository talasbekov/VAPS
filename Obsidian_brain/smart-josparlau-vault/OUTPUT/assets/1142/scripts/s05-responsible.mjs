import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('a_raiymzhanov')
await page.goto(`http://localhost:3106/employees`)
await page.waitForLoadState('networkidle'); await sleep(800)
console.log('рабочий стол ответственного:', (await page.getByRole('main').innerText()).replace(/\n+/g, ' | ').slice(0, 400))
await shot(page, 'raiymzhanov-workspace')
const notif = await api('a_raiymzhanov', 'GET', '/api/notifications/?page_size=5')
console.log('уведомления:', notif.status, JSON.stringify(notif.body).slice(0, 300))
await page.goto(`http://localhost:3106/employees?request=${encodeURIComponent(run.allocationId)}&businessDate=${run.date}`)
await page.waitForLoadState('networkidle'); await sleep(1000)
await shot(page, 'raiymzhanov-request-card', true)
console.log('заявка:', (await page.getByRole('main').innerText()).replace(/\n+/g, ' | ').slice(0, 600))
await page.locator('#answer-allocating').fill('3')
await page.locator('#answer-comment').fill('Проходка №1142: четвёртый сотрудник в командировке, выделяем троих')
const gc = page.getByRole('spinbutton', { name: /Количество групп, строка/ })
console.log('строк групп:', await gc.count())
for (const c of await gc.all()) await c.fill('1')
await page.getByRole('button', { name: 'Сохранить ответ', exact: true }).click(); await sleep(1000)
await shot(page, 'raiymzhanov-answer-saved', true)
let a = (await api('a_raiymzhanov', 'GET', `/api/ops/security-events/forces/requests/${encodeURIComponent(run.allocationId)}/`)).body.allocation
console.log('ответ:', JSON.stringify({ allocating: a.allocating, answerComment: a.answerComment, groupOffers: a.groupOffers?.map(g => [g.kindCode ?? g.kind, g.count ?? g.need]), directorates: a.directorates?.map(d => [d.divisionId, d.divisionName ?? d.name, d.need]) }))
console.log('квоты доступны:', (await page.locator('input[id^="quota-"]').evaluateAll(l => l.map(i => i.id))).join(' | '))
await page.locator('#quota-632').fill('3')
const drow = page.locator('#quota-632').locator('xpath=ancestor::tr')
console.log('чекбоксов групп в строке управления:', await drow.getByRole('checkbox').count())
for (const cb of await drow.getByRole('checkbox').all()) await cb.check()
const saveQ = page.getByRole('button', { name: 'Сохранить раскладку', exact: true })
if (await saveQ.count()) { await saveQ.click(); await sleep(800) }
await page.getByRole('button', { name: 'Отправить в управления', exact: true }).click(); await sleep(500)
console.log('подтверждение:', (await page.getByRole('dialog').innerText()).replace(/\n+/g, ' | ').slice(0, 300))
await shot(page, 'raiymzhanov-notify-confirm')
await page.getByRole('dialog').getByRole('button', { name: 'Отправить', exact: true }).click(); await sleep(1500)
a = (await api('a_raiymzhanov', 'GET', `/api/ops/security-events/forces/requests/${encodeURIComponent(run.allocationId)}/`)).body.allocation
console.log('после отправки:', JSON.stringify({ notifiedAt: a.notifiedAt, directorates: a.directorates?.map(d => [d.divisionId, d.divisionName ?? d.name, d.need, d.groupOffers?.length]) }))
await shot(page, 'raiymzhanov-sent-to-directorates', true)
await close()
