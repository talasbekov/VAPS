import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const list = await api('u_musakhan', 'GET', '/api/ops/personnel/?search=' + encodeURIComponent('Оралбаев') + '&page_size=50')
const rows = list.body.results
console.log('API кандидатов:', rows.length, rows.map((r, i) => `${i}:${r.id}:${r.rankLabel}:${r.unit}`).join(' | '))
const idx = rows.findIndex(r => String(r.id) === '162')
console.log('индекс 162 =', idx, rows[idx])
const { page, close } = await open('u_musakhan')
await page.goto(`http://localhost:3106/security-ops/events?search=${encodeURIComponent('Проходка №1142')}`)
await page.waitForLoadState('networkidle')
const row = page.getByRole('row').filter({ hasText: run.code })
await row.getByRole('button', { name: `Заменить старшего наряда ${run.code}` }).click()
const dialog = page.getByRole('dialog')
await dialog.getByRole('textbox', { name: 'Поиск сотрудника' }).fill('Оралбаев')
await sleep(1000)
const cands = dialog.getByRole('button', { name: /Оралбаев/ })
console.log('UI кандидатов:', await cands.count())
for (let i = 0; i < await cands.count(); i++) console.log('  ', i, (await cands.nth(i).innerText()).replace(/\n/g, ' · '), await cands.nth(i).isEnabled() ? '' : '(disabled)')
await shot(page, 'musakhan-replace-chief-14-same')
await cands.nth(idx).click()
const resp = page.waitForResponse(r => r.url().includes(`/security-events/${run.eventId}/chief/`) && r.request().method() === 'POST')
await dialog.getByRole('button', { name: 'Заменить', exact: true }).click()
const r = await resp; console.log('POST chief', r.status(), (await r.text()).slice(0, 160))
await sleep(600)
const ev = await api('u_musakhan', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('chief теперь:', ev.body.chiefEmployeeId, ev.body.chiefName)
await page.goto(`http://localhost:3106/security-ops/events/${run.eventId}/`)
await page.waitForLoadState('networkidle'); await sleep(800)
await shot(page, 'musakhan-event-card')
const btns = await page.getByRole('main').getByRole('button').allInnerTexts()
console.log('кнопки карточки:', btns.map(s => s.replace(/\n/g,' ').trim()).filter(Boolean).join(' | ').slice(0, 700))
console.log('есть «Редактировать бюллетень»:', await page.getByRole('button', { name: /Редактировать бюллетень/ }).count(), '| ссылок:', await page.getByRole('main').getByRole('link', { name: /Редактировать/ }).count())
await close()
