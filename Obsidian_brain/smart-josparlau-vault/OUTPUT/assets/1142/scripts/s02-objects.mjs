import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('k_baglanov')
await page.goto(`http://localhost:3106/security-ops/events?search=${encodeURIComponent('Проходка №1142')}`)
await page.waitForLoadState('networkidle'); await sleep(500)
const row = page.getByRole('row').filter({ hasText: run.code })
console.log('кнопки строки у старшего:', (await Promise.all((await row.getByRole('button').all()).map(b => b.getAttribute('aria-label')))).join(' | '))
// 2a. Правка бюллетеня: ОЛ → OL-2
await row.getByRole('button', { name: `Действия ${run.code}` }).click(); await sleep(400)
console.log('меню:', (await page.getByRole('menu').innerText()).replace(/\n+/g, ' | '))
await shot(page, 'baglanov-row-menu')
await page.getByRole('menuitem', { name: /Редактировать бюллетень/ }).click(); await sleep(900)
let dialog = page.getByRole('dialog')
await shot(page, 'baglanov-edit-bulletin')
const chipBtns = dialog.locator('[data-slot], button').filter({ hasText: /Контур1140/ })
console.log('чипов с Контур1140:', await chipBtns.count())
const removeBtn = dialog.getByRole('button', { name: /Убрать|Снять|Удалить.*Контур1140|Контур1140/ })
console.log('кнопок снятия:', await removeBtn.count(), (await removeBtn.allInnerTexts()).join('|').slice(0,100))
for (const b of await dialog.getByRole('button').all()) { const l = await b.getAttribute('aria-label'); if (l && /Контур|лицо|Убрать|Снять/i.test(l)) console.log('  aria:', l) }
const rm = dialog.getByRole('button', { name: /Убрать .*Контур1140|Снять .*Контур1140/ })
if (await rm.count()) await rm.first().click()
const ol = dialog.getByPlaceholder(/Добавить ещё лицо|Найти в справочнике ОЛ/)
await ol.click(); await ol.fill('OL-2'); await sleep(800)
const opts = dialog.getByRole('listbox').getByRole('option')
console.log('ОЛ по OL-2:', (await opts.allInnerTexts()).map(s => s.replace(/\n/g, ' ')).join(' | '))
const ex = opts.filter({ hasText: /^OL-2(?!\d)/ })
if (await ex.count()) await ex.first().getByRole('button').click(); else console.log('OL-2 не найден отдельно')
await sleep(400)
await shot(page, 'baglanov-edit-bulletin-ol2')
const save = dialog.getByRole('button', { name: /Сохранить/ })
console.log('сохранить:', (await save.allInnerTexts()).join('|'))
const resp = page.waitForResponse(r => r.url().includes(`/security-events/${run.eventId}/`) && ['PATCH','POST','PUT'].includes(r.request().method()))
await save.first().click()
const r = await resp; console.log(r.request().method(), r.url().replace(/^.*\/api/, '/api'), r.status(), (await r.text()).slice(0, 120))
await sleep(800)
let ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('ОЛ после правки:', JSON.stringify(ev.body.protectedPersons ?? ev.body.personName ?? ev.body.protectedPersonNames).slice(0, 160))
// 2b. Добавить объекты
await page.goto(`http://localhost:3106/security-ops/events?search=${encodeURIComponent('Проходка №1142')}`)
await page.waitForLoadState('networkidle'); await sleep(500)
const row2 = page.getByRole('row').filter({ hasText: run.code })
await row2.getByRole('button', { name: `Действия ${run.code}` }).click(); await sleep(300)
await page.getByRole('menuitem', { name: /Добавить объекты посещения/ }).click(); await sleep(800)
dialog = page.getByRole('dialog')
await shot(page, 'baglanov-add-objects-dialog')
console.log('объекты в окне:', (await dialog.getByRole('checkbox').all()).length, (await dialog.innerText()).replace(/\n+/g,' | ').slice(0, 500))
await dialog.getByRole('checkbox', { name: /Стенд: объект с готовым паспортом/ }).check()
await dialog.getByRole('checkbox', { name: /Стенд: второй объект посещения/ }).check()
await dialog.getByRole('button', { name: 'Добавить (2)', exact: true }).click()
await sleep(1200)
ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('объектов:', ev.body.visitObjects.map(v => `${v.id}:${v.name}:stage=${v.stage}:chief=${v.chiefEmployeeId}`).join(' | '))
// 2c. Старшие объектов
await row2.getByRole('button', { name: /^Развернуть объекты/ }).click(); await sleep(800)
await shot(page, 'baglanov-row-expanded')
const chiefs = [['Стенд: объект с готовым паспортом', 'Тасмагамбетов', '164'], ['Стенд: второй объект посещения', 'Сапарова', '163']]
for (const [obj, surname, id] of chiefs) {
  await page.getByRole('button', { name: `Назначить старшего объекта ${obj}`, exact: true }).click()
  const d = page.getByRole('dialog')
  await d.getByLabel('Поиск сотрудника').fill(surname); await sleep(900)
  const c = d.getByRole('button', { name: new RegExp(surname) })
  console.log(`кандидатов «${surname}»:`, await c.count(), (await c.allInnerTexts()).map(s => s.replace(/\n/g,' · ')).join(' || '))
  if (surname === 'Тасмагамбетов') await shot(page, 'baglanov-object-chief-search')
  const list = await api('k_baglanov', 'GET', '/api/ops/personnel/?search=' + encodeURIComponent(surname) + '&page_size=50')
  const idx = list.body.results.findIndex(x => String(x.id) === id); console.log('индекс', id, '=', idx)
  await c.nth(idx).click()
  const rp = page.waitForResponse(x => x.url().includes('/visit-objects/') && x.request().method() === 'POST')
  await d.getByRole('button', { name: 'Назначить', exact: true }).click()
  console.log('POST chief', (await rp).status())
  await sleep(600)
}
ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('объекты со старшими:', ev.body.visitObjects.map(v => `${v.id}:${v.name}:chief=${v.chiefEmployeeId}/${v.chiefName}`).join(' | '))
await shot(page, 'baglanov-object-chiefs-assigned')
// 2d. Открыть рекогносцировку
await page.goto(`http://localhost:3106/security-ops/events/${run.eventId}/`)
await page.waitForLoadState('networkidle'); await sleep(600)
const openRecon = page.getByRole('button', { name: 'Открыть рекогносцировку', exact: true })
console.log('кнопка «Открыть рекогносцировку»:', await openRecon.count(), await openRecon.count() ? await openRecon.isEnabled() : '')
if (await openRecon.count()) { await openRecon.click(); await sleep(1200) }
ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('stage ОМ:', ev.body.stage, '| объекты:', ev.body.visitObjects.map(v => v.stage).join(','))
await shot(page, 'baglanov-recon-opened')
fs.writeFileSync('run.json', JSON.stringify({ ...run, visits: ev.body.visitObjects.map(v => ({ id: v.id, name: v.name, chief: v.chiefEmployeeId })) }, null, 2))
await close()
