import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('u_musakhan')
await page.goto(`http://localhost:3106/security-ops/events?search=${encodeURIComponent('Проходка №1142')}`)
await page.waitForLoadState('networkidle')
const row = page.getByRole('row').filter({ hasText: run.code })
await row.getByRole('button', { name: `Действия ${run.code}` }).click()
await sleep(400)
console.log('меню:', (await page.getByRole('menu').innerText()).replace(/\n+/g, ' | '))
await shot(page, 'musakhan-row-actions-menu')
await page.getByRole('menuitem', { name: /Редактировать бюллетень/ }).click()
await sleep(800)
const dialog = page.getByRole('dialog')
await shot(page, 'musakhan-edit-bulletin-dialog')
const chief = dialog.getByLabel('Старший наряда')
console.log('поле старшего в правке:', await chief.count())
await chief.first().click(); await chief.first().fill('Оралбаев Арман'); await sleep(1000)
const cands = dialog.getByRole('button', { name: /Оралбаев/ }).or(dialog.getByRole('option', { name: /Оралбаев/ }))
const n = await cands.count(); console.log('кандидатов по «Оралбаев Арман»:', n)
for (let i = 0; i < Math.min(n, 5); i++) console.log('  ', (await cands.nth(i).innerText()).replace(/\n/g, ' · '))
await shot(page, 'musakhan-edit-chief-fullname-search')
if (n) await cands.first().click()
// ОЛ: снять Контур1140, добавить OL-2
const chip = dialog.getByRole('button', { name: /Убрать|Снять|×/ }).first()
const ol = dialog.getByPlaceholder(/Добавить ещё лицо|Найти в справочнике ОЛ/)
await ol.click(); await ol.fill('OL-2'); await sleep(700)
const olOpts = dialog.getByRole('listbox').getByRole('option')
console.log('ОЛ по «OL-2»:', (await olOpts.allInnerTexts()).map(s => s.replace(/\n/g, ' ')).join(' | '))
const exact = olOpts.filter({ hasText: /OL-2(?!\d)/ })
if (await exact.count()) await exact.first().getByRole('button').click()
console.log('чипы ОЛ:', (await dialog.locator('text=ГЛАВНОЕ').count()))
await shot(page, 'musakhan-edit-filled')
const save = dialog.getByRole('button', { name: /Сохранить/ })
console.log('кнопка сохранения:', await save.count(), (await save.allInnerTexts()).join('|'))
const resp = page.waitForResponse(r => /security-events\/\d+\/(details|)\/?$/.test(r.url()) && ['PATCH','POST','PUT'].includes(r.request().method()))
await save.first().click()
const r = await resp; console.log(r.request().method(), r.url().replace(/^.*\/api/, '/api'), r.status(), (await r.text()).slice(0, 200))
await sleep(800)
const ev = await api('u_musakhan', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('после правки: chief', ev.body.chiefEmployeeId, ev.body.chiefName, '| ОЛ', JSON.stringify(ev.body.protectedPersons ?? ev.body.protectedPersonNames ?? ev.body.personName).slice(0, 200))
await close()
