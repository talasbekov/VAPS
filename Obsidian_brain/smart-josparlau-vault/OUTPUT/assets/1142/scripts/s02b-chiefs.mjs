import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('k_baglanov')
await page.goto(`http://localhost:3106/security-ops/events?search=${encodeURIComponent('Проходка №1142')}`)
await page.waitForLoadState('networkidle'); await sleep(800)
const rows = page.getByRole('row').filter({ hasText: run.code })
console.log('строк с кодом:', await rows.count())
const main = rows.first()
console.log('кнопки:', (await Promise.all((await main.getByRole('button').all()).map(b => b.getAttribute('aria-label')))).join(' | '))
const exp = main.getByRole('button', { name: /^(Развернуть|Свернуть) объекты/ })
if ((await exp.getAttribute('aria-label') || '').startsWith('Развернуть')) { await exp.click(); await sleep(800) }
await shot(page, 'baglanov-row-expanded')
console.log('кнопки назначения:', (await page.getByRole('button', { name: /Назначить старшего объекта/ }).all()).length, (await Promise.all((await page.getByRole('button', { name: /старшего объекта/ }).all()).map(b => b.getAttribute('aria-label')))).join(' | '))
let ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('поля объекта:', Object.keys(ev.body.visitObjects[0]).slice(0, 40).join(','))
const chiefs = [['Стенд: объект с готовым паспортом', 'Тасмагамбетов', '164'], ['Стенд: второй объект посещения', 'Сапарова', '163']]
for (const [obj, surname, id] of chiefs) {
  await page.getByRole('button', { name: `Назначить старшего объекта ${obj}`, exact: true }).click()
  const d = page.getByRole('dialog')
  await d.getByLabel('Поиск сотрудника').fill(surname); await sleep(900)
  const c = d.getByRole('button', { name: new RegExp(surname) })
  console.log(`кандидатов «${surname}»:`, await c.count(), (await c.allInnerTexts()).map(s => s.replace(/\n/g,' · ')).join(' || '))
  if (surname === 'Тасмагамбетов') await shot(page, 'baglanov-object-chief-search')
  const list = await api('k_baglanov', 'GET', '/api/ops/personnel/?search=' + encodeURIComponent(surname) + '&page_size=50')
  const idx = list.body.results.findIndex(x => String(x.id) === id); console.log('индекс', id, '=', idx)
  await c.nth(Math.max(idx, 0)).click()
  const rp = page.waitForResponse(x => /visit-objects\/\d+\/chief/.test(x.url()) && x.request().method() === 'POST')
  await d.getByRole('button', { name: 'Назначить', exact: true }).click()
  const r = await rp; console.log('POST chief', r.status(), (await r.text()).slice(0, 100))
  await sleep(800)
}
ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('объекты со старшими:', ev.body.visitObjects.map(v => `${v.id}:${v.objectName ?? v.title}:chief=${v.chiefEmployeeId}/${v.chiefName}`).join(' | '))
await shot(page, 'baglanov-object-chiefs-assigned')
await page.goto(`http://localhost:3106/security-ops/events/${run.eventId}/`)
await page.waitForLoadState('networkidle'); await sleep(600)
const openRecon = page.getByRole('button', { name: 'Открыть рекогносцировку', exact: true })
console.log('«Открыть рекогносцировку»:', await openRecon.count(), await openRecon.count() ? await openRecon.isEnabled() : '')
if (await openRecon.count() && await openRecon.isEnabled()) { await openRecon.click(); await sleep(1500) }
ev = await api('k_baglanov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('stage ОМ:', ev.body.stage, '| объекты:', ev.body.visitObjects.map(v => v.stage).join(','))
await shot(page, 'baglanov-recon-opened')
fs.writeFileSync('run.json', JSON.stringify({ ...run, visits: ev.body.visitObjects.map(v => ({ id: v.id, name: v.objectName ?? v.title, chief: v.chiefEmployeeId })) }, null, 2))
await close()
