import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('m_turmagambetov')
await page.goto(`http://localhost:3106/security-ops/events/${run.eventId}?visit=${run.visits[1].id}`)
await page.waitForLoadState('networkidle'); await sleep(2500)
console.log('меню слева:', (await page.getByRole('navigation').first().innerText().catch(() => '')).replace(/\n+/g, ' | ').slice(0, 400))
await shot(page, 'turmagambetov-placement-sidebar-check')
const post = page.getByRole('button', { name: /Пост у ворот/ })
console.log('кнопка поста:', await post.count())
if (await post.count()) await post.first().click()
const cand = page.getByRole('button', { name: /Есимов/ })
console.log('карточка кандидата:', await cand.count(), (await cand.allInnerTexts()).map(s => s.replace(/\n+/g, ' · ')).join(' || '))
await cand.first().click(); await sleep(300)
const assign = page.getByRole('button', { name: /Назначить на выбранный пост/ })
console.log('кнопка назначения:', await assign.count(), await assign.count() ? await assign.isEnabled() : '')
await shot(page, 'turmagambetov-candidate-selected')
const rp = page.waitForResponse(x => /placement\/assign/.test(x.url()) && x.request().method() === 'POST')
await assign.click()
const r = await rp; console.log('POST placement/assign', r.status(), (await r.text()).slice(0, 100)); await sleep(1000)
await shot(page, 'turmagambetov-assigned', true)
await page.getByRole('button', { name: 'Завершить расстановку', exact: true }).click(); await sleep(800)
const dlg = page.getByRole('dialog')
if (await dlg.count()) { console.log('диалог:', (await dlg.innerText()).replace(/\n+/g, ' | ').slice(0, 200)) }
await sleep(1000)
const e = (await api('m_turmagambetov', 'GET', `/api/ops/security-events/${run.eventId}/`)).body
console.log('объект 2:', e.visitObjects[1].stage, e.visitObjects[1].documentStatus, '| ОМ:', e.stage, '| назначения:', JSON.stringify(e.placementAssignments?.map(a => [a.employeeId, a.postId?.slice(-6)])))
await shot(page, 'turmagambetov-placement-completed', true)
await close()
