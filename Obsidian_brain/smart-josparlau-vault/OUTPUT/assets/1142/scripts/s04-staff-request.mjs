import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const { page, close } = await open('y_meiram')
await page.goto(`http://localhost:3106/employees?collection=${run.eventId}&businessDate=${run.date}`)
await page.waitForLoadState('networkidle'); await sleep(1000)
await shot(page, 'meiram-collection-card', true)
const card = page.getByRole('main')
const t = (await card.innerText()).replace(/\n+/g, ' | ')
console.log('карточка сбора:', t.slice(0, 700))
await card.getByRole('button', { name: 'Департамент', exact: true }).click(); await sleep(400)
const dep = page.getByLabel('Департамент, строка 1', { exact: true })
console.log('департаменты:', (await dep.locator('option').allTextContents()).join(' | '))
await dep.selectOption('631')
await page.getByLabel('Сколько человек, строка 1', { exact: true }).fill('4')
await page.getByLabel('Комментарий Штаба, строка 1', { exact: true }).fill('Проходка №1142: физнаряд на два объекта + группа досмотра на входе')
const groups = page.locator('[data-slot="draft-row"]').getByRole('checkbox')
console.log('чекбоксов групп в строке:', await groups.count(), (await page.locator('[data-slot="draft-row"]').innerText()).replace(/\n+/g, ' | ').slice(0, 300))
for (const g of await groups.all()) await g.check()
await shot(page, 'meiram-request-draft', true)
await page.getByRole('button', { name: 'Отправить запросы', exact: true }).click(); await sleep(500)
console.log('подтверждение:', (await page.getByRole('dialog').innerText()).replace(/\n+/g, ' | ').slice(0, 400))
await shot(page, 'meiram-send-requests-confirm')
const rp = page.waitForResponse(x => /forces\/(split|send)/.test(x.url()) && x.request().method() === 'POST')
await page.getByRole('dialog').getByRole('button', { name: 'Отправить', exact: true }).click()
const r = await rp; console.log(r.request().method(), r.url().replace(/^.*\/api/, '/api'), r.status(), (await r.text()).slice(0, 120))
await sleep(1200)
await shot(page, 'meiram-requests-sent', true)
const fc = await api('y_meiram', 'GET', `/api/ops/security-events/${run.eventId}/force-collection/`)
const a = fc.body.allocations?.[0]
console.log('allocation:', JSON.stringify({ id: a?.id, dep: a?.departmentName ?? a?.departmentId, need: a?.need, sentAt: a?.sentAt, dueAt: a?.dueAt, groupDemands: a?.groupDemands?.map(g => [g.kindCode ?? g.kind, g.need]) }))
fs.writeFileSync('run.json', JSON.stringify({ ...run, allocationId: a?.id }, null, 2))
await close()
