import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const RUN = { marker: 'Проходка №1142', date: '2026-10-05', dateEnd: '2026-10-06' }
const { page, close } = await open('u_musakhan')
await page.goto('http://localhost:3106/security-ops/events/')
await page.getByRole('button', { name: '+ Создать бюллетень' }).click()
const dialog = page.getByRole('dialog')
await dialog.getByRole('button', { name: 'Внутреннее', exact: true }).click()
await dialog.getByLabel('Дата начала').fill(RUN.date)
await dialog.getByLabel('Дата окончания').fill(RUN.dateEnd)
await dialog.getByLabel('Время', { exact: true }).fill('10:00')
await dialog.getByLabel('Охраняемые лица').click()
await sleep(600)
const options = dialog.getByRole('listbox').getByRole('option')
console.log('ОЛ в списке:', (await options.allInnerTexts()).map(s => s.replace(/\n/g, ' ')).slice(0, 6).join(' | '))
const ol2 = options.filter({ hasText: 'OL-2' })
await ((await ol2.count()) ? ol2.first() : options.first()).getByRole('button').click()
await dialog.getByLabel('Название ОМ').fill(`${RUN.marker} — внутреннее ОМ`)
await sleep(500)
console.log('Страна/Город:', await dialog.getByLabel('Страна').inputValue(), '/', await dialog.getByLabel('Город').inputValue())
// старший наряда — k_baglanov = Оралбаев Арман
const chief = dialog.getByLabel('Старший наряда')
console.log('поле старшего есть:', await chief.count())
if (await chief.count()) {
  await chief.first().click(); await chief.first().fill('Оралбаев'); await sleep(800)
  await shot(page, 'musakhan-create-chief-search')
  const cand = page.getByRole('option', { name: /Оралбаев/ }).or(page.getByRole('button', { name: /Оралбаев/ }))
  console.log('кандидатов Оралбаев:', await cand.count())
  if (await cand.count()) await cand.first().click()
}
await sleep(500)
await shot(page, 'musakhan-create-filled', false)
console.log('предпросмотр:', (await dialog.innerText()).split('ТАК СТРОКА ЛЯЖЕТ')[1]?.replace(/\n+/g, ' | ').slice(0, 300))
const resp = page.waitForResponse(r => r.url().includes('/api/ops/security-events/') && r.request().method() === 'POST')
await dialog.getByRole('button', { name: 'Создать бюллетень', exact: true }).click()
const r = await resp
console.log('POST', r.status())
await page.waitForURL(/\/security-ops\/events\/\d+/, { timeout: 20000 })
const id = new URL(page.url()).pathname.split('/').filter(Boolean).at(-1)
await page.waitForLoadState('networkidle')
await shot(page, 'musakhan-event-created')
const ev = await api('u_musakhan', 'GET', `/api/ops/security-events/${id}/`)
console.log('event', id, ev.body.code, ev.body.title, 'stage', ev.body.stage, 'chief', ev.body.chiefEmployeeId, ev.body.chiefName, 'visits', ev.body.visitObjects?.length)
fs.writeFileSync('run.json', JSON.stringify({ ...RUN, eventId: id, code: ev.body.code }, null, 2))
await close()
