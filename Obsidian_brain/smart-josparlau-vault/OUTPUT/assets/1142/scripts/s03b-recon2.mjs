import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const run = JSON.parse(fs.readFileSync('run.json', 'utf8'))
const visit = run.visits[1]
const { page, close } = await open('m_turmagambetov')
await page.goto(`http://localhost:3106/security-ops/events/${run.eventId}?visit=${visit.id}`)
await page.waitForLoadState('networkidle'); await sleep(800)
const stage = page.getByRole('region', { name: 'Рекогносцировка объекта' })
console.log('регион:', await stage.count())
const imp = stage.getByRole('button', { name: 'Импорт из паспорта', exact: true })
console.log('импорт из паспорта:', await imp.count(), await imp.count() ? (await imp.isEnabled() ? 'enabled' : 'disabled') : '')
await shot(page, 'turmagambetov-recon2-start')
for (const item of await stage.locator('[data-slot="recon-check-item"]').all()) await item.getByRole('button', { name: 'Норма', exact: true }).click()
await stage.getByRole('button', { name: '+ Добавить сектор', exact: true }).click(); await sleep(500)
console.log('секторов:', await stage.getByLabel(/^Сектор /).count(), '| названия:', (await stage.getByLabel(/^Название сектора/).all()).length)
const secName = stage.getByLabel(/^Название сектора/).first()
await secName.fill('Вход и парковка')
console.log('постов после добавления сектора:', await stage.getByLabel('Пост', { exact: true }).count())
const addPost = stage.getByRole('button', { name: /Добавить пост|\+ Пост/ })
console.log('кнопок «добавить пост»:', await addPost.count(), (await addPost.allInnerTexts()).join('|'))
if (await stage.getByLabel('Пост', { exact: true }).count() === 0 && await addPost.count()) { await addPost.first().click(); await sleep(400) }
const posts = stage.getByLabel('Пост', { exact: true })
console.log('постов:', await posts.count())
await posts.first().fill('Пост у ворот')
const name = await posts.first().inputValue()
await stage.getByLabel('Задача').first().fill('Контроль въезда')
await stage.getByLabel('Потребность', { exact: true }).first().fill('1')
await stage.getByLabel(`Подробнее: ${name}`, { exact: true }).click()
await stage.getByLabel(`Вид потребности: ${name}`, { exact: true }).selectOption('PHYSICAL_SQUAD')
await stage.getByLabel(`Спецификация потребности: ${name}`, { exact: true }).fill('Охрана въезда')
await shot(page, 'turmagambetov-recon2-filled', true)
await stage.getByRole('button', { name: 'Сохранить расчёт', exact: true }).click(); await sleep(1000)
const fin = stage.getByRole('button', { name: 'Завершить рекогносцировку →', exact: true })
console.log('завершить доступна:', await fin.isEnabled())
await fin.click(); await sleep(400)
console.log('диалог:', (await page.getByRole('dialog').innerText()).replace(/\n+/g, ' | ').slice(0, 200))
const rp = page.waitForResponse(x => x.url().includes('/recon/complete/') && x.request().method() === 'POST')
await page.getByRole('dialog').getByRole('button', { name: 'Отправить', exact: true }).click()
const r = await rp; console.log('POST recon/complete', r.status(), (await r.text()).slice(0, 100))
await sleep(1000)
const ev = await api('m_turmagambetov', 'GET', `/api/ops/security-events/${run.eventId}/`)
console.log('объекты:', ev.body.visitObjects.map(v => `${v.id}:${v.stage}:need=${v.reconForceRequest}`).join(' | '), '| ОМ stage:', ev.body.stage, '| demandRows:', JSON.stringify(ev.body.demandRows?.map(d => [d.visitObjectId, d.kindCode, d.need])))
await shot(page, 'turmagambetov-recon2-done')
await close()
