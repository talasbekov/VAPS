import fs from 'node:fs'
import { open, shot, sleep, api } from './walk.mjs'
const { page, close } = await open('acc_admin')
// 1. Выдать роль EVENT_APPROVER учётке a_rakhymzhanov
await page.goto('http://localhost:3106/settings/users/')
await page.getByLabel('Поиск по учётным записям').fill('a_rakhymzhanov')
await page.getByRole('table').getByRole('button', { name: 'a_rakhymzhanov', exact: true }).click()
await sleep(800)
await shot(page, 'admin-user-rakhymzhanov-before')
const roleSel = page.getByLabel('Роль', { exact: true })
const opts = await roleSel.locator('option').allTextContents()
console.log('роли в списке:', opts.filter(o => /соглас|approver|утвер/i.test(o)).join(' | '))
await roleSel.selectOption('EVENT_APPROVER')
await page.getByRole('button', { name: 'Выдать' }).click()
await sleep(1200)
await shot(page, 'admin-user-rakhymzhanov-role-granted')
console.log('роли человека:', (await page.getByLabel('Роли человека').innerText()).replace(/\n+/g, ' | '))
// 2. Маршрут согласования: второй подписант — a_rakhymzhanov
await page.goto('http://localhost:3106/security-ops/settings/')
await page.waitForLoadState('networkidle')
const card = page.locator('[data-slot="approval-route-card"]')
await card.scrollIntoViewIfNeeded()
await shot(page, 'admin-approval-route-before')
console.log('шаг1:', await card.getByLabel('Роль подписанта 1').inputValue(), '/', await card.getByLabel('Учётка подписанта 1').inputValue())
console.log('шаг2:', await card.getByLabel('Роль подписанта 2').inputValue(), '/', await card.getByLabel('Учётка подписанта 2').inputValue())
await card.getByLabel('Учётка подписанта 2').fill('a_rakhymzhanov')
await card.getByRole('button', { name: 'Сохранить маршрут' }).click()
await sleep(1500)
await shot(page, 'admin-approval-route-saved')
console.log('карточка после:', (await card.innerText()).replace(/\n+/g, ' | ').slice(0, 500))
const r = await api('acc_admin', 'GET', '/api/ops/approval-route/')
console.log('API маршрут:', JSON.stringify(r.body))
await close()
