def _period(event):
    """Период мероприятия так, как он написан в образце: «20-21.04.2026».

    Одна дата — без диапазона: «20.04.2026». Образец пишет и так, и так, и
    выдумывать второй день ради единообразия нельзя.
    """
    start = event.business_date
    end = event.business_date_end
    if end and end != start:
        return f"{start.day:02d}-{end.day:02d}.{start.month:02d}.{start.year}"
    return f"{start.day:02d}.{start.month:02d}.{start.year}"


# Метки бланка, за которыми стоит место под человека, — в терминах справочника
# ролей наряда (`PLACEMENT_ROLES`). Ключ — казахская подпись из бланка, она же
# лежит в скобках у подписи роли: по ней документ и сверяют.
def _roles_by_kazakh_label():
    """{казахская подпись: код роли} по справочнику раздела.

    Читается из справочника, а не из списка здесь: роли ведут на экране
    справочников, и второй список разошёлся бы с первым молча.
    """
    from organization_management.apps.operations.models import OpsDictionaryEntry

    mapping = {}
    for entry in OpsDictionaryEntry.objects.filter(
        dictionary_code="PLACEMENT_ROLES", is_active=True
    ):
        match = re.search(r"\(([^)]+)\)", entry.label)
        if match:
            mapping[match.group(1).strip().lower()] = entry.code
    return mapping


def placeholder_roles(path=TEMPLATE):
    """{имя места: код роли} — по подписи, стоящей в бланке ПЕРЕД местом.

    🔴 ТОЛЬКО СОБСТВЕННАЯ ПОДПИСЬ. В бланке есть перечисления вида
    «Көшпелі күзетінің жауаптысы: X, Y, Z»: у второго и третьего места своей
    подписи нет, и приписать им роль первого — та же догадка, от которой
    уходили (см. шапку файла). Такие места остаются без роли и в документе
    пустыми.
    """
    import zipfile

    with zipfile.ZipFile(path) as archive:
        xml = archive.read("word/document.xml").decode("utf-8", "ignore")
    text = re.sub(r"<[^>]+>", "", xml)
    roles = _roles_by_kazakh_label()
    found = {}
    for match in re.finditer(r"\{\{(person_\d+)\}\}", text):
        before = text[max(0, match.start() - 70) : match.start()]
        label = re.split(r"[;.»\n]|\{\{person_\d+\}\}", before)[-1]
        label = label.strip().rstrip(":").strip().lower()
        code = roles.get(label)
        if code is not None:
            found[match.group(1)] = code
    return found


#: Кириллица бланка → латиница кода секции. Таблица нужна затем, что коды
#: справочника раздела читают глазами при разборе («какая секция не заполнилась»),
#: и непрозрачный хэш вместо `ULAN_BATOR` сделал бы разбор невозможным.
#: Казахские буквы переведены по общепринятой латинице; порядок замен важен
#: только для многобуквенных («Ш» → `SH` до «С» → `S` дела не меняет, но
#: явный словарь надёжнее правил).
_TRANSLIT = {
    "а": "a", "ә": "a", "б": "b", "в": "v", "г": "g", "ғ": "g", "д": "d",
    "е": "e", "ё": "e", "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k",
    "қ": "q", "л": "l", "м": "m", "н": "n", "ң": "n", "о": "o", "ө": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ұ": "u", "ү": "u",
    "ф": "f", "х": "h", "һ": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sh",
    "ъ": "", "ы": "y", "і": "i", "ь": "", "э": "e", "ю": "iu", "я": "ia",
}

#: Предел длины кода — у `OpsDictionaryEntry.code` он 100 символов. Обрезка
#: молчаливой быть не должна: подписи секций бланка длинные, и две разные,
#: совпавшие после обрезки, слились бы в одну. Поэтому у обрезанных кодов
#: хвост — короткий отпечаток полной подписи.
_SECTION_CODE_LIMIT = 100


def _section_code(label):
    """Код секции по её подписи: читаемый, устойчивый, не длиннее 100.

    Читаемый — потому что коды справочника раздела разбирают глазами. Устойчивый
    — потому что бланк переснимается при каждом новом образце заказчика, и код,
    зависящий от ПОРЯДКА секций в файле, молча переехал бы на чужую секцию при
    первой же вставке раздела в середину.
    """
    import hashlib

    normalized = "".join(
        _TRANSLIT.get(char, char) for char in label.lower()
    )
    slug = re.sub(r"[^a-z0-9]+", "_", normalized).strip("_").upper()
    if not slug:
        slug = "SECTION"
    if len(slug) <= _SECTION_CODE_LIMIT:
        return slug
    fingerprint = hashlib.sha1(label.encode("utf-8")).hexdigest()[:8].upper()
    return f"{slug[: _SECTION_CODE_LIMIT - len(fingerprint) - 1]}_{fingerprint}"


def _is_section_heading(text):
    """Заголовок ли это секции бланка (Plane №242, Ш-1).

    Правило выведено ПЕРЕЧИСЛЕНИЕМ всех абзацев файла, а не догадкой: заголовки
    секций — короткие абзацы с названием в кавычках-ёлочках («Ұлан-батор»
    көшпелі күзет, «Сапар» объектісі, «St.Regis Astana» - Ұлан-батор).

    Три отсекающих условия, и каждое поймало настоящий абзац:
      • есть место подстановки — это строка с людьми, а не заголовок;
      • длиннее 80 знаков — это проза («ҚК ӘП (жауынгерлік топ) – 5 қызм. …
        „Алмаз-1“…»), в ней кавычки встречаются как обычная пунктуация;
      • кончается двоеточием — это зачин предложения («…жедел штаб „Балхаш“
        жүзеге асырады:»), а не заголовок раздела.

    Замерено на образце: правило даёт 29 заголовков и накрывает 1026 мест из
    1027. Единственное место вне секций — `person_1`, ответственный за ВСЮ
    выездную охрану; он и стоит выше первого заголовка. Это не промах правила,
    а факт документа.
    """
    if "{{" in text:
        return False
    if len(text) > 80:
        return False
    if text.rstrip().endswith(":"):
        return False
    return re.search(r"«([^»]+)»", text) is not None


def _template_paragraphs(path=TEMPLATE):
    """Абзацы шаблона по порядку, текстом.

    Читается тем же способом, что `placeholder_roles` — прямо из XML, а не
    через python-docx: разметка Word рвёт текст места на несколько `<w:t>`, и
    оба чтения обязаны видеть одну и ту же склеенную строку.
    """
    import zipfile

    with zipfile.ZipFile(path) as archive:
        xml = archive.read("word/document.xml").decode("utf-8", "ignore")
    paragraphs = []
    for chunk in re.findall(r"<w:p[ >].*?</w:p>", xml, re.S):
        text = re.sub(r"<[^>]+>", "", chunk).strip()
        if text:
            paragraphs.append(text)
    return paragraphs


def template_sections(path=TEMPLATE):
    """Секции бланка по порядку: [{"code", "label"}].

    Нужны справочнику раздела (Ш-2): человек выбирает секцию при назначении, и
    выбирать он должен из того, что в бланке действительно есть.

    Дубли по коду сняты: подпись «Сапар» объектісі стоит в файле трижды (по
    разу на каждый заход мероприятия на объект), и это ОДНА секция, а не три.
    """
    seen = {}
    for text in _template_paragraphs(path):
        if not _is_section_heading(text):
            continue
        code = _section_code(text)
        if code not in seen:
            seen[code] = {"code": code, "label": text}
    return list(seen.values())


def placeholder_sections(path=TEMPLATE):
    """{имя места: код секции} — по ближайшему заголовку НАД местом.

    Вторая координата места (Plane №242, решение заказчика 30.08.2026). Одной
    роли не хватает: «Көшпелі күзетінің жауаптысы» есть у восьми выездных охран
    подряд — «Ұлан-батор», «Ташкент», «Ереван», «Душанбе», … — и система знала
    роль, но не знала, чьего кортежа. Раскладка по одной роли ставила первого
    назначенного в первую охрану наугад.

    Места ДО первого заголовка в ответ не попадают вовсе: у них секции нет, и
    выдумывать её («первая», «общая») значило бы вернуть ту самую догадку.
    """
    current = None
    found = {}
    for text in _template_paragraphs(path):
        if _is_section_heading(text):
            current = _section_code(text)
            continue
        if current is None:
            continue
        for match in re.finditer(r"\{\{(person_\d+)\}\}", text):
            found[match.group(1)] = current
    return found


def _people_by_place(event):
    """{(код роли, код секции): [«Фамилия И.», …]} по назначениям расстановки.

    ПАРА, А НЕ ОДНА РОЛЬ (Plane №242, Ш-6). «Көшпелі күзетінің жауаптысы» есть
    у восьми выездных охран подряд, и раскладка по одной роли ставила первого
    назначенного в первую охрану — то есть наугад, ровно как до №240.

    Назначение без секции попадает под ключ `(роль, None)` и раскладывается
    ТОЛЬКО по местам без секции. Так расстановки, сделанные до №242, не
    расползаются по разделам бланка молча: их места остаются пустыми, а пустое
    место означает «система этого не знает» — то же, что и всегда.
    """
    from collections import defaultdict

    people = defaultdict(list)
    for row in event.placement_assignments or []:
        code = row.get("roleCode")
        if code:
            people[(code, row.get("sectionCode") or None)].append(
                row.get("employeeName") or ""
            )
    return people

def template_placeholders(path=TEMPLATE):
    """Все места подстановки бланка — по именам.

    Читается ИЗ ФАЙЛА, а не из списка в коде: бланк переснимается при каждом
    новом образце заказчика (`build_placement_template.py`), и число мест
    меняется вместе с ним. Список в коде устарел бы молча.
    """
    from docx import Document

    return unresolved_placeholders(Document(path))


def placement_full_values(event):
    """Значения подстановки: даты — периодом, люди — ПО РОЛИ (Plane №240).

    Пусто именно ПУСТОЙ СТРОКОЙ, а не пропуском: пропущенное место остаётся в
    документе как `{{person_17}}` и уезжает заказчику видимым мусором.

    Люди раскладываются по местам, подписанным ИХ РОЛЬЮ И ИХ СЕКЦИЕЙ (Plane
    №242, Ш-6), в порядке назначения. Мест под пару в бланке больше, чем
    людей, — остаток пуст: «система этого не знает» честнее выдуманного имени.
    Людей больше, чем мест, — лишние в документ не попадают, и это видно по
    расстановке на экране: там они есть.

    ЧТО ОСТАЛОСЬ НАУГАД И ЭТО ПРИНЯТО. Внутри одной секции места из
    перечислений («Купол: X, Y») по-прежнему заполняются порядком назначения:
    у второго места своей подписи нет, и различить их нечем. Секция сузила
    беду с восьми мест до двух-трёх, но не сняла её — см. Ш-7 плана.
    """
    period = _period(event)
    by_place = _people_by_place(event)
    roles = placeholder_roles()
    sections = placeholder_sections()
    used = {key: 0 for key in by_place}
    values = {}
    # 🔴 ПОРЯДОК БЛАНКА, а не порядок множества. `template_placeholders`
    # отдаёт МНОЖЕСТВО (оно нужно проверке «ничего не осталось»), и обход по
    # нему разложил бы людей в произвольном порядке: один и тот же состав
    # печатался бы по-разному от запуска к запуску. Сперва места в том
    # порядке, в каком они стоят в документе, затем остальные — на случай,
    # если разбор XML и python-docx разойдутся.
    ordered = list(roles)
    ordered += [name for name in template_placeholders() if name not in roles]
    for name in ordered:
        if name.startswith("day_"):
            values[name] = period
            continue
        code = roles.get(name)
        # Ключ раскладки — ПАРА: у места своя роль и своя секция, и человек
        # встаёт в него, только если совпали обе. Место без секции (их одно —
        # ответственный за всю выездную охрану) берёт человека, у которого
        # секции тоже нет.
        key = (code, sections.get(name))
        queue = by_place.get(key, [])
        taken = used.get(key, 0)
        if code and taken < len(queue):
            values[name] = queue[taken]
            used[key] = taken + 1
        else:
            values[name] = ""
    return values


def render_placement_full(event_code, as_of=None, fmt="pdf"):
    """Байты бланка «Общая расстановка» по коду мероприятия.

    `as_of` принимается ради общей подписи реестра и НЕ используется: в
    бланке нет ни одного среза на момент — даты в нём означают период
    мероприятия целиком, а он от момента выгрузки не зависит.
    """
    event = OpsSecurityEvent.objects.filter(code=event_code).first()
    if event is None:
        raise DomainError(
            "ENTITY_NOT_FOUND",
            404,
            detail={"code": [str(event_code)]},
            message="Мероприятие не найдено.",
        )
    filled_path, left = fill_template(TEMPLATE, placement_full_values(event))
    try:
        if left:
            # Недозаполненный документ выглядит готовым и уходит наружу
            # готовым. Отказ называет ИМЕНА оставшихся мест: иначе чинить
            # будут конвейер вместо бланка.
            raise DomainError(
                "DOCUMENT_INCOMPLETE",
                500,
                detail={"placeholders": left[:20]},
                message="Бланк расстановки заполнен не полностью.",
            )
        return emit(filled_path, fmt)
    finally:
        try:
            os.unlink(filled_path)
        except OSError:
            pass


