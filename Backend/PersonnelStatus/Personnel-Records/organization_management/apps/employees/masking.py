"""Показ ИИН в списках: наружу уходит только хвост.

ИИН — персональные данные, а списку сотрудников он нужен ровно для одного:
различить однофамильцев в строке таблицы. Для этого хватает последних четырёх
цифр, поэтому полное значение из выдачи списка не уходит вовсе — маскирование
делает СЕРВЕР, а не разметка. Обратная схема (отдать 12 цифр и спрятать их
стилем) оставляет полный ИИН в теле ответа, в кэше запроса и в devtools.
"""


def mask_iin(value):
    """`'900000000001'` → `'•••••• 0001'`. Пустое и короткое — `None`.

    Короткое значение (меньше четырёх цифр) не маскируется, а скрывается
    целиком: у него нечего показывать, кроме самого себя.
    """
    if not value:
        return None
    digits = str(value).strip()
    if len(digits) < 4:
        return None
    return f"•••••• {digits[-4:]}"
