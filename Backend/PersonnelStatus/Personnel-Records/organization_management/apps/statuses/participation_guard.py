def is_participation_code(status_type) -> bool:
    """Код участия по справочнику раздела ОМ, регистр не важен."""
    from organization_management.apps.operations.status_service import (
        PARTICIPATION_STATUS_CODES,
    )

    code = str(status_type or "").strip().upper()
    return code in {c.upper() for c in PARTICIPATION_STATUS_CODES}


#: Текст отказа. 🔴 НАЗЫВАЕТ ТО МЕСТО, ГДЕ СТАТУС ДЕЙСТВИТЕЛЬНО СТАВИТСЯ
#: (уточнено ревью №825). Прежняя редакция отправляла в раздел «Сбор сил на
#: ОМ», но по решению №737 «Участие в ОМ» проставляет начальник управления и
#: делает это на ТОМ ЖЕ экране «Статусы сотрудников» — чекбоксами запроса и в
#: окне одного сотрудника. Человек уходил на другой экран искать то, что лежало
#: в соседнем окне.
REFUSAL = (
    "«Участие в ОМ» кадровой ручкой не ставится: у него свои правила раздела ОМ "
    "(мероприятие обязательно и обязано быть тем, о котором просили управление). "
    "Ставится оно на экране «Статусы сотрудников» — чекбоксами запроса сил или в "
    "окне одного сотрудника, где спрашивают мероприятие."
)


def refuse_manual_participation(status_type, *, current=None) -> None:
    """Отбить попытку ЗАВЕСТИ или СМЕНИТЬ тип на участие кадровым путём.

    `current` — тип, который стоит у строки сейчас (для правки). Совпадает с
    новым — значит тип не меняли, и трогать строку можно: закрытие и правка
    уже заведённого участия остаются доступными.
    """
    from rest_framework import serializers

    if not is_participation_code(status_type):
        return
    if current is not None and str(current).strip().upper() == str(status_type).strip().upper():
        return
    raise serializers.ValidationError(REFUSAL)
