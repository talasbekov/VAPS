"""Билдер снимка сдачи дня (порт apps/operations/submissions/services/
snapshot.py из Backend/VAPS).

Собирает для (подразделение, бизнес-дата) самодостаточный снимок
{schema_version, roster, rows, catalog, division_title}:

* roster — ЗНАМЕНАТЕЛЬ: по строке на каждого работающего обитателя штатных
  слотов подразделения, с денормализованными ФИО и званием. Сотрудник без
  единого факта остаётся здесь (он в строю) — иначе знаменатель считался бы
  по тем, у кого что-то случилось.
* rows — действующие на дату интервалы-ФАКТЫ статусов (полуинтервал
  [начало, конец), отменённые исключены), с id строки и её происхождением.
* catalog — СПРАВОЧНИК типов на момент сдачи: подпись, приоритет, колонка
  расхода и счёт в штате. Без него интервалы не превратить в числа, а
  справочник правят — и правка переписывала бы уже подписанный день.
* division_title — НАЗВАНИЕ подразделения на момент сдачи; та же заморозка
  подписи, что у ФИО и звания в составе.
* staff_total / vacancies — ЗНАМЕНАТЕЛЬ по штатным слотам на момент сдачи:
  всего единиц и сколько из них некем закрыть (свободные и занятые
  уволенными).

САМОДОСТАТОЧНОСТЬ — весь смысл: расход и светофор по сданному дню считаются
ТОЛЬКО из roster+rows, без повторного обращения к живым данным. Иначе
«сданный вчера день» менялся бы каждый раз, когда кто-то правит статус, и
подпись под сдачей ничего не значила бы.

Снимок хранит ИНТЕРВАЛЫ, а не выведенные состояния: PLANNED/ACTIVE, колонки
расхода и цвет светофора выводятся из снимка и даты на чтении. Денорм
заморожен на момент СДАЧИ (текущие ФИО/звание при построении), а не «как
было на бизнес-дату»: истории переименований старая структура не хранит, и
изображать её было бы ложью.

READ-ONLY: строк сдачи не пишет, транзакции не открывает — атомарность даёт
вызывающий сервис. Бизнес-дата — ЯВНЫЙ параметр, часы здесь не читаются
(иначе снимок за вчера тихо собрался бы на сегодня).

Свод вверх по дереву — отдельная сдача родителя, здесь только свой уровень.

Штат и вакансии снимок ХРАНИТ (с версии 6), хотя это и другая ось: обе оси
попадают в один документ и обязаны в нём сойтись. «+N» приданных при этом
остаётся живым — он ДОБАВКА сверх равенства «Штат == Список + Вне списка +
Вакансии» и его не ломает; за ним заморозки нет, и это честное ограничение,
а не недосмотр.

ОТЛИЧИЕ ОТ ИСТОЧНИКА: там знаменатель приходит из истории принадлежности
сотрудника подразделению; в старой структуре принадлежность несёт штатная
единица, и знаменатель берётся ТЕМ ЖЕ селектором, что и у расхода
(slots_with_working_occupants) — иначе у сдачи и у расхода было бы два
разных списка одного подразделения. Историчности штата у него нет (см.
strength_report), и снимок наследует это ограничение честно: статусы на
дату, слоты сегодняшние.
"""
# Версия 2 добавила к каждому человеку `position_level` — уровень его
# должности. Без него сданный день нечем упорядочить: канон порядка ведёт по
# должности, а живые данные читать нельзя (в этом весь смысл снимка). Поле
# добавлено, а не заменило что-либо, поэтому старые снимки читаются как были —
# у них уровня просто нет, и канон ставит таких людей в конец своей группы.
# Версия 3 добавила `catalog` — СПРАВОЧНИК ТИПОВ, по которому день считался.
# До неё справочник брался живым, и правка каталога переписывала уже
# подписанный день: перенос колонки уводил человека в другой столбец, снятие
# counts_in_staff меняло знаменатель, а удаление типа делало день невыводимым
# вовсе (последнее закрыто отдельно — запретом удаления). Самодостаточность
# снимка объявлена смыслом этого модуля, и справочник был последним, чего в
# ней не хватало.
#
# Поле добавлено, а не заменило что-либо: у снимков версий 1 и 2 его просто
# нет, и читатель для них берёт живой справочник — как и раньше.
# Версия 4 добавила в каждую строку каталога `name` — ПОДПИСЬ типа. Без неё
# личная копия сданного дня печатала подпись из сегодняшнего словаря, и
# переименование типа меняло уже ВЫДАННЫЙ файл: две копии одной версии
# расходились, хотя файл берут именно затем, чтобы предъявить его в споре.
# Читатели старых версий поля просто не находят и берут живые подписи.
# Версия 5 добавила `division_title` — НАЗВАНИЕ подразделения на момент сдачи.
# До неё копия сданного дня печатала название из живого справочника, и
# переименование подразделения меняло паспорт уже выданного файла: тот же день,
# та же версия, другая шапка. Довод ровно тот же, которым заморожены ФИО и
# звание в составе — истории переименований старая структура не хранит, и
# подставлять сегодняшнее имя во вчерашний документ значит выдавать его за
# бывшее тогда. Читатели старых версий поля не находят и берут живое имя.
# Версия 6 добавила `staff_total` и `vacancies` — ЗНАМЕНАТЕЛЬ дня по штатным
# слотам. До неё оба числа печатались живыми, и подписанный документ переставал
# СХОДИТЬСЯ САМ С СОБОЙ: удали кто-нибудь штатную единицу — и в документе за
# вчера штат оказывался меньше, чем список плюс вакансии. Читатель видит бумагу,
# у которой не бьётся арифметика, и объяснить её нечем.
#
# Прежний довод («штат и вакансии — другая ось, её знает расход») верен ровно до
# того, как обе оси попадают в ОДИН документ и обязаны сойтись.
#
# Оба числа считаются из тех же слотов, что и состав, — лишних запросов нет.
SCHEMA_VERSION = 6


def build_division_snapshot(division_id, business_date):
    """Собрать снимок одного подразделения на дату.

    Порядок детерминирован (roster по employee_id, rows по (employee_id,
    status_id)): по снимкам сравнивают версии сдачи, и «то же самое в другом
    порядке» выглядело бы изменением.

    JSON-безопасно: даты — строками ISO, никаких объектов модели.
    """
    # Импорты внутри функции: уровень модуля остаётся без ORM (тот же приём,
    # что и у расхода) и не образует цикла селекторы ↔ сервисы.
    from organization_management.apps.operations.selectors import (
        EmployeeSelector,
        EmployeeStatusSelector,
        StaffUnitSelector,
    )

    # Коэрции division_id здесь НЕТ намеренно: id уходит прямо в фильтр по
    # целочисленной колонке, и его приведение — работа поля. Строковый "5"
    # им понимается, мусор падает ValueError. Своя проверка была бы вторым
    # владельцем одного правила: снять её оказалось невозможно заметить
    # тестом (проверено красной пробой — сюита осталась зелёной), а
    # дублирующий гард живёт ровно до первого расхождения с настоящим.
    slots, _dismissed = StaffUnitSelector.slots_with_working_occupants([division_id])
    # Уволенный обитатель приходит из селектора как пустой слот: он не в
    # списке, и в знаменателе сдачи ему тоже не место (одно правило на расход
    # и на сдачу).
    employee_ids = [slot["employee_id"] for slot in slots if slot["employee_id"]]

    denorm = EmployeeSelector.denorm_for(employee_ids)
    roster = sorted(
        (
            {
                "employee_id": employee_id,
                "full_name": info["full_name"],
                "rank": info["rank"],
                # Уровень ЗАМОРАЖИВАЕТСЯ вместе с ФИО и званием: перевод
                # человека на другую должность не должен переставлять его в
                # уже подписанном документе.
                "position_level": info["position_level"],
            }
            for employee_id, info in denorm.items()
        ),
        key=lambda row: row["employee_id"],
    )

    # Факты сужаются ТЕМ ЖЕ множеством, что и знаменатель (denorm.keys(), а
    # не employee_ids): rows ⊆ roster тогда верно по построению, и факт не
    # может сослаться на человека, которого в знаменателе нет.
    facts = EmployeeStatusSelector.snapshot_facts_on(
        business_date, list(denorm.keys())
    )
    rows = sorted(
        (
            {
                "employee_id": fact["employee_id"],
                "status_type_code": fact["status_type_code"],
                "status_id": fact["id"],
                "date_start": fact["date_start"].isoformat(),
                "date_end": fact["date_end"].isoformat(),
                "source": fact["source"],
            }
            for fact in facts
        ),
        key=lambda row: (row["employee_id"], row["status_id"]),
    )

    # Справочник берётся ТЕМ ЖЕ селектором, что и у живого расхода: свой
    # запрос дал бы снимку каталог, отличающийся от того, по которому день
    # только что показывали на экране.
    from organization_management.apps.operations.selectors import (
        StatusTypeSelector,
    )
    from organization_management.apps.operations.strength_report import (
        StatusCatalog,
    )

    catalog = sorted(
        StatusTypeSelector.catalog_rows(), key=lambda row: row["code"]
    )
    # ПРИГОДНОСТЬ СПРАВОЧНИКА ПРОВЕРЯЕТСЯ ЗДЕСЬ, на сборке, а не на чтении.
    #
    # Пока справочник брался живым, неполный каталог чинился сам: дополнили
    # словарь — и старые дни снова печатаются. Замороженный не чинится ничем:
    # день, сданный без колонки для выводимого «в строю», остался бы
    # невыводимым НАВСЕГДА, и узналось бы об этом при первой попытке напечатать
    # документ, то есть уже после подписи.
    #
    # Поэтому отказ ставится там, где его ещё можно исправить: сдача не
    # проходит, словарь дополняют, день сдают. StatusCatalog поднимает ValueError
    # сам — здесь достаточно его позвать.
    StatusCatalog.from_rows(catalog)

    # Название берётся ТЕМ ЖЕ селектором дерева, что и у всех читателей: свой
    # запрос дал бы снимку имя, отличающееся от того, под которым день только
    # что показывали на экране. Расформированное подразделение имени не
    # отдаёт — пустая строка честнее выдуманной, и читатель подставит id.
    from organization_management.apps.operations.selectors import (
        DivisionTreeSelector,
    )

    division_title = DivisionTreeSelector.names_map([division_id]).get(
        division_id, ""
    )
    return {
        "schema_version": SCHEMA_VERSION,
        "roster": roster,
        "rows": rows,
        "catalog": catalog,
        "division_title": division_title,
        # Из ТЕХ ЖЕ слотов, что и состав: второй запрос дал бы знаменателю
        # другой момент времени, чем у списка, и они разошлись бы под
        # одновременной правкой штата.
        "staff_total": len(slots),
        "vacancies": sum(1 for slot in slots if not slot["employee_id"]),
    }
