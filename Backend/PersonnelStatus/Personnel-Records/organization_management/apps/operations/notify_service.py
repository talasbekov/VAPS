"""Отправка уведомления раздела (порт notify() из Backend/VAPS
apps/notifications/services.py).

Единственная точка записи ops_notifications — как record(...) у журнала.

Две вещи здесь неочевидны и обе намеренны.

ПЕРВАЯ: запись идёт СИНХРОННО, внутри транзакции вызывающего. Уведомление —
следствие делового факта, и жить оно должно вместе с ним: откат операции обязан
унести и уведомление о ней, иначе получатель узнаёт о том, чего не случилось.
Отложить запись «до коммита» значило бы развести их.

ВТОРАЯ: сбой отправки НЕ роняет вызывающую операцию — он пишется в журнал
процесса и глотается (возвращается None). Уведомление — побочный канал: сдача
дня принята, статус создан, и падать из-за того, что кому-то не сообщили, они
не должны. Это верно ДЛЯ ВЫЗЫВАЮЩИХ, у которых уведомление побочно; там, где
уведомление и ЕСТЬ вся операция (догон отставших), None надо превращать в
ошибку самому — иначе водяной знак уедет за день, о котором не сообщили.

Отличия от источника: WS-публикации нет — доставка отдельным срезом.
"""
import logging

from organization_management.apps.operations.models_notification import (
    OpsNotification,
)

logger = logging.getLogger(__name__)


def notify(recipient, kind, business_date, payload=None):
    """Идемпотентно сообщить `recipient` о факте `kind` за `business_date`.

    «Одно на день»: первый вызов создаёт строку с `payload`, последующие —
    холостые, и побеждает ПЕРВЫЙ payload. Так и надо: повторный вызов приходит
    из догона, который переспрашивает уже пройденные дни, — переписав payload,
    он затёр бы то, что человек уже прочитал.

    Получатель обрезается по краям: «7» и «7 » — один человек, а для ключа
    «одно на день» это две разные строки, и пробел породил бы дубликат.

    Возвращает строку (созданную или найденную) либо None, если отправка не
    удалась. Пустой получатель — ValueError, а не None: это ошибка вызывающего,
    и глотать её вместе с инфраструктурными нельзя.
    """
    if not recipient or not recipient.strip():
        raise ValueError("notify требует получателя")
    recipient = recipient.strip()
    payload = payload or {}

    try:
        notification, _created = OpsNotification.objects.get_or_create(
            recipient=recipient,
            kind=kind,
            business_date=business_date,
            defaults={"payload": payload},
        )
        return notification
    except Exception:
        # Точку сохранения от гонки двух одновременных вызовов get_or_create
        # снимает сам; всё остальное (БД недоступна, сериализация) пишется и
        # глотается, а не летит наверх в деловую операцию.
        logger.exception(
            "notify() не сработал: получатель=%r вид=%r дата=%r",
            recipient,
            kind,
            business_date,
        )
        return None
