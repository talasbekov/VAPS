"""Детерминированный отпечаток .docx (порт docx_normalize из Backend/VAPS
apps/documents/generators/).

Сравнивать печатную форму БАЙТ В БАЙТ нельзя, и это не придирка: .docx —
zip-контейнер, а zip хранит время изменения каждой записи. Два вызова генератора
на одном и том же входе дают разные байты уже потому, что прошла секунда. Плюс
`docProps/core.xml` несёт момент создания документа. Сравнение байт краснело бы
всегда — то есть не сравнивало бы ничего.

Отпечаток берётся с `word/document.xml` — того единственного места, где живёт
СОДЕРЖИМОЕ: текст, таблица, кегли. Остальное в контейнере — упаковка.

ЧТО ВЫРЕЗАЕТСЯ И ПОЧЕМУ. Атрибуты `w:rsid*` — идентификаторы сеанса
редактирования Word; к содержимому они отношения не имеют, а меняться могут от
правки шаблона. Оставь их — и обновление шаблона выглядело бы изменением
документа.

ЗАЧЕМ КАНОНИЗАЦИЯ. Один и тот же XML можно записать по-разному: порядок
атрибутов, объявления пространств имён, пустые элементы. C14N приводит запись к
единственной форме, и отпечаток начинает зависеть от СОДЕРЖАНИЯ, а не от того,
как библиотека его сериализовала в этот раз.
"""
import io
import re
import zipfile

# Идентификаторы сеанса правки Word: w:rsidR="00AB12CD" и родня.
_RSID_RE = re.compile(rb'\s+w:rsid\w+="[0-9A-Fa-f]+"')

DOCUMENT_PART = "word/document.xml"


def normalize_document_xml(docx_bytes):
    """Байты .docx → канонический XML его содержимого.

    Детерминировано (тот же вход — тот же выход) и идемпотентно по смыслу:
    повторный прогон генератора на тех же данных даёт тот же отпечаток, хотя
    байты .docx у них разные.
    """
    from lxml import etree

    with zipfile.ZipFile(io.BytesIO(docx_bytes)) as archive:
        xml = archive.read(DOCUMENT_PART)
    xml = _RSID_RE.sub(b"", xml)
    return etree.canonicalize(xml_data=xml.decode("utf-8")).encode("utf-8")
