"""Уведомление раздела ОМ (порт Notification из Backend/VAPS
apps/notifications/models.py).

ТАБЛИЦА РЯДОМ со старыми уведомлениями (ops_notifications) — тот же приём
strangler, что с журналом и статусами, и здесь он вынужденный вдвойне: у
источника таблица зовётся ровно `notifications`, а это имя в старом проекте
уже занято. Но дело не в имени:

- там получатель — FK на User, а раздел адресует СТРОКОЙ: отставание по сдаче
  адресуется ответственному, которого справочник называет по идентификатору, и
  живого пользователя за ним может не быть вовсе;
- там текст готовится при отправке (title/message/link), то есть уведомление
  хранит СЛОВА. Раздел хранит ФАКТ: вид, деловую дату и плоские данные; как
  это прочитать человеку — дело читающего экрана, и переписать формулировку
  можно не трогая историю;
- там нет и не может быть «одного на день»: у старой модели ключ — сам факт
  вставки, и повторный прогон догона (а он повторяется по построению)
  насыпал бы дубликатов на каждый повтор.

Старые уведомления и их экраны не тронуты.

Отличия от источника: int-pk; WS-публикации в этом срезе нет — доставка идёт
отдельным срезом (у старого проекта свой consumer и своя маршрутизация).
"""
from django.db import models

from organization_management.apps.operations.models import TimeStampedModel


class OpsNotification(TimeStampedModel):
    """Один факт, о котором сообщено получателю.

    Ключ «одно на день» — (получатель, вид, деловая дата) — держит БАЗА, а не
    договорённость: догон по построению переспрашивает уже пройденные дни
    (идемпотентность по водяному знаку), и без ограничения каждый повторный
    прогон превращался бы в рассылку дубликатов.

    read_at, а не is_read: «прочитано» — это МОМЕНТ, и он нужен лентам
    («что нового с моего последнего захода»). Булев флаг ответил бы только
    «да/нет» и не отличил бы прочитанное час назад от прочитанного в марте.
    """

    class Kind(models.TextChoices):
        SUBMISSION_LAGGING = "SUBMISSION_LAGGING", "Отставание по сдаче"
        # Заступление на охранное мероприятие (Plane №243). Получатели —
        # назначенные на посты И отвечающие за их подразделения: сценарий
        # заказчика требует уведомить и людей, и их руководителей.
        EVENT_ACKNOWLEDGEMENT = "EVENT_ACKNOWLEDGEMENT", "Заступление на ОМ"
        # Запрос сил управлению (Plane №392, `[СБС-22]`): ответственный
        # департамента «отправил в управления», и начальник управления
        # получает уведомление со ссылкой — выделить людей. Получатель —
        # учётка с областью ровно на это управление.
        FORCES_REQUEST = "FORCES_REQUEST", "Запрос сил управлению"
        # Возврат расстановки объекта с согласования (Plane №400, `[ВОЗ-03]`):
        # «уведомление старшему объекта и замещающим „Расстановка по объекту
        # …“ возвращена: N замечаний». Получатели — учётки старшего объекта и
        # его замещающих: чинить замечания им, и узнать о возврате они должны
        # не заглянув в карточку, а сразу.
        PLACEMENT_RETURNED = "PLACEMENT_RETURNED", "Возврат расстановки"

    # Получатель строкой: str(User.pk) для человека, метка — для роли/службы.
    recipient = models.CharField(max_length=100)
    kind = models.CharField(max_length=50, choices=Kind.choices)
    business_date = models.DateField()
    # Плоские данные факта (например, идентификаторы отставших подразделений)
    # — без ссылок в чужие таблицы: уведомление переживает удаление того, о
    # чём сообщало. Идентификаторы кладутся КАК ЕСТЬ, целыми: JSON знает целые,
    # и строка заставила бы каждого читателя разбирать её обратно (в источнике
    # UUID пришлось стрингифицировать за неимением такого типа в JSON).
    payload = models.JSONField(default=dict)
    read_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "ops_notifications"
        verbose_name = "Уведомление раздела"
        verbose_name_plural = "Уведомления раздела"
        indexes = [
            # Ленту читают «мои, свежие сверху»: (получатель, -created_at, id).
            # Левый префикс ключа «одно на день» этот разрез не обслуживает —
            # он ведёт по виду и дате, а не по времени создания.
            models.Index(
                fields=["recipient", "-created_at", "id"],
                name="idx_ops_notif_recency",
            ),
        ]
        constraints = [
            models.UniqueConstraint(
                fields=["recipient", "kind", "business_date"],
                name="uq_ops_notif_recipient_kind_date",
            ),
            # Словарь видов держит БД: choices у CharField проверяются только в
            # формах и full_clean, а раздел пишет через .create()/get_or_create()
            # — то есть мимо. Расхождение с Kind ловит отдельный тест.
            models.CheckConstraint(
                condition=models.Q(
                    kind__in=[
                        "SUBMISSION_LAGGING",
                        "EVENT_ACKNOWLEDGEMENT",
                        "FORCES_REQUEST",
                        "PLACEMENT_RETURNED",
                    ]
                ),
                name="chk_ops_notif_kind",
            ),
            # Пустой получатель означал бы «сообщено никому», и «одно на день»
            # на пустой строке как раз выполняется: все безадресные уведомления
            # схлопнулись бы в одну строку.
            models.CheckConstraint(
                condition=~models.Q(recipient__regex=r"^\s*$"),
                name="chk_ops_notif_recipient",
            ),
        ]

    def __str__(self):
        return f"{self.kind} → {self.recipient} ({self.business_date})"
