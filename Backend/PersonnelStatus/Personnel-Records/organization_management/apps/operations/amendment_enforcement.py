"""Принуждение к поправке: ретро-правка накрытого сданного дня ОБЯЗАНА
породить поправку (порт submissions/amendment_enforcement.py из Backend/VAPS).

Инвариант один и он несущий: сданный день заявляет расход, и правка статуса
задним числом делает заявление неверным. Либо расход перестаёт соответствовать
данным — и тогда у одного дня две правды, — либо правку запрещают вовсе.
Раздел выбирает третье: правка проходит, но ОБЯЗАНА вытеснить сданное новой
версией. Поправка здесь не наказание и не согласование, а способ сохранить
единственность правды.

Поправка ставится АВТОМАТИЧЕСКИ, а не требуется от оператора отдельным
действием: забытая поправка неотличима от честной сдачи, и обнаружилась бы
она у того, кто читает расход, а не у того, кто правил.

ЗАТРОНУТЫЕ ДНИ — ОБЪЕДИНЕНИЕ полуинтервалов, не их габарит. Правка, разнесённая
на два непересекающихся периода, габаритом накрыла бы дни в промежутке между
ними — и день, о котором никто ничего не менял, вышел бы поправленным с
чужой санкцией. Верхняя граница исключена: полуинтервал [начало, конец) везде
в разделе значит одно и то же.

ПРИЧИНА ТРЕБУЕТСЯ УСЛОВНО — ровно тогда, когда правка задела сданное.
Санкцию раздел не выдумывает: у поправки обязано стоять объяснение, ЧТО и
почему изменили, а сгенерированный текст объяснял бы только то, что кто-то
что-то поправил. Требовать причину на каждой правке было бы другой крайностью:
подавляющее большинство правок ничего сданного не задевает, и обязательное
поле там научило бы операторов писать «правка» в каждое.

ЧИСТОГО МОДУЛЯ ЗДЕСЬ НЕТ намеренно: обнаружение — это запрос к сданному, и
разносить «какие дни» и «какие из них сданы» по разным модулям значило бы
завести владельца, который знает половину ответа. Часы не читаются: дни
приходят интервалами правки.

ОДНА ПОПРАВКА НА ДЕНЬ, а не на правку: массовое обновление, задевшее двадцать
человек одного дня, вытесняет его сдачу ОДИН раз. Поштучный подсчёт породил бы
версии 2, 3, 4… на один акт, и читатель истории дня увидел бы двадцать
поправок там, где было одно обновление.

У СИСТЕМНЫХ ПУТЕЙ ПРИЧИНА ВЫВОДИТСЯ, а не спрашивается. Разница с оператором
не в строгости, а в том, кто знает событие: оператор один знает, ЧТО он
изменил, и текст приходится требовать; увольнение же известно целиком —
человек и дата, — и санкция складывается из него. Спрашивать причину у
сигнала было бы некого, а пропускать поправку — оставлять сданный день
заявлять человека, которого в нём уже нет.

ВЛАДЕЛЕЦ ПОПРАВКИ — ОПЕРАЦИЯ, А НЕ СТРОКА. У одного акта одна поправка,
сколько бы строк он ни записал: пара прикомандирования пишет две ноги,
возврат закрывает обе, пачка задевает десятки — день получает ОДНУ новую
версию. Поэтому оркестраторы (secondment_service) забирают поправку себе, а
низкоуровневый путь зовётся с `amend=False`: иначе день получил бы версии 2 и
3 за одно решение, и читатель истории увидел бы два возврата вместо одного.

Шов стоит на всех путях записи раздела. Единственное исключение —
`update_status` по метаданным (комментарий, основание): расхода они не
меняют, и поправка из-за них была бы ни о чём.

ОТЛИЧИЕ ОТ ИСТОЧНИКА — прямой вызов вместо слота-инверсии. Там statuses и
submissions разные приложения, стрелка между ними односторонняя, и обращение
наверх приходилось разворачивать поздним связыванием через
`register_amendment_handler`. Здесь раздел один пакет, цикла импортов нет
(сдача не знает о правке статусов), и слот был бы церемонией без адресата.
"""
from datetime import timedelta

from organization_management.apps.operations.day_submission_service import amend_day
from organization_management.apps.operations.exceptions import DomainError
from organization_management.apps.operations.selectors import DailySubmissionSelector

# Санкцией едет причина САМОЙ правки: она объясняет, что и почему изменили, а
# строка ниже — лишь как поправка появилась. Поменять их местами значило бы
# записать в объяснение дня служебный текст, одинаковый у всех поправок.
AUTO_AMENDMENT_REASON = "Авто-поправка: ретро-правка статуса под сданным днём."


def affected_days(intervals):
    """Дни, накрытые полуинтервалами [начало, конец), — объединением.

    Пустой и вывернутый интервал не дают ни одного дня: у них нет ни одного
    дня внутри, и трактовать их как «весь диапазон» было бы догадкой.
    """
    days = set()
    for date_start, date_end in intervals:
        day = date_start
        while day < date_end:
            days.add(day)
            day += timedelta(days=1)
    return days


def enforce_amendment_on_bulk_edit(
    employee_ids, intervals, *, actor, reason, triggered_by_status_id=None
):
    """Поправить каждый сданный день, накрытый правкой сразу по многим людям.

    Отличается от поштучного входа только тем, кем задан периметр людей;
    правило «одна поправка на накрытый день» общее, и владелец обоих — этот
    модуль. `triggered_by_status_id` у пачки обычно None: одной строки,
    вызвавшей поправку, у неё нет, а pk первой был бы враньём — поле
    допускает пустоту именно для таких случаев.
    """
    covered = DailySubmissionSelector.covering_many(
        employee_ids, affected_days(intervals)
    )
    return _amend_covered(
        covered,
        actor=actor,
        reason=reason,
        triggered_by_status_id=triggered_by_status_id,
    )


def enforce_amendment_on_retro_edit(
    employee_id, intervals, *, actor, reason, triggered_by_status_id=None
):
    """Поправить каждый сданный день, накрытый ретро-правкой.

    Вызывается ВНУТРИ транзакции правки: поправка обязана лечь тем же
    коммитом, что и сама правка. Иначе между ними существует момент, в
    котором сданный день уже не соответствует данным, а объяснения этому
    ещё нет, — и любой сбой на этом промежутке оставляет расхождение
    навсегда.

    Пустая причина отвергается ТОЛЬКО когда сданные дни действительно
    накрыты: обнаружение идёт первым, и правка, никого не задевшая, проходит
    без объяснений.

    Возвращает список созданных поправок — по одной на накрытый день; пустой,
    когда правка сданного не задела.
    """
    covered = DailySubmissionSelector.covering(employee_id, affected_days(intervals))
    return _amend_covered(
        covered,
        actor=actor,
        reason=reason,
        triggered_by_status_id=triggered_by_status_id,
    )


def _amend_covered(covered, *, actor, reason, triggered_by_status_id):
    """Общий хвост обоих входов: требование причины и сами поправки."""
    if not covered:
        return []
    if not (reason or "").strip():
        raise DomainError(
            "AMENDMENT_REASON_REQUIRED",
            422,
            detail={
                "business_dates": [
                    submission.business_date.isoformat() for submission in covered
                ]
            },
            message="Правка задевает сданные дни: нужна причина для поправки.",
        )
    return [
        amend_day(
            division_id=submission.division_id,
            business_date=submission.business_date,
            actor=actor,
            reason=AUTO_AMENDMENT_REASON,
            sanction=reason,
            triggered_by_status_id=triggered_by_status_id,
        )
        for submission in covered
    ]
