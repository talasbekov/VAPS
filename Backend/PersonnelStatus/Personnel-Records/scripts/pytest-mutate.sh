#!/usr/bin/env bash
# Мутационная проверка пробы — ВНУТРИ замка тестовой базы (Plane №811).
#
# ЗАЧЕМ. Правило проекта «новый тест — красная проба» проверяется так: сломать
# правку, убедиться, что проба краснеет, восстановить. Естественно это пишется
# тремя шагами подряд — правка файла, `scripts/pytest-lock.sh … pytest`,
# восстановление, — и в этой форме СЛОМАННЫЙ ФАЙЛ ЛЕЖИТ В ОБЩЕМ ДЕРЕВЕ ВСЁ
# ВРЕМЯ ОЖИДАНИЯ ОЧЕРЕДИ. Сосед гонит полный прогон семь минут — семь минут в
# дереве заведомо сломанный код, и любой, кто в это окно запустит свой pytest,
# получит красноту неизвестного происхождения и пойдёт искать дефект у себя.
# За 05.09.2026 такое случилось в обе стороны не раз.
#
# Порча обязана жить ровно столько, сколько идёт проверка. Поэтому скрипт
# сначала БЕРЁТ ЗАМОК и только потом ломает файл: ожидание очереди проходит на
# целом дереве.
#
# ЧТО СЧИТАЕТСЯ УСПЕХОМ — ИМЕННО КРАСНАЯ ПРОБА. Код возврата 0 означает
# «мутация поймана»; зелёная проба на сломанном коде — это отказ (код 1), и
# сказано это словами, а не оставлено читателю вывода pytest. Раньше исход
# читали глазами, и «1 failed» в конце длинной простыни легко принять за беду,
# а не за доказательство.
#
# БАЗОВЫЙ ПРОГОН ОБЯЗАТЕЛЕН И ИДЁТ ПЕРВЫМ. «Проба краснеет на мутации» ничего
# не доказывает, если она красная и без мутации (чужая незакоммиченная правка,
# сломанная фикстура, неверный `-k`). Оба прогона — под одним замком: разводить
# их значило бы снова ждать очередь дважды.
#
# ИСПОЛЬЗОВАНИЕ
#   bash scripts/pytest-mutate.sh \
#       --file organization_management/apps/ops/my_assignments.py \
#       --old 'a.get("viewedAt") is None' --new 'True' \
#       -- organization_management/apps/ops/tests/test_ops_my_assignments.py -q
#
#   Тройка `--file/--old/--new` повторяется, если мутация нужна в нескольких
#   местах или файлах; порядок замен — как перечислены.
#   Ждать очереди: PYTEST_LOCK_WAIT=900 bash scripts/pytest-mutate.sh …
#   Другой интерпретатор: PYTEST=".venv/bin/python -m pytest" (по умолчанию он же).
#
# ⚠️ НЕ ЗВАТЬ ИЗНУТРИ ПРОГОНА, КОТОРЫЙ УЖЕ ДЕРЖИТ ЗАМОК. Скрипт берёт замок
# сам, а замок не рекурсивный: из теста, запущенного под `pytest-lock.sh`, он
# отобьётся кодом 75 «база занята» — причём занята будет им же самим. Поэтому
# проверять им пробу надо ИЗ КОНСОЛИ, а не из другой пробы; собственные его
# исходы (мутация поймана / проба зелена / нет строки / базовый красный)
# проверены запуском вручную и записаны в `Changelog.md` за 06.09.2026.
set -u

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"

# Второй заход — уже под замком. Разделение нужно затем, что первый заход не
# имеет права трогать файлы: он ЖДЁТ.
if [ "${PYTEST_MUTATE_LOCKED:-}" != "1" ]; then
  PYTEST_MUTATE_LOCKED=1 exec bash "$HERE/pytest-lock.sh" bash "${BASH_SOURCE[0]}" "$@"
fi
# 🔴 ФЛАГ СНИМАЕТСЯ СРАЗУ (найдено ревью, задача №825). Он экспортирован, а
# значит наследуется pytest и всем, что под ним: вложенный вызов этого скрипта
# увидел бы «уже под замком», ПРОПУСТИЛ взятие замка и начал портить файлы без
# него — ровно тот дефект, ради которого карточка и заведена. То же было бы,
# случись переменной остаться в оболочке человека после отладки.
unset PYTEST_MUTATE_LOCKED

FILES=(); OLDS=(); NEWS=(); PYTEST_ARGS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --file) FILES+=("$2"); shift 2 ;;
    --old)  OLDS+=("$2");  shift 2 ;;
    --new)  NEWS+=("$2");  shift 2 ;;
    --) shift; PYTEST_ARGS=("$@"); break ;;
    *) echo "[мутация] непонятный аргумент: $1" >&2; exit 2 ;;
  esac
done

if [ "${#FILES[@]}" -eq 0 ] || [ "${#PYTEST_ARGS[@]}" -eq 0 ]; then
  echo "[мутация] нужны --file/--old/--new и аргументы pytest после --" >&2
  exit 2
fi
if [ "${#OLDS[@]}" -ne "${#FILES[@]}" ] || [ "${#NEWS[@]}" -ne "${#FILES[@]}" ]; then
  echo "[мутация] --file, --old и --new должны идти тройками (сейчас ${#FILES[@]}/${#OLDS[@]}/${#NEWS[@]})" >&2
  exit 2
fi

cd "$ROOT" || exit 2
PYTEST_CMD="${PYTEST:-.venv/bin/python -m pytest}"

# Копии — рядом с файлом и с уникальным суффиксом: два таких прогона в одном
# дереве не должны затирать копии друг друга. Восстановление стоит в `trap`,
# поэтому переживает и падение pytest, и Ctrl-C, и убитую задачу.
BACKUPS=()
restore() {
  local i
  for i in "${!BACKUPS[@]}"; do
    if [ -f "${BACKUPS[$i]}" ]; then
      mv -f "${BACKUPS[$i]}" "${FILES[$i]}"
      echo "[мутация] восстановлен ${FILES[$i]}"
    elif [ -n "${BACKUPS[$i]}" ]; then
      # Молча пропустить нельзя: это значит, что в общем дереве остался
      # заведомо сломанный файл, и никто об этом не узнает.
      echo "🔴 КОПИИ НЕТ: ${BACKUPS[$i]} — ${FILES[$i]} мог остаться сломанным, проверьте руками" >&2
    fi
  done
}
# 🔴 СИГНАЛЫ ДОЛЖНЫ ЗАВЕРШАТЬ (найдено ревью, задача №825, воспроизведено).
# Обработчик `INT`/`TERM`, который не выходит сам, ВОЗВРАЩАЕТ управление
# следующей строке: Ctrl-C на прогоне с мутацией уводил pytest в ненулевой код,
# `if` не срабатывал, и скрипт печатал «✅ мутация поймана» с кодом 0. Прерванная
# проверка была неотличима от пройденной — в проекте, где видимый вывод и ЕСТЬ
# доказательство. `HUP` добавлен отдельно: закрытая вкладка или оборванный ssh
# по умолчанию убивают процесс БЕЗ выполнения `EXIT`, и файл остался бы
# сломанным (тот же случай, что описан в CLAUDE.md про резко убитого сторожа).
trap restore EXIT
trap 'restore; echo "🔴 ПРЕРВАНО СИГНАЛОМ — проверка НЕ состоялась" >&2; exit 130' INT
trap 'restore; echo "🔴 ПРЕРВАНО СИГНАЛОМ — проверка НЕ состоялась" >&2; exit 143' TERM HUP

# 🔴 ПОДБОР СИРОТ: копия, оставшаяся от УМЕРШЕГО прогона, значит сломанный файл
# в общем дереве. Тот же приём, что у замка (`pytest-lock.sh`): владелец
# проверяется через `kill -0`, а не «протух ли по сроку».
while IFS= read -r orphan; do
  [ -n "$orphan" ] || continue
  owner="${orphan##*.}"
  case "$owner" in (*[!0-9]*|"") continue ;; esac
  if kill -0 "$owner" 2>/dev/null; then continue; fi
  victim="${orphan%.mutate-backup.*}"
  mv -f "$orphan" "$victim"
  echo "🔴 подобрана копия мёртвого прогона (pid $owner): $victim восстановлен" >&2
done < <(find "$ROOT" -name '*.mutate-backup.*' -type f 2>/dev/null)

echo "── базовый прогон (без мутации) ───────────────────────────────────────"
if ! $PYTEST_CMD "${PYTEST_ARGS[@]}"; then
  echo
  echo "🔴 БАЗОВЫЙ ПРОГОН КРАСНЫЙ — мутацию проверять нечем." >&2
  echo "   Проба красная и без мутации: чужая незакоммиченная правка в дереве," >&2
  echo "   сломанная фикстура или неверный отбор (-k / путь). Чините это." >&2
  exit 1
fi

echo
echo "── вношу мутацию ──────────────────────────────────────────────────────"
for i in "${!FILES[@]}"; do
  target="${FILES[$i]}"
  if [ ! -f "$target" ]; then
    echo "[мутация] нет файла: $target" >&2
    exit 2
  fi
  if [ -L "$target" ]; then
    # Восстановление идёт через `mv`, а он ЗАМЕНИЛ БЫ саму ссылку обычным
    # файлом: ссылка исчезла бы, а настоящий файл остался бы сломанным.
    echo "[мутация] $target — символическая ссылка, отказываюсь" >&2
    exit 2
  fi
  backup="${target}.mutate-backup.$$"
  # 🔴 НЕУДАВШАЯСЯ КОПИЯ — ОТКАЗ, А НЕ «ПОЙДЁМ ДАЛЬШЕ» (найдено ревью, №825).
  # Без проверки скрипт записывал путь несуществующей копии, ломал файл и
  # тихо не восстанавливал его: заведомо сломанный файл оставался в дереве,
  # которое делят пять сессий, и без единого сообщения.
  if ! cp -p "$target" "$backup"; then
    echo "🔴 не удалось сделать копию $target → $backup: файл НЕ трогаю" >&2
    exit 2
  fi
  BACKUPS[$i]="$backup"
  echo "[мутация] копия: $backup"
  # Замена одна и ровно первая: `replace(..., 1)`. Отсутствие искомой строки —
  # ОТКАЗ, а не «ничего не заменилось»: молчаливый пропуск дал бы зелёный
  # прогон неизменённого кода, то есть ровно тот вывод «проба не стережёт»,
  # которого мы боимся, — но ложный.
  OLD="${OLDS[$i]}" NEW="${NEWS[$i]}" TARGET="$target" python3 - <<'PY' || exit 1
import io, os, sys
target, old, new = os.environ["TARGET"], os.environ["OLD"], os.environ["NEW"]
text = io.open(target, encoding="utf-8").read()
if old not in text:
    sys.stderr.write(f"[мутация] в {target} нет строки для замены:\n  {old}\n")
    sys.exit(1)
# 🔴 НЕОДНОЗНАЧНАЯ СТРОКА — ОТКАЗ (найдено ревью, задача №825). Заменялось
# ПЕРВОЕ вхождение; если строка встречается трижды, а проба стережёт третье,
# скрипт ломал первое — возможно, в мёртвом коде, — проба оставалась зелёной,
# и он печатал «проба не стережёт эту мутацию». Ложное обвинение хорошему
# тесту, причём причина невидима.
count = text.count(old)
if count > 1:
    sys.stderr.write(
        f"[мутация] в {target} строка встречается {count} раза — какое вхождение ломать, "
        f"непонятно. Удлините --old до однозначного:\n  {old}\n"
    )
    sys.exit(1)
io.open(target, "w", encoding="utf-8").write(text.replace(old, new, 1))
print(f"[мутация] {target}: заменено 1 вхождение")
PY
done

echo
echo "── прогон на мутации ──────────────────────────────────────────────────"
MUTATED_LOG="$(mktemp -t pytest-mutate.XXXXXX.log)"
set +e
$PYTEST_CMD "${PYTEST_ARGS[@]}" 2>&1 | tee "$MUTATED_LOG"
MUTATED_RC="${PIPESTATUS[0]}"
set -e
echo "[мутация] pytest вернул $MUTATED_RC"

# 🔴 «КРАСНАЯ» ПО ПОСТОРОННЕЙ ПРИЧИНЕ — НЕ ДОКАЗАТЕЛЬСТВО (найдено ревью,
# задача №825, и уточнено ЗАМЕРОМ). Ревью предлагало различать коды возврата,
# но замер показал, что этого мало: мутация, сделавшая файл неразбираемым,
# даёт код 1, а не 2, — импорт в этом коде идёт ВНУТРИ функции, и pytest
# считает такое обычным падением («4 failed»). Скрипт печатал «✅ мутация
# поймана», хотя проба покраснела не оттого, что стережёт поведение, а оттого,
# что код перестал разбираться. Поэтому смотрим не только код, но и ПРИЧИНУ.
if grep -qE "SyntaxError|IndentationError|ModuleNotFoundError|ImportError|INTERNALERROR" "$MUTATED_LOG"; then
  echo
  echo "🔴 МУТАЦИЯ СЛОМАЛА КОД, А НЕ ПОВЕДЕНИЕ — проверка НЕ состоялась." >&2
  echo "   В выводе SyntaxError/ImportError: проба покраснела оттого, что файл" >&2
  echo "   перестал разбираться или импортироваться, а не оттого, что стережёт" >&2
  echo "   эту мутацию. Мутация обязана быть ОСМЫСЛЕННОЙ правкой поведения." >&2
  rm -f "$MUTATED_LOG"
  exit 1
fi
if grep -qE "^[0-9]+ error(s)? in |, [0-9]+ error(s)? in " "$MUTATED_LOG"; then
  echo
  echo "🔴 pytest сообщил ОШИБКИ сбора, а не падения проб — проверка НЕ состоялась." >&2
  rm -f "$MUTATED_LOG"
  exit 1
fi
rm -f "$MUTATED_LOG"
# 🔴 ТОЛЬКО КОД 1 ЗНАЧИТ «ПРОБА ПОКРАСНЕЛА» (найдено ревью, задача №825).
# У pytest 0 — прошло, 1 — тесты упали, 2 — прервано или ошибка сбора, 3 —
# внутренняя ошибка, 4 — ошибка вызова, 5 — не собрано ничего. Мутация,
# давшая SyntaxError или сломавшая импорт, кладёт ВЕСЬ модуль на сборке (код 2)
# — это не доказывает, что ЭТА проба стережёт ЭТО поведение, а скрипт печатал
# «✅».
if [ "$MUTATED_RC" -eq 0 ]; then
  echo
  echo "🔴 ПРОБА ОСТАЛАСЬ ЗЕЛЁНОЙ НА СЛОМАННОМ КОДЕ — она не стережёт эту мутацию." >&2
  echo "   Это отказ: проба ничего не проверяет. Причины из разбора №810/№605:" >&2
  echo "   подменённый ответ структурно равен исходному (React Query отдаёт" >&2
  echo "   прежний объект); проба пишет до чтения и лечит стор; отбор не" >&2
  echo "   проходит через изменённый код; пин на строку вместо замера." >&2
  exit 1
fi
if [ "$MUTATED_RC" -ne 1 ]; then
  echo
  echo "🔴 pytest упал по ПОСТОРОННЕМУ поводу (код $MUTATED_RC) — проверка НЕ состоялась." >&2
  echo "   Код 2 — прервано или ошибка сбора (мутация сломала импорт?), 3 —" >&2
  echo "   внутренняя ошибка, 4 — ошибка вызова, 5 — не собрано ничего." >&2
  exit 1
fi

echo
echo "✅ мутация поймана: проба покраснела (pytest вернул 1). Восстановление — строками выше."
exit 0
