#!/usr/bin/env bash
# Мутационная проверка пробы — ВНУТРИ замка тестовой базы (Plane №811).
#
# ЗАЧЕМ. Правило проекта «новый тест — красная проба» проверяется так: сломать
# правку, убедиться, что проба краснеет, восстановить. Естественно это пишется
# тремя шагами подряд — правка файла, `scripts/pytest-lock.sh … pytest`,
# восстановление, — и в этой форме СЛОМАННЫЙ ФАЙЛ ЛЕЖИТ В ОБЩЕМ ДЕРЕВЕ ВСЁ
# ВРЕМЯ ОЖИДАНИЯ ОЧЕРЕДИ. Сосед гонит полный прогон семь минут — семь минут в
# дереве заведомо сломанный код, и любой, кто в это окно запустит свой pytest,
# получит красноту неизвестного происхождения и пойдёт искать дефект у себя.
# За 05.09.2026 такое случилось в обе стороны не раз.
#
# Порча обязана жить ровно столько, сколько идёт проверка. Поэтому скрипт
# сначала БЕРЁТ ЗАМОК и только потом ломает файл: ожидание очереди проходит на
# целом дереве.
#
# ЧТО СЧИТАЕТСЯ УСПЕХОМ — ИМЕННО КРАСНАЯ ПРОБА. Код возврата 0 означает
# «мутация поймана»; зелёная проба на сломанном коде — это отказ (код 1), и
# сказано это словами, а не оставлено читателю вывода pytest. Раньше исход
# читали глазами, и «1 failed» в конце длинной простыни легко принять за беду,
# а не за доказательство.
#
# БАЗОВЫЙ ПРОГОН ОБЯЗАТЕЛЕН И ИДЁТ ПЕРВЫМ. «Проба краснеет на мутации» ничего
# не доказывает, если она красная и без мутации (чужая незакоммиченная правка,
# сломанная фикстура, неверный `-k`). Оба прогона — под одним замком: разводить
# их значило бы снова ждать очередь дважды.
#
# ИСПОЛЬЗОВАНИЕ
#   bash scripts/pytest-mutate.sh \
#       --file organization_management/apps/ops/my_assignments.py \
#       --old 'a.get("viewedAt") is None' --new 'True' \
#       -- organization_management/apps/ops/tests/test_ops_my_assignments.py -q
#
#   Тройка `--file/--old/--new` повторяется, если мутация нужна в нескольких
#   местах или файлах; порядок замен — как перечислены.
#   Ждать очереди: PYTEST_LOCK_WAIT=900 bash scripts/pytest-mutate.sh …
#   Другой интерпретатор: PYTEST=".venv/bin/python -m pytest" (по умолчанию он же).
#
# ⚠️ НЕ ЗВАТЬ ИЗНУТРИ ПРОГОНА, КОТОРЫЙ УЖЕ ДЕРЖИТ ЗАМОК. Скрипт берёт замок
# сам, а замок не рекурсивный: из теста, запущенного под `pytest-lock.sh`, он
# отобьётся кодом 75 «база занята» — причём занята будет им же самим. Поэтому
# проверять им пробу надо ИЗ КОНСОЛИ, а не из другой пробы; собственные его
# исходы (мутация поймана / проба зелена / нет строки / базовый красный)
# проверены запуском вручную и записаны в `Changelog.md` за 06.09.2026.
set -u

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"

# Второй заход — уже под замком. Разделение нужно затем, что первый заход не
# имеет права трогать файлы: он ЖДЁТ.
if [ "${PYTEST_MUTATE_LOCKED:-}" != "1" ]; then
  PYTEST_MUTATE_LOCKED=1 exec bash "$HERE/pytest-lock.sh" bash "${BASH_SOURCE[0]}" "$@"
fi

FILES=(); OLDS=(); NEWS=(); PYTEST_ARGS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --file) FILES+=("$2"); shift 2 ;;
    --old)  OLDS+=("$2");  shift 2 ;;
    --new)  NEWS+=("$2");  shift 2 ;;
    --) shift; PYTEST_ARGS=("$@"); break ;;
    *) echo "[мутация] непонятный аргумент: $1" >&2; exit 2 ;;
  esac
done

if [ "${#FILES[@]}" -eq 0 ] || [ "${#PYTEST_ARGS[@]}" -eq 0 ]; then
  echo "[мутация] нужны --file/--old/--new и аргументы pytest после --" >&2
  exit 2
fi
if [ "${#OLDS[@]}" -ne "${#FILES[@]}" ] || [ "${#NEWS[@]}" -ne "${#FILES[@]}" ]; then
  echo "[мутация] --file, --old и --new должны идти тройками (сейчас ${#FILES[@]}/${#OLDS[@]}/${#NEWS[@]})" >&2
  exit 2
fi

cd "$ROOT" || exit 2
PYTEST_CMD="${PYTEST:-.venv/bin/python -m pytest}"

# Копии — рядом с файлом и с уникальным суффиксом: два таких прогона в одном
# дереве не должны затирать копии друг друга. Восстановление стоит в `trap`,
# поэтому переживает и падение pytest, и Ctrl-C, и убитую задачу.
BACKUPS=()
restore() {
  local i
  for i in "${!BACKUPS[@]}"; do
    [ -f "${BACKUPS[$i]}" ] && mv -f "${BACKUPS[$i]}" "${FILES[$i]}"
  done
}
trap restore EXIT INT TERM

echo "── базовый прогон (без мутации) ───────────────────────────────────────"
if ! $PYTEST_CMD "${PYTEST_ARGS[@]}"; then
  echo
  echo "🔴 БАЗОВЫЙ ПРОГОН КРАСНЫЙ — мутацию проверять нечем." >&2
  echo "   Проба красная и без мутации: чужая незакоммиченная правка в дереве," >&2
  echo "   сломанная фикстура или неверный отбор (-k / путь). Чините это." >&2
  exit 1
fi

echo
echo "── вношу мутацию ──────────────────────────────────────────────────────"
for i in "${!FILES[@]}"; do
  target="${FILES[$i]}"
  if [ ! -f "$target" ]; then
    echo "[мутация] нет файла: $target" >&2
    exit 2
  fi
  backup="${target}.mutate-backup.$$"
  cp -p "$target" "$backup"
  BACKUPS[$i]="$backup"
  # Замена одна и ровно первая: `replace(..., 1)`. Отсутствие искомой строки —
  # ОТКАЗ, а не «ничего не заменилось»: молчаливый пропуск дал бы зелёный
  # прогон неизменённого кода, то есть ровно тот вывод «проба не стережёт»,
  # которого мы боимся, — но ложный.
  OLD="${OLDS[$i]}" NEW="${NEWS[$i]}" TARGET="$target" python3 - <<'PY' || exit 1
import io, os, sys
target, old, new = os.environ["TARGET"], os.environ["OLD"], os.environ["NEW"]
text = io.open(target, encoding="utf-8").read()
if old not in text:
    sys.stderr.write(f"[мутация] в {target} нет строки для замены:\n  {old}\n")
    sys.exit(1)
io.open(target, "w", encoding="utf-8").write(text.replace(old, new, 1))
print(f"[мутация] {target}: заменено 1 вхождение")
PY
done

echo
echo "── прогон на мутации ──────────────────────────────────────────────────"
if $PYTEST_CMD "${PYTEST_ARGS[@]}"; then
  echo
  echo "🔴 ПРОБА ОСТАЛАСЬ ЗЕЛЁНОЙ НА СЛОМАННОМ КОДЕ — она не стережёт эту мутацию." >&2
  echo "   Это отказ: проба ничего не проверяет. Причины из разбора №810/№605:" >&2
  echo "   подменённый ответ структурно равен исходному (React Query отдаёт" >&2
  echo "   прежний объект); проба пишет до чтения и лечит стор; отбор не" >&2
  echo "   проходит через изменённый код; пин на строку вместо замера." >&2
  exit 1
fi

echo
echo "✅ мутация поймана: проба покраснела. Файлы восстановлены из копий."
exit 0
