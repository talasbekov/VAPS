/**
 * Адрес раздела ОМ ищется В СТРОКОВЫХ ЛИТЕРАЛАХ, а не в тексте файла.
 *
 * 🔴 ПОЧЕМУ НЕ «СНЯТЬ КОММЕНТАРИИ РЕГУЛЯРКОЙ», как было в первых двух
 * редакциях (найдено ревью, Plane №873). Снятие блочных комментариев проходом
 * `/\*[\s\S]*?\*\//g` считает началом комментария ЛЮБОЕ `/*` — а оно
 * встречается и внутри строк. В `lib/api.ts:1815` стоит HTTP-заголовок
 * `accept: "*\/*"`, и его `/*` открывало псевдо-блок до ближайшего настоящего
 * `*\/` двумя сотнями строк ниже.
 *
 * ЗАМЕР: из `lib/api.ts` при такой очистке выпадало 400 строк — то есть
 * сторож слеп ровно на том файле, ради которого написан. Проверено вставкой
 * одной и той же строки: на строке 100 сторож краснеет, на строке 1900 —
 * зелёный.
 *
 * Порядок проходов тут не спасает вовсе: строковый литерал с `//` или `/*`
 * внутри ломает любой. Поэтому исходник РАЗБИРАЕТСЯ ПО СОСТОЯНИЯМ — код,
 * строчный комментарий, блочный комментарий, строковый литерал, — и вопрос
 * задаётся правильный: «адрес лежит в строке КОДА или это текст ПРО адрес».
 * Докстрока с примером в разбор не попадает сама собой, без отдельной очистки.
 */
/**
 * Начинается ли в позиции `at` регулярный литерал, а не деление (Plane №918).
 *
 * Смотрит НАЗАД на ближайший значащий символ: после значения (`)`, `]`, имя,
 * число) слэш — деление; после оператора, открывающей скобки или ключевого
 * слова — начало регулярки. Пробелы и переводы строк пропускаются.
 *
 * Точного ответа без разбора выражений не бывает, и обещать его нельзя: это
 * эвристика, принятая в разборщиках, а не правило языка.
 */
function startsRegex(source: string, at: number): boolean {
  // 🔴 JSX — НЕ РЕГУЛЯРКА (ревью №825 по №918, 08.09.2026): `</p>` и
  // `<br/>` — теги; `<` стоит в списке операторов ниже, и без этой строки
  // слэш закрывающего тега открывал «регулярку» до следующего слэша через
  // переводы строк — сторож терял ~13 % литералов дерева.
  if (source[at - 1] === '<' || source[at + 1] === '>') return false
  let i = at - 1
  while (i >= 0 && /\s/.test(source[i] as string)) i -= 1
  if (i < 0) return true
  const prev = source[i] as string
  if ('([{,;=:!&|?+-*%<>~^}'.includes(prev)) return true
  const word = source.slice(Math.max(0, i - 9), i + 1).match(/[A-Za-z_$]+$/)
  if (word === null) return false
  const wordStart = i + 1 - word[0].length
  // `value2of` must not be shortened to the keyword `of`.
  if (wordStart > 0 && /[A-Za-z0-9_$]/.test(source[wordStart - 1] as string)) return false
  return ['return', 'case', 'typeof', 'in', 'of', 'new', 'delete', 'void'].includes(word[0])
}

function stringLiterals(source: string): string[] {
  const found: string[] = []
  let i = 0
  while (i < source.length) {
    const ch = source[i]
    const next = source[i + 1]
    if (ch === '/' && next === '/') {
      while (i < source.length && source[i] !== '\n') i += 1
      continue
    }
    if (ch === '/' && next === '*') {
      i += 2
      while (i < source.length && !(source[i] === '*' && source[i + 1] === '/')) i += 1
      i += 2
      continue
    }
    // 🔴 РЕГУЛЯРНЫЙ ЛИТЕРАЛ — НЕ КОД И НЕ СТРОКА (Plane №918). Автомат его не
    // знал, и опасность тут не в пропуске адреса ВНУТРИ регулярки, а в том,
    // что регулярка с кавычкой (`/["']/`, `/[^']+/`) открывала псевдо-строку:
    // разбор «съедал» код до следующей такой же кавычки и мог пройти мимо
    // настоящего нарушения НИЖЕ. Ровно та же болезнь, что была со снятием
    // блочных комментариев (№873), только с другого конца.
    //
    // Отличить деление от регулярки без разбора выражений нельзя, поэтому
    // применяется общепринятая эвристика: `/` начинает регулярку, если
    // предыдущий значащий символ — открывающий или операторный
    // (`( , = : [ ! & | ? { ; + - * % < > ~ ^`), либо это начало файла,
    // либо перед ним слово `return`/`case`/`typeof`/`in`/`of`. После значения
    // (`)`, `]`, имени, числа) `/` — это деление.
    if (ch === '/' && startsRegex(source, i)) {
      i += 1
      // Регулярный литерал не переживает перевода строки: дошли до `\n` —
      // это был не литерал (деление, JSX), разбор идёт дальше как по коду.
      while (i < source.length && source[i] !== '/' && source[i] !== '\n') {
        if (source[i] === '\\') {
          i += 2
          continue
        }
        // Класс символов: `/` внутри `[...]` регулярку НЕ закрывает.
        if (source[i] === '[') {
          i += 1
          while (i < source.length && source[i] !== ']') {
            if (source[i] === '\\') i += 1
            i += 1
          }
        }
        i += 1
      }
      i += 1
      continue
    }
    if (ch === '"' || ch === "'" || ch === '`') {
      const quote = ch
      i += 1
      let value = ''
      while (i < source.length && source[i] !== quote) {
        // Экранирование: `\"` внутри строки её не закрывает, и `\\` не
        // экранирует следующий символ.
        if (source[i] === '\\') {
          value += source[i] + (source[i + 1] ?? '')
          i += 2
          continue
        }
        value += source[i]
        i += 1
      }
      i += 1
      found.push(value)
      continue
    }
    i += 1
  }
  return found
}

/**
 * Строка-адрес `/api/operations/`, спрошенная через `page_size`.
 *
 * 🔴 ТОЛЬКО `operations`, НО НЕ `ops` — И ЭТО ГЛАВНОЕ В ПРОБЕ (найдено ревью).
 * Два пространства имён раздела пагинируются ПО-РАЗНОМУ, и правило у них
 * ПРОТИВОПОЛОЖНОЕ. Замерено на живом стенде 06.09.2026:
 *
 *     /api/ops/security-events/?page_size=3   → 3 строки   ?limit=3 → 20
 *     /api/ops/personnel/?page_size=3         → 3 строки   ?limit=3 → 100
 *     /api/operations/status-types/?page_size=3 → 19 строк  ?limit=3 → 3
 *
 * `/api/ops/` пагинируется ВРУЧНУЮ (`api/views.py`, свои `page`/`page_size`),
 * а `LimitOffsetPagination` живёт только у `/api/operations/`. Первая редакция
 * этой пробы ловила `(?:operations|ops)` и требовала `limit` от обоих — то
 * есть требовала сломать 62 рабочих вызова: на `/api/ops/` `limit` не
 * применяется, и страница схлопнулась бы до умолчания.
 */
const OPS_WITH_PAGE_SIZE = /\/api\/operations\/[^\n]*page_size/

function countIn(text: string): number {
  return stringLiterals(text).filter((value) => OPS_WITH_PAGE_SIZE.test(value)).length
}

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules') continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) walk(full, out)
    else if (entry.endsWith('.ts') || entry.endsWith('.tsx')) out.push(full)
  }
  return out
}

