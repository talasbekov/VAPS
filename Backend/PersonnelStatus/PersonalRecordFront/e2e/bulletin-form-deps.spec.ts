/**
 * Форма правки бюллетеня не зависит от ИДЕНТИЧНОСТИ мероприятия
 * (Plane №925, класс — №555).
 *
 * 🔴 ЧТО СТЕРЕЖЁТСЯ. Эффект наполнял форму серверными значениями по
 * `[open, event, reset]`, то есть по ССЫЛКЕ на объект. `event` — строка выдачи
 * реестра, объект из кэша React Query: её меняет любой рефетч ключа, даже
 * если данные те же. Человек набирает форму, не сохраняя, рядом происходит
 * рефетч — и набранное молча откатывается к серверному. Тот же класс уже
 * стоил потери набранного в «Ответе департамента» (№555).
 *
 * 🔴 ПОЧЕМУ ПРОБА ЧИТАЕТ ИСХОДНИК, А НЕ ХОДИТ ПО ЭКРАНУ. Сегодня дефект НЕ
 * достижим: окно модальное, рефетч по фокусу выключен, WS-инвалидация сужена
 * до рейтингов и уведомлений. Живая проба проверяла бы это СТЕЧЕНИЕ, а не
 * код, и зеленела бы ровно до того дня, когда рядом появится немодальная
 * кнопка. Здесь предмет — зависимость эффекта, и читать её надо там, где она
 * написана. Без `SMOKE_LIVE` проба даёт «passed», а не «skipped» — тот же
 * приём, что у `right-hint-pattern` и `route-map-coverage`.
 *
 * 🔴 ПОЧЕМУ НЕ СТОРОЖ КЛАССА НА ВСЕ ФОРМЫ. Он был написан и выброшен:
 * надёжного правила без разбора синтаксиса не получилось. Отбор «зависимость,
 * у которой в теле берут поле через точку» обвиняет законный код —
 * `employeeId.split(...)` у строки, `staffUnits.length` у массива,
 * `create.reset()` у мутации React Query. Сторож, требующий исключений на
 * здоровый код, кончается тем, что следующий молча дописывает туда своё, —
 * это ровно та беда, которую разбирали в №901.
 */
import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE = join(
  __dirname,
  '..',
  'features/create-security-event/ui/EditBulletinDialog.tsx',
)

test.describe('правка бюллетеня', () => {
  test('форма наполняется по значениям, а не по ссылке на мероприятие', () => {
    const source = readFileSync(SOURCE, 'utf8')

    // Эффект с `reset(` — тот самый, что наполняет форму при открытии.
    const at = source.indexOf('reset(valuesOf(event))')
    expect(at, 'эффект наполнения формы не найден — проба устарела').toBeGreaterThan(0)
    const deps = source.slice(at, source.indexOf('])', at) + 2)

    expect(
      /\[\s*open\s*,\s*event\s*,/.test(deps),
      'эффект снова зависит от ОБЪЕКТА мероприятия: рефетч кэша сотрёт ' +
        'набранное, как только окно перестанет быть модальным (Plane №925)',
    ).toBe(false)
    expect(
      deps.includes('formPrint'),
      'нет подписи значений: без неё форма либо сбрасывается на каждый ' +
        'рефетч, либо не обновляется вовсе',
    ).toBe(true)
    expect(
      deps.includes('event.id'),
      'нет идентификатора строки: у соседнего мероприятия значения могут ' +
        'совпасть, и переход между строками оставил бы чужой черновик',
    ).toBe(true)
  })
})
