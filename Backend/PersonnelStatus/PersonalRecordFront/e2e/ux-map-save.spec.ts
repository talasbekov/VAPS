import { test, expect } from '@playwright/test';
import { signIn } from './ux-fixture';
import { STAND_PASSWORD, STAND_USERNAME } from './stand-credentials';

test('manual object and outdoor-post coordinates persist through a real isolated API, reload and failed save', async ({ page, request }) => {
  const id = process.env.UX_MAP_WRITE_EVENT;
  test.skip(!id, 'Requires the task-owned database clone and explicit event id.');
  expect(process.env.SMOKE_API).toBe('http://127.0.0.1:18349');
  const tokenResponse = await request.post(process.env.SMOKE_API! + '/api/token/', { data: { username: STAND_USERNAME, password: STAND_PASSWORD } });
  const token = (await tokenResponse.json()).access;
  const headers = { Authorization: `Bearer ${token}` };
  const base = `/api/ops/security-events/${id}/`;
  const before = await (await request.get(process.env.SMOKE_API + base, { headers })).json();
  expect(before.code).toBe('UX-MAP-20261012-A');
  const unexpectedWrites: string[] = [];
  await page.route('**/api/**', route => {
    const req = route.request(), path = new URL(req.url()).pathname;
    if (['GET', 'HEAD', 'OPTIONS'].includes(req.method()) || path.startsWith('/api/auth/') || (path === base + 'placement/map/' && req.method() === 'PATCH')) return route.fallback();
    unexpectedWrites.push(req.method() + ' ' + path);
    return route.fulfill({ status: 403, json: { detail: 'Only the owned event map may be changed.' } });
  });
  await signIn(page);
  await page.goto(`/security-ops/events/${id}/?step=2&visit=${before.visitObjects[0].id}&map=1`);
  await expect(page.getByRole('region', { name: 'Офлайн-карта Астаны', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Указать точку на карте', exact: true }).click();
  await page.getByLabel('Точка для', { exact: true }).selectOption(`object:${before.visitObjects[0].id}`);
  await page.getByLabel('Широта точки', { exact: true }).fill('51.128');
  await page.getByLabel('Долгота точки', { exact: true }).fill('71.43');
  const search = page.getByRole('searchbox', { name: 'Поиск улицы или района', exact: true });
  await search.fill('проспект туран');
  await search.press('Enter');
  await expect(page.getByText('Найдено: проспект Туран', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Широта точки', { exact: true })).toHaveValue('51.128');
  await expect(page.getByLabel('Долгота точки', { exact: true })).toHaveValue('71.43');
  await page.getByRole('button', { name: 'Сохранить точку', exact: true }).click();
  await expect(page.getByText('Координаты сохранены.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Указать точку на карте', exact: true }).click();
  await page.getByLabel('Точка для', { exact: true }).selectOption(`post:${before.reconSectorPosts[0].id}`);
  await page.getByLabel('Широта точки', { exact: true }).fill('51.129');
  await page.getByLabel('Долгота точки', { exact: true }).fill('71.431');
  await page.getByRole('button', { name: 'Сохранить точку', exact: true }).click();
  await expect(page.getByText('Координаты сохранены.', { exact: true })).toBeVisible();
  await page.reload();
  const locations = await (await request.get(process.env.SMOKE_API + base + 'placement/map/', { headers })).json();
  expect(locations.objects[before.visitObjects[0].id]).toEqual({ latitude: 51.128, longitude: 71.43 });
  expect(locations.posts[before.reconSectorPosts[0].id]).toEqual({ location: { latitude: 51.129, longitude: 71.431 }, outdoor: true });
  await page.getByRole('button', { name: 'Указать точку на карте', exact: true }).click();
  await page.getByLabel('Широта точки', { exact: true }).fill('51.13');
  const fail = (route: import('@playwright/test').Route) => route.request().method() === 'PATCH' ? route.fulfill({ status: 503, json: { error_code: 'PLACEMENT_MAP_UNAVAILABLE', message: 'Test failure' } }) : route.fallback();
  await page.route('**/placement/map/', fail);
  await page.getByRole('button', { name: 'Сохранить точку', exact: true }).click();
  await expect(page.getByText(/Не удалось сохранить точку/)).toBeVisible();
  await expect(page.getByLabel('Широта точки', { exact: true })).toHaveValue('51.13');
  await page.unroute('**/placement/map/', fail);
  await page.getByRole('button', { name: 'Отмена', exact: true }).click();
  const after = await (await request.get(process.env.SMOKE_API + base, { headers })).json();
  for (const key of ['reconSectorPosts', 'placementAssignments', 'forceRoster']) expect(after[key]).toEqual(before[key]);
  expect(unexpectedWrites).toEqual([]);
});
