/**
 * Карта маршрутов покрыта обходом — сверка ДВУХ СПИСКОВ, без браузера и стенда
 * (Plane №319).
 *
 * Живёт в ЦЕЛЕВОМ смоуке, а не в обходе портала, и это главное в этой пробе.
 * Раньше она стояла внутри `smoke-buttons.spec.ts` вне персон, а обход гоняется
 * блоками `-g "persona ..."` — значит сверка не попадала ни в один блок. За
 * полный прогон 29.08.2026 её не запустили НИ РАЗУ, и всё это время она была
 * красной: `/security-ops/vehicles` и справочники штата обход не покрывал
 * вовсе. Проверка, которая не выполняется, ничем не отличается от
 * отсутствующей, и молчит она убедительнее, чем говорит.
 *
 * 🔴 `SMOKE_LIVE` ЗДЕСЬ НЕ ТРЕБУЕТСЯ И НЕ ПРОВЕРЯЕТСЯ — намеренно. Живые спеки
 * без этой переменной молча скипаются, а скип читается как зелень; поставь
 * такое условие сюда — болезнь вернулась бы в новом месте и тише прежнего.
 * Пробе нечего спрашивать у стенда: она читает файловую систему и константу.
 *
 * Красная на мутации: убрать любой маршрут из `ROUTES` — падает с именем
 * потерянной страницы.
 */
import { expect, test } from "@playwright/test";

import { ROUTES, declaredPortalRoutes } from "./portal-routes";

test("карта маршрутов покрыта обходом", () => {
  const covered = new Set(
    ROUTES.map((r) => r.template.split("?")[0].replace(/\{[^}]+\}/g, ":x")),
  );
  const missing = declaredPortalRoutes().filter((d) => {
    if (covered.has(d)) return false;
    // /ops/:x — опциональный catch-all: одного входа достаточно, дальше
    // страница только редиректит (app/ops/[[...slug]]/page.tsx).
    return !(d === "/ops/:x" && covered.has("/ops/objects"));
  });
  expect(missing, "страницы app/ вне обхода").toEqual([]);
});
