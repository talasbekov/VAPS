import { expect, type Locator, type Page } from '@playwright/test'

/**
 * Открыть меню строки таблицы и нажать его пункт (Plane №820).
 *
 * 🔴 ЧТО ЛЕЧИМ. В полном смоуке пробы экрана «Статусы» падали пачкой и всегда
 * одинаково, поодиночке — зелены всегда. Дефект ВОСПРОИЗВЕДЁН 06.09.2026:
 * полный смоук по прод-стенду со СТАРЫМ кодом уронил
 * `forms-validation.spec.ts:173` с тем самым логом —
 *
 *     waiting for getByRole('menuitem', { name: 'Откомандировать сотрудника' })
 *     2 × waiting for element to be visible, enabled and stable
 *       - element is not stable
 *     ...
 *       - element is visible, enabled and stable
 *       - scrolling into view if needed
 *       - done scrolling
 *       - element is outside of the viewport
 *     17 × retrying click action → TimeoutError 10000ms
 *
 * 🔴 ЗАМЕР 1 — ЭТО НЕ ДЕФЕКТ ВИДА. Меню строки открывали на ПЕРВОЙ, СРЕДНЕЙ и
 * ПОСЛЕДНЕЙ строке при высоте окна 720, 500 и 380 пикселей — девять замеров, и
 * во всех девяти пункт оказывался В ОКНЕ: Radix переворачивает всплывающее меню
 * сам. Экран чинить не надо.
 *
 * 🔴 ЗАМЕР 2 — ПЕРВАЯ СТРОКА ТАБЛИЦЫ СТОИТ НИЖЕ ОКНА. При окне 1280×720 её
 * верх — y=726: шапка экрана («Ежедневный расход», четыре плитки сводки,
 * панель отбора) выше окна целиком. Значит КАЖДОЕ открытие меню строки
 * начинается с прокрутки, которую делает сам Playwright по ходу клика — уже
 * после того, как страница решила, где рисовать меню.
 *
 * 🔴 ЗАМЕР 3 — ПОЧЕМУ МИГАЛА ИМЕННО ЭТА ПРОБА. Из четырёх мест, открывающих
 * меню строки на /statuses, падало ровно одно — то, что шло к меню сразу после
 * `hydrated()` (а `hydrated` ждёт кнопку темы в шапке, НЕ таблицу): ни одного
 * ответа сети проба не дожидалась. Её соседка строкой выше ждёт ответ ручки
 * перед кликом и не мигала ни разу. Под нагрузкой полного смоука окно между
 * «строки появились» и «страница встала» шире, и клик попадает в него.
 *
 * ЧТО ДЕЛАЕТ ПОМОЩНИК: дожидается строки, доводит ЕЁ до окна ДО открытия меню
 * (пункт двигать поздно — он уже нарисован) и называет обе возможные поломки
 * словами. Прокрутка сделана и завершена до того, как Radix считает координаты.
 */
export async function clickRowMenuItem(
  page: Page,
  row: Locator,
  itemName: string | RegExp,
): Promise<void> {
  await expect(row, 'строки нет на экране').toBeVisible({ timeout: 30_000 })
  await row.scrollIntoViewIfNeeded()
  const trigger = row.getByRole('button', { name: /^Действия:/ })
  await expect(trigger, 'в строке нет кнопки действий').toBeVisible({ timeout: 20_000 })
  await trigger.click()
  const item = page.getByRole('menuitem', { name: itemName })
  await expect(item, `в меню строки нет пункта «${String(itemName)}»`).toBeVisible({
    timeout: 15_000,
  })
  await item.click()
}


/**
 * Укомплектованная строка таблицы статусов — НЕ первая попавшаяся.
 *
 * 🔴 ПОЧЕМУ НЕ `.first()` (Plane №822 Ш-5). Первой в таблице может стоять
 * ВАКАНСИЯ, а у вакантной строки меню действий ДРУГОЕ (`status-vacancy-actions`
 * проверяет его отдельно): пункта «Запланировать статус» там нет, и проба
 * падает по таймауту ожидания пункта — то есть на инфраструктуре, ничего не
 * сказав о своём предмете. Кто окажется первым, зависит от того, что соседняя
 * сессия только что сделала со статусами и штатом.
 *
 * Тот же фильтр стоял в `status-dialog-calendar-locale` и во второй половине
 * `status-vacancy-actions`, а в `forms-validation` и `status-set-dialog` его
 * не повторили. Живёт он ЗДЕСЬ, рядом с `clickRowMenuItem`, а не копией в
 * каждой спеке: копии расходятся молча — так разошлись шестнадцать копий
 * заведения ОМ до №822 Ш-1.
 */
export function staffedRow(page: Page): Locator {
  return page
    .locator('table tbody tr')
    .filter({ hasNot: page.getByText('ВАКАНТ') })
    .first()
}
