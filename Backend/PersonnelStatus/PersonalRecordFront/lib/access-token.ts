/**
 * Токен доступа для запросов к бэку — ОДИН на весь фронт, с кэшем и
 * дедупликацией (Plane №343).
 *
 * ЗАЧЕМ ПОЯВИЛСЯ. Оба API-клиента (`lib/api.ts`, `lib/ops-api.ts`) звали
 * `getSession()` из `next-auth/react` ПЕРЕД КАЖДЫМ обращением к бэку, а
 * `getSession` ничего не кэширует: в `node_modules/next-auth/client/_utils.js`
 * это голый `fetch(url)` к `/api/auth/session` — ни памяти, ни общего промиса.
 * То есть каждый запрос экрана стоил ДВА round-trip'а вместо одного.
 *
 * ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (прод-сборка :3108, обход семи модулей кликами
 * по сайдбару): 158 запросов `/api/auth/session` против 84 обращений к данным
 * — лишних почти ВДВОЕ больше, чем полезных. Один экран «Сбор сил на ОМ» —
 * 120 запросов за сессией на 60 запросов к бэку: он бьёт `/api/ops/daily/
 * employees/` по каждому подразделению, и каждый тащил свой `getSession()`.
 *
 * ПОЧЕМУ ЭТО НЕ ВИДНО РАЗРАБОТЧИКУ И ВИДНО ЗАКАЗЧИКУ. Это не время счёта, а
 * СУММА ЗАДЕРЖЕК СЕТИ, линейная по числу запросов. На localhost round-trip
 * 3-15 мс, и 120 запросов дают полсекунды — незаметно. При задержке канала
 * 30-50 мс те же 120 запросов дают 3,6-6 секунд, то есть ровно описанное в
 * карточке «нажимаешь на модуль — он думая через пару секунд отвечает».
 * Дефект масштабируется каналом, а не мощностью машины.
 *
 * ДВА МЕХАНИЗМА, И ОНИ РАЗНЫЕ:
 *
 * 1. ДЕДУПЛИКАЦИЯ ПАРАЛЛЕЛЬНЫХ. Пока запрос сессии в полёте, все остальные
 *    ждут ЕГО, а не заводят свой. Это лечит веер «запрос на подразделение»
 *    (`useQueries` пускает их разом) и семантики не меняет вовсе: все
 *    получают тот же ответ, который получили бы каждый сам.
 * 2. КОРОТКИЙ СРОК ГОДНОСТИ. Последовательные запросы (пагинация статусов
 *    идёт страницами в цикле с `await`) параллельными не бывают, и одной
 *    дедупликацией не лечатся — им нужна память. Отсюда `TTL_MS`.
 *
 * ПОЧЕМУ СРОК КОРОТКИЙ. Кэш токена — это окно, в котором клиент может
 * послать УЖЕ НЕДЕЙСТВИТЕЛЬНЫЙ токен (сессию продлили, роль сменили, человек
 * вышел). Ни один из клиентов не умеет повторять запрос после 401, поэтому
 * окно должно быть заведомо меньше, чем время жизни токена, и заметно меньше
 * человеческой паузы между действиями. Пятнадцати секунд хватает, чтобы
 * схлопнуть ВСПЫШКУ запросов одного экрана (она укладывается в сотни
 * миллисекунд), и мало, чтобы пережить смену сессии.
 *
 * ВЫХОД ИЗ СИСТЕМЫ СБРАСЫВАЕТ КЭШ ЯВНО (`resetAccessToken`), а не ждёт
 * истечения срока: иначе следующий вход в течение 15 секунд подписывался бы
 * чужим токеном — и это была бы не медлительность, а неверные данные.
 */

/** Срок годности записи в кэше. Обоснование величины — в шапке файла. */
const TTL_MS = 15_000;

interface CachedToken {
  token: string | null;
  at: number;
}

let cached: CachedToken | null = null;
/** Запрос сессии в полёте. Общий промис — и есть дедупликация. */
let inflight: Promise<string | null> | null = null;

/**
 * Токен из сессии NextAuth. На сервере всегда `null` — сессия живёт в
 * браузере, и попытка спросить её при рендере на сервере вернула бы пустоту
 * ценой запроса.
 */
export async function getAccessToken(): Promise<string | null> {
  if (typeof window === "undefined") return null;

  const now = Date.now();
  if (cached !== null && now - cached.at < TTL_MS) return cached.token;
  if (inflight !== null) return inflight;

  inflight = (async () => {
    try {
      const { getSession } = await import("next-auth/react");
      const session = await getSession();
      const user = session?.user as { accessToken?: string } | undefined;
      const token = user?.accessToken ?? null;
      cached = { token, at: Date.now() };
      return token;
    } catch {
      // Отказ НЕ КЭШИРУЕТСЯ: запомнить «токена нет» на 15 секунд означало бы
      // превратить одну сетевую икоту в четверть минуты отказов на всех
      // экранах сразу.
      cached = null;
      return null;
    } finally {
      inflight = null;
    }
  })();

  return inflight;
}

/**
 * Забыть токен немедленно. Зовётся при выходе из системы и при смене учётной
 * записи — везде, где следующий запрос обязан спросить сессию заново.
 */
export function resetAccessToken(): void {
  cached = null;
  inflight = null;
}
