/**
 * Когда отказ продления означает «токен мёртв», а когда «сеть икнула»
 * (Plane №459).
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило живёт внутри серверного колбэка
 * NextAuth, а колбэк из пробы не позвать: продление идёт на стороне Next, и
 * ни `page.route`, ни запрос из браузера в него не попадают. Проверить
 * решение можно было бы только подняв фальшивый бэкенд рядом со стендом —
 * дорого и хрупко. Вынесенное правило проверяется прямо, а `auth-config`
 * зовёт его же: второй копии решения не появляется.
 */

/** Пауза перед повтором продления после ВРЕМЕННОГО отказа (Plane №461). */
export const REFRESH_RETRY_MS = 30_000;

/**
 * Сервер сказал, что токен НЕ ГОДЕН, — повторять нечего, сессию жжём.
 *
 * Всё остальное (5xx, таймаут, `ECONNREFUSED`, 200 без поля) — временная
 * беда: refresh-токен в cookie ЖИВОЙ, и стирать его из-за перезапуска
 * Django значит выкинуть из системы каждого, чей access-токен попал в
 * минутное окно продления.
 */
export function isTokenRejected(status: number): boolean {
  return status === 400 || status === 401 || status === 403;
}

/**
 * Одна работа на ключ: параллельные вызовы ждут ПЕРВЫЙ, а не заводят свой
 * (Plane №465, №474).
 *
 * Правило вынесено сюда по той же причине, что и `isTokenRejected`: колбэк
 * NextAuth из пробы не позвать, а гонку надо чем-то стеречь. Здесь она
 * проверяется прямо — счётчиком запусков.
 *
 * Запись снимается В ЛЮБОМ исходе: оставшийся промис раздавал бы всем
 * следующим уже протухший ответ, и продление перестало бы работать совсем —
 * хуже исходной гонки.
 */
export function makeOnce<T>(): (key: string, work: () => Promise<T>) => Promise<T> {
  const inflight = new Map<string, Promise<T>>();
  return (key, work) => {
    const running = inflight.get(key);
    if (running !== undefined) return running;
    const started = work().finally(() => {
      inflight.delete(key);
    });
    inflight.set(key, started);
    return started;
  };
}

/** За сколько до истечения токен считается протухшим. Минута — запас на
 *  дорогу запроса и на расхождение часов клиента и сервера: токен,
 *  истекающий через две секунды, до бэкенда уже не доедет. */
export const EXPIRY_SKEW_MS = 60_000;

/**
 * Насколько верить токену, у которого срок прочитать не удалось (Plane №464).
 *
 * 🔴 ЧИСЛО ОБЯЗАНО БЫТЬ БОЛЬШЕ `EXPIRY_SKEW_MS`, иначе фолбэк не делает
 * ничего: `isExpiring` вычитает запас, и «сейчас + минута» при минутном
 * запасе протухает в ту же секунду — ровно то вечное продление, от которого
 * фолбэк и заводится. Полезное окно равно РАЗНИЦЕ: две минуты минус минута
 * запаса — минута жизни, то есть не чаще одного продления в минуту вместо
 * одного на каждое чтение сессии.
 *
 * Больше брать нельзя: срок неизвестен, и длинное окно — это обещание за
 * сервер, которого никто не давал. Токен может жить и две минуты; тогда
 * лишние минуты обернутся 401 на каждом экране, а это и есть дефект №383.
 */
export const UNKNOWN_EXPIRY_MS = 2 * EXPIRY_SKEW_MS;

/** Момент истечения access-токена (мс), прочитанный из самого токена.
 *
 *  Читаем `exp` ИЗ ТОКЕНА, а не считаем «сейчас + 8 часов»: срок задан
 *  настройкой сервера, и локальная копия этого числа разошлась бы с ним при
 *  первой же правке `ACCESS_TOKEN_LIFETIME`. `null` — прочитать не удалось.
 */
export function tokenExpiryMs(raw: unknown): number | null {
  if (typeof raw !== "string") return null;
  const payload = raw.split(".")[1];
  if (payload === undefined) return null;
  try {
    const json = JSON.parse(
      Buffer.from(payload.replace(/-/g, "+").replace(/_/g, "/"), "base64").toString("utf8"),
    ) as { exp?: unknown };
    return typeof json.exp === "number" ? json.exp * 1000 : null;
  } catch {
    return null;
  }
}

/**
 * Срок, который кладётся в сессию рядом с полученным токеном.
 *
 * 🔴 ЗАЧЕМ ФОЛБЭК (Plane №464). Раньше сюда попадал сам `null`, и это
 * стоило не «лишнего продления», как обещал комментарий, а ВЕЧНОГО:
 * `isExpiring(null)` истинно всегда, значит каждое чтение сессии — а их за
 * обход портала около полутора сотен — слало свой `POST /api/token/refresh/`.
 * Пока бэкенд отдаёт SimpleJWT с `exp`, беды нет; перейдут на непрозрачный
 * токен — и портал удвоит запросы на ровном месте, с симптомом «стало
 * медленнее», а не с ошибкой.
 */
export function accessExpiryMs(raw: unknown, now: number = Date.now()): number {
  return tokenExpiryMs(raw) ?? now + UNKNOWN_EXPIRY_MS;
}

/**
 * Пора ли продлевать. `undefined` — сессия, выданная до появления срока:
 * такую продлеваем сразу, иначе она доживёт до 401 на каждом экране (№383).
 */
export function isExpiring(expires: unknown, now: number = Date.now()): boolean {
  if (typeof expires !== "number") return true;
  return now >= expires - EXPIRY_SKEW_MS;
}
