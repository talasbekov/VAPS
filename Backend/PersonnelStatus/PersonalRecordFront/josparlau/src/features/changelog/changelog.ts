//   · API-поверхность закрыта списком (architecture.md:600):
//     /api/{core,operations,audit,notifications,documents}/, /api/jobs/{id},
//     WS /ws/notifications/ — пути журнала там нет.
// Прецеденты рукописного зеркала при отсутствующей схеме — daySubmission.ts.
//
// ЧЕМ ЕГО ЗАМЕНИТ 13.4: она приносит и эндпоинт, и схему. Тогда `FixEntry`
