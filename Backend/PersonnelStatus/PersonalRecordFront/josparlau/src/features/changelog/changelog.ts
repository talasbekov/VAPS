// разработчику (анонимность от начальства, epics.md#L1354). Чего нет в типе,
// то не утечёт в вёрстку. Контракт будущей строки (epics.md#L1378) — «строка
// журнала связывает репорт и версию», личности в нём нет.

/** Строка журнала: что и в какой версии закрыто. Без личности сообщившего. */
export interface FixEntry {
  id: string
  /** Версия выпуска, semver из трёх частей (architecture.md#L145). */
  version: string
  /** Дата выпуска, ISO `YYYY-MM-DD` — как её отдаёт бэк в остальных контрактах. */
  releasedAt: string
  /** Что исправлено — формулировка для пользователя, не тикет-заголовок. */
  summary: string
}

/**
 * Источник строк СЕГОДНЯ пуст — это нормальное состояние до 13.4, а не сбой
 * (порядок эпиков E10 → 13.1-13.3 → E12 → 13.4, epics.md#L160).
 * Используется как дефолт пропа `fixes` у ChangelogPage.
 */
export const CLOSED_FIXES: readonly FixEntry[] = []

/**
 * Новые сверху.
 *
 * 🔴 НЕ мутирует вход — `[...fixes].sort(...)`, а не голый `.sort()`: голый
 * перетасовал бы фикстуру вызывающего и сделал соседний тест зависимым от
 * порядка выполнения. `toSorted` не годится — target es2022, а FF115+ (см.
 * шапку tsconfig.app.json).
 *
 * Сравнение строк ISO лексикографически совпадает с хронологическим, поэтому
 * `Date` не нужен и здесь (тот же довод, что в formatJournalDate).
 * `Array.prototype.sort` стабилен → равные даты сохраняют порядок входа.
 */
export function sortFixesByRelease(fixes: readonly FixEntry[]): FixEntry[] {
  return [...fixes].sort((a, b) => b.releasedAt.localeCompare(a.releasedAt))
}

/**
 * `'2026-07-19'` → `'19.07.2026'` ПЕРЕСТАНОВКОЙ СТРОКИ.
 *
 * 🔴 `new Date()` ЗАПРЕЩЁН, и это гейт, а не стиль. QA-находка 10.7 (HIGH):
 * мутация «форматировать через `new Date(iso).toLocaleDateString()`» оставляла
 * 71/71 тестов зелёными под зоной гейта +05 и краснела только под
 * отрицательной зоной — `new Date('2026-07-19')` парсится как UTC-полночь, а
 * в America/Anchorage (UTC−8/−9) локальная дата откатывается на сутки назад.
 * Тот же класс всплывал в 10.5. Перестановка строки от зоны не зависит вовсе.
 */
export function formatJournalDate(iso: string): string {
  const [year, month, day] = iso.split('-')
  return `${day}.${month}.${year}`
}
