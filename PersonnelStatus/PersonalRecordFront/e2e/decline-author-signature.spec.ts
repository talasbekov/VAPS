/**
 * Автор чужого отказа подписан ОДИНАКОВО на обоих экранах (Plane №916,
 * требование №796).
 *
 * 🔴 ЧТО СТЕРЕЖЁТСЯ. Отказ «не могу заступить» вписывает не только сам
 * сотрудник: гейт ручки намеренно пускает старшего и ведущего ОМ — человек
 * может позвонить. Пока автора не было, чужая формулировка выдавалась за
 * собственную. №796 потребовал показывать автора ТОЙ ЖЕ формулировкой и ТЕМ
 * ЖЕ правилом на обоих экранах: в карточке ОМ («Ознакомление») и в профиле
 * сотрудника.
 *
 * Сегодня оба места совпадают дословно, но стерёгся только ОДИН: живая проба
 * профиля проверяет текст отказа, а слова «записал» в ней нет вовсе. Снять
 * подпись на «Ознакомлении» можно было молча — и формулировки разошлись бы
 * ровно так, как боится карточка, только в форме «на одном экране есть, на
 * другом нет».
 *
 * 🔴 ПОЧЕМУ ПО ИСХОДНИКАМ, А НЕ ЖИВОЙ ПРОБОЙ. Предмет — СОВПАДЕНИЕ ДВУХ
 * МЕСТ, а не поведение одного. Живая проба показала бы, что подпись есть
 * там, куда она зашла; чтобы поймать расхождение, ей пришлось бы поставить
 * на стенде отказ, вписанный ЧУЖИМ человеком, на обоих экранах сразу — то
 * есть завести состояние ради проверки текста. Разбор исходников отвечает на
 * тот же вопрос и не трогает общий стенд. Без `SMOKE_LIVE` проба даёт
 * «passed», а не «skipped».
 */
import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(__dirname, '..')

/** Оба экрана, показывающие подпись под чужим отказом. */
const SCREENS = [
  'features/security-event-stages/ui/AcknowledgementStage.tsx',
  'widgets/my-profile/ui/ProfileBody.tsx',
]

test.describe('подпись под чужим отказом', () => {
  test('оба экрана печатают её одной формулировкой и по одному правилу', () => {
    for (const relative of SCREENS) {
      const source = readFileSync(join(ROOT, relative), 'utf8')

      const label = source.match(/записал:\s*\{/g) ?? []
      expect(
        label.length,
        `${relative}: подписи «записал: …» нет или их несколько — ` +
          'формулировка обязана быть одна и та же на обоих экранах',
      ).toBe(1)

      expect(
        /declinedVia\s*===\s*"personal"/.test(source),
        `${relative}: правило показа взято не из declinedVia — подписи ` +
          'приходят из разных источников и совпадают не всегда, поэтому ' +
          'сравнение подписи с фамилией здесь не годится',
      ).toBe(true)
    }
  })
})
