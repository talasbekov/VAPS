/**
 * «Не отнесены к объекту» — законный выбор ТОЛЬКО когда такие строки есть
 * (Plane №488).
 *
 * 🔴 ЧТО ЭТО СТЕРЕЖЁТ. С №388 показанный объект живёт в адресе (`?visit=`), и
 * `__unassigned__` — такое же его значение, как идентификатор объекта: его
 * пишет сам выборщик и его пересылают ссылкой. Но потребители писались под
 * другой случай — «у ОМ нет объектов вовсе» — и получали «объекта нет» на
 * мероприятии, где объекты ЕСТЬ. Значение при этом считалось живым ВСЕГДА и
 * не чинилось никогда.
 *
 * Три симптома одной причины, все на многообъектных ОМ:
 *   1. на «Проведении» молча исчезали панели оценки и закрытия объекта;
 *   2. на «Согласовании» показывался маршрут ПЕРВОГО объекта как свой, а
 *      кнопки уходили на сервер без адреса объекта и получали отказ;
 *   3. на ОМ с ОДНИМ объектом шапка уверяла «показаны строки, не отнесённые
 *      ни к одному объекту», рисуя при этом ВСЕ строки.
 * Выйти можно было только правкой адресной строки руками.
 *
 * ПРАВИЛО ПРОВЕРЯЕТСЯ ПРЯМО, а не через экран: оно названо один раз
 * (`unassignedIsMeaningful`) и читается и хуком, и страницей. Второй ответ на
 * тот же вопрос разошёлся бы с первым — именно так дефект и появился.
 */
import { expect, test } from '@playwright/test'
import { unassignedIsMeaningful } from '../features/security-event-stages/ui/useVisitObjectScope'

const TWO = [{ id: '1' }, { id: '2' }]
const ONE = [{ id: '1' }]

test('«не отнесены» имеет смысл только при неразмеченных строках и двух объектах', () => {
  // Есть что показать: два объекта и строка без владельца.
  expect(
    unassignedIsMeaningful(TWO, [{ visitObjectId: '1' }, { visitObjectId: null }]),
  ).toBe(true)
  expect(unassignedIsMeaningful(TWO, [{ visitObjectId: '1' }, {}])).toBe(true)

  // Показывать нечего: все строки размечены. Раньше выбор оставался живым, а
  // пункта в списке уже не было — «сняли последнюю неразмеченную строку».
  expect(
    unassignedIsMeaningful(TWO, [{ visitObjectId: '1' }, { visitObjectId: '2' }]),
  ).toBe(false)
  expect(unassignedIsMeaningful(TWO, [])).toBe(false)

  // 🔴 У ЕДИНСТВЕННОГО ОБЪЕКТА НЕРАЗМЕЧЕННЫЕ СТРОКИ — ЕГО. Так считает и
  // сервер (`_visit_placement`), и экран обязан отвечать так же: иначе шапка
  // говорила бы «не отнесены ни к одному объекту», показывая все строки.
  expect(unassignedIsMeaningful(ONE, [{ visitObjectId: null }])).toBe(false)
  expect(unassignedIsMeaningful(ONE, [{ visitObjectId: '1' }])).toBe(false)

  // ОМ без объектов посещения: отнести не к чему, но и выбирать не из чего —
  // отдельного пункта у него нет, и правило отвечает «нет» вместе со всеми.
  expect(unassignedIsMeaningful([], [{ visitObjectId: null }])).toBe(false)
})
