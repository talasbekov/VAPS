/**
 * Шаг подготовки живой пробы, который НЕ МОЛЧИТ (Plane №812, уточнение №813).
 *
 * 🔴 ЧТО ЭТО ЛЕЧИТ. Фикстура живой пробы — цепочка вызовов: завести ОМ,
 * импортировать посты, отметить чек-лист, завершить рекогносцировку, назначить
 * людей, отправить на согласование. Писалась она как `await call('POST', …)`
 * подряд, без единого взгляда на ответ сервера. Пока правила не менялись, это
 * работало.
 *
 * Как это выглядит, когда правило поменялось: `recon/complete/` начинает
 * отвечать 422, фикстура МОЛЧА идёт дальше, ОМ остаётся на прежнем этапе — и
 * проба падает СИЛЬНО ПОЗЖЕ и в другом месте: «элемент не найден», «не удалось
 * подготовить фикстуру», «кнопки нет на экране». Настоящая причина — код и
 * тело отказа — не печатается нигде.
 *
 * Цена замерена за одну смену 05.09.2026: три сессии независимо разбирали одну
 * и ту же поломку по симптомам — четыре красных пробы в `acknowledgement-stage`,
 * пятнадцать в `test_ops_force_collection_board`, три в `approval-stage` с
 * текстом «не удалось подготовить фикстуру». Каждый раз сначала искали дефект в
 * своей правке, потом повторяли прогон, и только потом добирались до сервера.
 *
 * 🔴 ПРОВЕРЯЮТСЯ НЕ ВСЕ ВЫЗОВЫ, А ШАГИ, МЕНЯЮЩИЕ СОСТОЯНИЕ (Plane №813).
 * Формулировка «каждый `post` проверяет код» слишком широка и потому опасна: в
 * живых пробах есть шаги, где отказ ОЖИДАЕМ и сам является предметом проверки
 * (PATCH черновика с заведомо неверным полем, действие без права, повторное
 * закрытие). Сторож, требующий проверки на каждом `post`, покраснел бы и там —
 * и его начали бы глушить построчными исключениями, после чего он перестал бы
 * ловить что-либо вовсе.
 *
 * Поэтому список путей-переходов задан ЯВНО и ниже, а не угадывается по слову
 * `post`. Переход — то, после чего следующий шаг фикстуры имеет смысл только
 * при успехе предыдущего.
 */

/**
 * Пути, после которых фикстура не имеет смысла без успеха: переходы этапов,
 * завершения, отправки, приёмы. Сверяется вхождением подстроки — адреса
 * собираются шаблонами, и точного равенства здесь не бывает.
 *
 * `/decide/` — решение согласующего: отказ означает, что маршрут не тот или
 * прав нет, и всё, что идёт следом, проверяет не то, что написано в пробе.
 */
export const TRANSITION_STEPS = [
  'bulletin/complete/',
  'recon/import-from-passport/',
  'recon/complete/',
  'demand/approve/',
  'forces/complete/',
  'placement/assign/',
  'placement/complete/',
  'approval/send/',
  'approval/approve/',
  '/decide/',
  'acknowledgement/complete/',
  'conduct/complete/',
  '/handover/',
  '/stage/',
] as const;

export function isTransitionStep(path: string): boolean {
  return TRANSITION_STEPS.some((step) => path.includes(step));
}

/**
 * Отбить шаг-переход, ответивший не 2xx, — с методом, адресом, кодом и телом.
 *
 * Ставится ОДНОЙ строкой в уже существующий помощник спеки, до разбора тела:
 * так проверка появляется у всех его вызовов сразу, а форма возвращаемого
 * значения (у разных спек она своя — то тело, то `{status, payload}`) не
 * меняется вовсе. Переписывать помощники под общий вид было бы правкой ради
 * единообразия в четырнадцати живых файлах — цена без предмета.
 *
 * Понимает оба вида ответа: `Response` из `fetch` (`status` — поле, тело
 * читается у копии) и `APIResponse` Playwright (`status()` — метод, тело
 * буферизовано и читается повторно).
 */
export async function assertStep(
  response: { status: number | (() => number); text?: () => Promise<string>; clone?: () => any },
  method: string,
  path: string,
): Promise<void> {
  const status = typeof response.status === 'function' ? response.status() : response.status;
  if (status >= 200 && status < 300) return;
  if (!isTransitionStep(path)) return;
  let body = '';
  try {
    const source = typeof response.clone === 'function' ? response.clone() : response;
    body = typeof source.text === 'function' ? await source.text() : '';
  } catch {
    body = '';
  }
  throw new Error(
    `[фикстура] шаг ${method} ${path} отбит: ${status}\n` +
      `${body.slice(0, 600)}\n` +
      'Это подготовка, а не предмет пробы: дальше проверять нечего. ' +
      'Скорее всего изменилось серверное правило этого перехода.',
  );
}


/**
 * Собрать `call(method, path, body)` для фикстуры живой пробы.
 *
 * Отличие от прежних самодельных помощников ровно одно и оно главное: на
 * шаге-переходе, ответившем не 2xx, бросается ошибка С МЕТОДОМ, АДРЕСОМ,
 * КОДОМ И ТЕЛОМ. Всё остальное — чтения, заведомо отбиваемые попытки — как
 * прежде: ответ возвращается разобранным, и проба решает сама.
 *
 * Тело отказа обрезается до 600 символов: у DRF там бывает страница HTML, и
 * простыня в отчёте прячет первую строку, ради которой всё и затевалось.
 */
export function makeCall(
  api: string,
  headers: Record<string, string>,
): (method: string, path: string, body?: unknown) => Promise<any> {
  return async function call(method: string, path: string, body?: unknown): Promise<any> {
    const response = await fetch(`${api}${path}`, {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    let payload: unknown = {};
    try {
      payload = text === '' ? {} : JSON.parse(text);
    } catch {
      payload = { raw: text };
    }
    if (!response.ok && isTransitionStep(path)) {
      throw new Error(
        `[фикстура] шаг ${method} ${path} отбит: ${response.status}\n` +
          `${text.slice(0, 600)}\n` +
          'Это подготовка, а не предмет пробы: дальше проверять нечего. ' +
          'Скорее всего изменилось серверное правило этого перехода.',
      );
    }
    return payload;
  };
}
