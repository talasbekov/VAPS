"use client";

// Права звеньев цепочки «Сбор сил на ОМ» на КЛИЕНТЕ (Plane №74, шаг Р-7).
//
// 🔴 Клиент гейтит по КОДУ права, а не по области. Ручка прав отдаёт плоский
// список кодов (`/api/operations/my-permissions/`) и про области ничего не
// знает; посчитать «мой ли это департамент» на клиенте значило бы завести
// ВТОРУЮ правду об авторизации — она разошлась бы с сервером при первой же
// правке дерева подразделений. Область проверяет сервер, и его отказ человек
// читает словами там же, где нажал.
//
// Недоступное действие ВЫКЛЮЧАЕТСЯ, а не прячется: спрятанная кнопка не
// отвечает на вопрос «почему я этого не вижу», и человек идёт спрашивать. Это
// же правило раздел уже применяет к меню — пункт виден, экран говорит «Доступ
// закрыт».
import { useOpsPermissions } from "@/hooks/use-ops-permissions";

export const FORCES_COMMAND = "forces.command";
export const FORCES_ALLOCATE = "forces.allocate";
export const FORCES_SELECT = "forces.select";
export const PLACEMENT_MANAGE = "placement.manage";
/** Решение согласующего по расстановке (Plane №267). Отдельно от ведения
 * мероприятия: утверждающий видит расстановку целиком, но не правит её —
 * иначе подписывающий переписывает подписываемое. */
export const APPROVAL_APPROVE = "assignment.approve";
export const APPROVAL_RETURN = "assignment.return";

/** Причина отказа — ЧТО ЗА РОЛЬ это делает, а не «нет прав».
 *
 * Общее «недостаточно прав» человеку бесполезно: он не знает, чьё это
 * действие и к кому идти. Подписи названы теми же словами, которыми звенья
 * назвал заказчик. */
const REASON: Record<string, string> = {
  [FORCES_COMMAND]: "Делит потребность и решает по спискам штаб",
  [FORCES_ALLOCATE]:
    "Оповещает управления и отправляет список ответственный за выделение в своём департаменте",
  [FORCES_SELECT]: "Выделяет людей начальник управления по своему управлению",
  [PLACEMENT_MANAGE]: "Расставляет людей по постам старший объекта",
  [APPROVAL_APPROVE]: "Согласовывает расстановку утверждающий",
  [APPROVAL_RETURN]: "Возвращает расстановку на доработку утверждающий",
};

export interface ChainAccess {
  /** Разрешено ли действие по коду права. Пока права грузятся — `true`:
   * выключать кнопки на полсекунды загрузки значит мигать интерфейсом, а
   * сервер всё равно отобьёт запрос, если права нет. */
  can(code: string): boolean;
  /** Подпись причины для выключенной кнопки; пусто — действие доступно. */
  reason(code: string): string;
}

export function useChainAccess(): ChainAccess {
  const { hasPermission, isLoading } = useOpsPermissions();
  return {
    can: (code) => isLoading || hasPermission(code),
    reason: (code) =>
      isLoading || hasPermission(code) ? "" : (REASON[code] ?? "Действие закрыто правом"),
  };
}
