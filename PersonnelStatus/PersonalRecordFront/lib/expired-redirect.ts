/**
 * Куда уводить человека, у которого сессия кончилась посреди работы
 * (Plane №467).
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ — та же причина, что у `lib/refresh-policy`:
 * решение принимается внутри клиентского провайдера (`lib/auth.tsx`), куда
 * проба не дотягивается, а провайдер тянет за собой react и next-auth. Правило
 * вынесено и проверяется прямо; `auth.tsx` зовёт его же, второй копии решения
 * не появляется.
 */

/**
 * Адрес формы входа для человека, которого выкинуло по истечении сессии.
 *
 * 🔴 АДРЕС, НА КОТОРОМ ЧЕЛОВЕК РАБОТАЛ, ЕДЕТ С НИМ. Раньше увод шёл голым
 * `/?reason=expired`, и после повторного входа человек оказывался на
 * дашборде: расстановку сил или согласование он искал руками. Обычный путь
 * через middleware адрес сохранял — то есть это было расхождение с соседним
 * поведением, а не осознанное решение.
 *
 * Читает это тот же `safeCallbackUrl` на форме входа, что и адрес от
 * middleware: он берёт только внутренний путь и на саму форму не возвращает —
 * круга не получится. Поэтому здесь достаточно положить путь как есть;
 * проверять его второй раз значило бы завести вторую копию правила.
 *
 * `pathname` без `search` и `hash` не годится: и то и другое несёт СОСТОЯНИЕ
 * экрана — выбранный день, открытую вкладку карточки, — и без них человек
 * вернулся бы на «тот же» экран, но не на своё место.
 */
export function expiredLoginUrl(here: {
  pathname: string;
  search: string;
  hash: string;
}): string {
  // С формы входа возвращать некуда: параметр только замусорил бы адрес.
  if (here.pathname === "/") return "/?reason=expired";
  const target = `${here.pathname}${here.search}${here.hash}`;
  return `/?reason=expired&callbackUrl=${encodeURIComponent(target)}`;
}
