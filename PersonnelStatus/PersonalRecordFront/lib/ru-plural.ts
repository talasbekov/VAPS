/**
 * Согласование существительного с числом по-русски — ОДНО правило на портал.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Правило простое, и именно поэтому его писали заново
 * в каждом месте, где понадобилось: реестр ОМ («N замечаний»), лента
 * уведомлений, окно заведения ОМ, срок статуса. Написанное четырежды, оно
 * четырежды и разошлось: в реестре 21 давало «21 замечание», а в уведомлении о
 * ТОМ ЖЕ возврате — «21 замечаний» (Plane №585); уведомление о запросе сил
 * вообще не склоняло и печатало «Выделите 1 сотрудников» (Plane №562). Две
 * поверхности говорили про одно число по-разному, и человек читал это как сбой,
 * а не как небрежность.
 *
 * ХВОСТ СЧИТАЕТСЯ ПО ДВУМ ОСТАТКАМ, А НЕ ПО ОДНОМУ. Подводит именно второй
 * десяток: 11-14 читаются как «одиннадцать замечаниЙ», хотя их хвосты (1-4)
 * просят «замечание/замечания». Тернарник без `% 100` проходит все проверки на
 * 1, 2, 5 и ломается ровно на 11 и 21 — на числах, которых в проверке не было.
 */

/** Три формы: для 1, для 2-4, для 5 и «ноль/много». Порядок — как в языке. */
export type RuPluralForms = readonly [one: string, few: string, many: string];

/** Форма слова для числа: `ruPlural(21, ["замечание", "замечания", "замечаний"])` → «замечание». */
export function ruPlural(count: number, forms: RuPluralForms): string {
  const n = Math.abs(Math.trunc(count));
  const tail = n % 10;
  const teen = n % 100;
  if (teen >= 11 && teen <= 14) return forms[2];
  if (tail === 1) return forms[0];
  if (tail >= 2 && tail <= 4) return forms[1];
  return forms[2];
}

/** Число со словом: `ruCount(21, …)` → «21 замечание». Читается вслух как есть. */
export function ruCount(count: number, forms: RuPluralForms): string {
  return `${count} ${ruPlural(count, forms)}`;
}

/** «1 замечание · 2 замечания · 5 замечаний» — бейдж реестра и уведомление о
 *  возврате с согласования говорят про одно число ОДНИМИ словами (Plane №585). */
export const REMARKS: RuPluralForms = ["замечание", "замечания", "замечаний"];

/** «Выделите 1 сотрудника» — запрос сил управлению (Plane №562, `[СБС-22]`).
 *
 * ⚠️ ВТОРАЯ И ТРЕТЬЯ ФОРМЫ СОВПАДАЮТ, И ЭТО НЕ ОПЕЧАТКА. «Сотрудник»
 * одушевлённый, а фраза стоит в винительном падеже («выделите КОГО»): у
 * одушевлённых винительный совпадает с родительным, поэтому и «выделите двух
 * сотруднико́в», и «выделите пять сотруднико́в». Отличается только единица —
 * «выделите одного сотрудника». Написать здесь «сотрудника» во второй форме
 * (как в именительном «два сотрудника») значило бы поставить фразу в падеж,
 * которым она не управляется. */
export const EMPLOYEES: RuPluralForms = ["сотрудника", "сотрудников", "сотрудников"];

/** «1 сотрудник · 2 сотрудника · 5 сотрудников» — ИМЕНИТЕЛЬНЫЙ счёт, в
 *  отличие от `EMPLOYEES` выше: «оповещено 2 сотрудника», а не «выделите». */
export const PEOPLE: RuPluralForms = ["сотрудник", "сотрудника", "сотрудников"];

/** «1 день · 2 дня · 5 дней» — срок статуса, срок визита, окно заведения ОМ. */
export const DAYS: RuPluralForms = ["день", "дня", "дней"];

/** «1 мероприятие · 2 мероприятия · 5 мероприятий» — реестры ГВО и аналитика. */
