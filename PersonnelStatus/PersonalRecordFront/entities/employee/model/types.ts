// Типы для сущности Employee (UI-представление)
export interface Employee {
  id: string;
  number: number;
  name: string;
  position: string;
  department: string;
  departmentId: string;
  status: string;
  /**
   * Сырой код текущего статуса; `null` — статуса нет вовсе.
   *
   * Нужен, чтобы красить бейдж ПО КОДУ, а не обратным поиском по русской
   * подписи (Plane №366): с приходом справочника подписи перестали быть
   * замкнутым списком, и поиск «подпись → код» отдавал `undefined` на каждом
   * типе, заведённом заказчиком в админке, — статус красился серым, как
   * неизвестный, при верной подписи.
   */
  statusCode: string | null;
  /**
   * Начало ТЕКУЩЕГО СТАТУСА, пустая строка — статуса нет.
   *
   * Поле звалось `hireDate` и подписывалось «Дата найма», хотя в него клали
   * `current_status.start_date`, а при его отсутствии — сегодняшнее число.
   * Отсюда одинаковая дата у всех строк таблицы и «стаж работы 0 месяцев» у
   * всякого, кто ушёл в отпуск. Настоящая дата найма теперь приезжает
   * отдельным полем `hireDate`.
   */
  statusSince: string;
  /** Конец текущего статуса, пустая строка — бессрочный или статуса нет. */
  statusUntil: string;
  /** Звание. Пустая строка — в карточке сотрудника оно не заполнено. */
  rank: string;
  /**
   * ИИН ХВОСТОМ: «•••••• 4216». Маскирует сервер — полных двенадцати цифр во
   * фронте нет вовсе. Пустая строка — ИИН не заполнен.
   */
  iinMasked: string;
  /** Дата найма «ГГГГ-ММ-ДД» — настоящая, из модели, а не начало статуса. */
  hireDate: string;
  /** Дата рождения «ГГГГ-ММ-ДД». */
  birthDate: string;
  /** Табельный номер. */
  personnelNumber: string;
  photo?: string;
  /** Штатная единица. Нужна модалке статусов: она адресует сотрудника ключом
   * `${staffUnitId}-${id}`, и без неё строка таблицы туда не доедет. */
  staffUnitId?: string;
}
