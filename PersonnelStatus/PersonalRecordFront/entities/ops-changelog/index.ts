/** Новые сверху. НЕ мутирует вход: голый .sort() перетасовал бы фикстуру
 * вызывающего. Сравнение строк ISO лексикографически совпадает с
 * хронологическим — Date не нужен. */
export function sortFixesByRelease(fixes: readonly FixEntry[]): FixEntry[] {
  return [...fixes].sort((a, b) => b.releasedAt.localeCompare(a.releasedAt));
}

/** '2026-07-19' → '19.07.2026' ПЕРЕСТАНОВКОЙ СТРОКИ: new Date(iso) парсится
 * как UTC-полночь и в минусовой зоне откатывает дату на сутки. */
export function formatJournalDate(iso: string): string {
  const [year, month, day] = iso.split("-");
  return `${day}.${month}.${year}`;
}
