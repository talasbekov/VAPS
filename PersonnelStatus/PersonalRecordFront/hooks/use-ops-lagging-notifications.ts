"use client";

// Личная лента уведомлений раздела ОМ — «напоминания об отставших».
//
// Ключ кэша СВОЙ и НЕ пересекается с ['ops-ratings','notifications']: там
// уведомления оценивания (готовый текст, свой канал), здесь — факты сдачи. Их
// объединение означало бы, что кадр WS оценок перечитывает эту ленту, а её
// обновление стирает ту.
import { useQuery } from "@tanstack/react-query";
import { apiClient, type OpsNotificationPage } from "@/lib/api";

/**
 * Свои уведомления, свежие сверху. Дата не передаётся: лента отвечает на
 * вопрос «что мне пришло», а не «что было в такой-то день», и деловая дата
 * приезжает у каждой строки своя.
 *
 * Гейт ручки — аутентификация, поэтому `enabled` здесь нет: право
 * «Статусы: просмотр» закрывает светофор, но не чужую-свою ленту, и завязать
 * её на тот же гейт значило бы спрятать собственные напоминания от того, кому
 * они адресованы.
 */
export function useOpsLaggingNotifications() {
  return useQuery<OpsNotificationPage>({
    queryKey: ["ops-notifications", "feed"],
    queryFn: () => apiClient.getOpsNotifications(),
  });
}
