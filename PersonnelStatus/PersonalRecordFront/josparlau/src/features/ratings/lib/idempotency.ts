// Ключ идемпотентности отправки и исправления (§19.26).
//
// Ключ живёт ОДНУ форму и переживает её повторные отправки: в этом и смысл —
// человек, не дождавшийся ответа, жмёт «Отправить» ещё раз, и второй запрос
// обязан вернуть результат первого, а не создать вторую оценку. Новый ключ на
// каждую попытку сделал бы защиту бессмысленной ровно в том случае, ради
// которого она заведена.
//
// В ключе НЕТ ни одного значения записи: ключ, собранный из полей формы, нёс бы
// закрытый комментарий и оценку целиком — в заголовке запроса, в журнале
// сервера и в любом снимке состояния.

let fallbackCounter = 0

export function newIdempotencyKey(): string {
  const api = globalThis.crypto
  if (api !== undefined && typeof api.randomUUID === 'function') return api.randomUUID()
  // Окружения без Web Crypto (старые движки, часть тестовых сред) не должны
  // ронять отправку: ключ обязан быть уникальным в пределах вкладки, а не
  // криптостойким — сервер сверяет его как строку.
  fallbackCounter += 1
  return `idem-${fallbackCounter}-${String(performance.now()).replace('.', '-')}`
}
