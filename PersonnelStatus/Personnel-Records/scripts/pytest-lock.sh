#!/usr/bin/env bash
# Замок тестовой базы (Plane №107, по следам двух столкновений 26.08.2026).
#
# ЗАЧЕМ. Две сессии в одном дереве делят одну тестовую базу. Второй запуск
# ломает первый, и выглядит это НЕ как конфликт, а как дефект кода: все тесты
# файла краснеют разом на setup (ассерты при этом не падают), время прогона в
# 4-5 раз больше обычного, повтор — зелёный. За день так потеряли два прогона.
#
# ПОЧЕМУ НЕ ХВАТИЛО ОБЪЯВЛЕНИЯ «беру базу». Сообщение между сессиями приходит
# на следующем обращении к инструментам, а не мгновенно: между «я объявил» и
# «ты прочитал» помещается целый прогон. `ps | grep pytest` перед стартом не
# спасает по той же причине — два старта в одну секунду видят пустой список
# оба.
#
# `mkdir` АТОМАРЕН: каталог либо создаётся, либо нет — поэтому замок каталогом,
# а не файлом с проверкой существования.
#
# Использование:
#   bash scripts/pytest-lock.sh .venv/bin/python -m pytest <аргументы>
#   PYTEST_LOCK_WAIT=300 bash scripts/pytest-lock.sh ...   # подождать очереди
set -u

LOCK="${PYTEST_LOCK:-/tmp/claude-1000/pytest.lock}"
WHO="${PYTEST_LOCK_OWNER:-$(whoami)@$$}"
WAIT="${PYTEST_LOCK_WAIT:-0}"

mkdir -p "$(dirname "$LOCK")" 2>/dev/null

waited=0
until mkdir "$LOCK" 2>/dev/null; do
  owner=$(cat "$LOCK/owner" 2>/dev/null || echo "неизвестно кто")
  if [ "$WAIT" -le 0 ] || [ "$waited" -ge "$WAIT" ]; then
    echo "[pytest-lock] база занята: $owner"
    echo "[pytest-lock] подождать — PYTEST_LOCK_WAIT=300; снять брошенный замок — rm -rf $LOCK"
    exit 75
  fi
  sleep 5
  waited=$((waited + 5))
done

echo "$WHO" > "$LOCK/owner"
# Замок снимается ДАЖЕ при падении прогона: брошенный замок хуже гонки — он
# останавливает всех, и снимать его пришлось бы руками.
trap 'rm -rf "$LOCK"' EXIT INT TERM

echo "[pytest-lock] база занята мной ($WHO)"
"$@"
