"""Схема обязана объявлять то, что ручка требует (Plane №151, следствие №63).

ЧТО ЛОВИТ. Ручку, которая без параметра отвечает «параметр обязателен», а в
схеме ни одного обязательного параметра не объявляет. Клиент, сгенерированный
по такой схеме, получает метод БЕЗ аргументов, который падает ВСЕГДА, — и
выясняется это только в рантайме.

ПОЧЕМУ ПРОБА ОБХОДИТ СХЕМУ, А НЕ СПИСОК ИЗ СЕМИ АДРЕСОВ. Список пришлось бы
дописывать руками при каждой новой ручке, то есть он устарел бы к следующей
задаче. Проба идёт от схемы: появится восьмая такая ручка — покраснеет здесь,
а не у того, кто по схеме генерировал клиент.

ГРАНИЦА. Проверяются GET-коллекции без параметров пути в разделах, которые
ведёт этот проект. Ответ 5xx проба НЕ трогает: падение сервера — своя беда и
свой разбор, здесь речь только о честности объявления.
"""
import pytest

from organization_management.apps.operations.tests.test_bulk_status_api import (
    client_for,
)

pytestmark = pytest.mark.django_db

#: Разделы, которые ведёт проект. Чужие маршруты (django admin, служебные)
#: сюда не попадают: чинить их — не эта задача.
OWNED_PREFIXES = ("/api/ops/", "/api/operations/", "/api/statuses/")

#: Коды, которыми ручка говорит «в запросе чего-то не хватает». 403 и 404 сюда
#: НЕ входят: 403 — про право, 404 — про адрес, и оба к объявлению параметров
#: отношения не имеют.
MISSING_PARAM_STATUSES = (400, 422)

#: Имена, которыми ответ говорит «раздел не настроен», а НЕ «вы не прислали
#: параметр». Настройка чинится сидом, объявление — схемой; путать их значит
#: обвинять ручку в чужой беде.
CONFIGURATION_FIELDS = {"flags", "policy", "settings"}


def _named_fields(response):
    """Имена, названные в `details` ответа. Пусто — ответ не сказал, чего ему
    не хватило, и обвинять его не в чем: проба судит по названному, а не по
    догадке."""
    try:
        body = response.json()
    except ValueError:
        return set()
    details = body.get("details")
    return set(details) if isinstance(details, dict) else set()


@pytest.fixture
def admin_api(db):
    """Полный доступ: проба про ОБЪЯВЛЕНИЕ параметров, а не про права.
    Под слабым актором половина ручек ответила бы 403, и проверять было бы
    нечего."""
    api, _ = client_for("schema-walker", "SCHEMA_WALKER", perms=("*",))
    return api


def collection_gets(schema):
    """GET-коллекции наших разделов: без параметров пути и без явного
    исключения. Деталь по id (`{id}`) не проверяется — у неё параметр в пути,
    и он в схеме есть по построению."""
    for path, methods in schema["paths"].items():
        if not path.startswith(OWNED_PREFIXES):
            continue
        if "{" in path:
            continue
        operation = methods.get("get")
        if operation is None:
            continue
        yield path, operation


def declares_any_query_param(operation):
    """Есть ли у метода ХОТЬ ОДИН объявленный query-параметр.

    Критерий именно такой, а не «есть обязательный». Дефект, ради которого
    проба написана, звучит так: клиент, сгенерированный по схеме, получает
    метод БЕЗ АРГУМЕНТОВ, которому нечего передать. Лечится это объявлением
    параметров — а вот `required=True` подходит НЕ ВСЕМ.

    Пример, на котором первая редакция пробы споткнулась: у аналитики период
    задаётся ЛИБО кодом пресета, ЛИБО парой дат. Обязателен не параметр, а
    выбор между ними, и пометить `required=True` нельзя ни на одном из трёх —
    это соврало бы про два других. Клиенту при этом есть что передать, и
    исходной беды нет.

    Там, где обязателен именно ОДИН параметр (`division_id`, даты периода,
    `employee`), `required=True` стоит — это отдельное, более сильное
    утверждение, и его стерегут свои пробы.
    """
    return any(
        param.get("in") == "query"
        for param in operation.get("parameters", [])
    )


def test_no_endpoint_demands_what_the_schema_hides(admin_api, client):
    """Главная проба: ручка требует параметр — схема обязана его объявить.

    Красная проба этого сторожа — снять `required=True` у любой из ручек,
    приведённых в порядок по Plane №151: она немедленно окажется в списке.
    """
    schema = client.get("/api/schema/?format=json").json()

    liars = []
    for path, operation in collection_gets(schema):
        if declares_any_query_param(operation):
            continue
        try:
            response = admin_api.get(path)
        except Exception:
            # Ручка упала на ПУСТОЙ тестовой базе (нет справочника, нет
            # политики, нет фикстуры). Это своя беда со своим разбором, и к
            # честности объявления параметров она отношения не имеет. Молча
            # пропускаем — иначе сторож объявления превратился бы в сторож
            # фикстур и краснел бы по чужому поводу.
            continue
        if response.status_code not in MISSING_PARAM_STATUSES:
            continue
        named = _named_fields(response)
        if not named:
            continue
        # РАЗЛИЧЕНИЕ, без которого проба бесполезна: 4xx на голом вызове бывает
        # по двум РАЗНЫМ причинам, и лечатся они в разных местах.
        #
        # «Не прислали параметр» называет ИМЯ ПАРАМЕТРА: from, to,
        # division_id, employee. Это и есть дефект №151 — схема о параметре
        # молчит, клиент передать его не может.
        #
        # «Раздел не настроен» называет НАСТРОЙКУ: flags, policy. Схема тут ни
        # при чём, лечится это сидом, а не объявлением. Первая редакция пробы
        # их не различала и обвиняла восемь невиновных ручек — включая
        # /api/ops/personnel/, у которой параметров не требуется вовсе.
        if named & CONFIGURATION_FIELDS:
            continue
        liars.append((path, response.status_code, sorted(named)))

    assert liars == [], (
        "эти ручки требуют параметр, но в схеме его не объявляют — "
        "сгенерированный по схеме клиент получит метод, который всегда падает: "
        + ", ".join(
            f"{path} → {code}, требует {names}" for path, code, names in liars
        )
    )


def test_the_walk_actually_visits_something():
    """Сторож сторожа: обход, нашедший ноль ручек, зелен всегда.

    Без этой пробы опечатка в префиксе или в разборе схемы превратила бы
    главную пробу в вечнозелёную — она проверяла бы пустой список.
    """
    from django.test import Client

    schema = Client().get("/api/schema/?format=json").json()
    visited = list(collection_gets(schema))

    assert len(visited) > 30, (
        f"обход схемы нашёл всего {len(visited)} GET-коллекций — "
        "похоже, сломан разбор схемы, а не система"
    )
