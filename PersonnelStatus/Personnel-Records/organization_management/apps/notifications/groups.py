#: Поле `type` конверта КАНАЛЬНОГО СЛОЯ: по нему channels выбирает обработчик
#: (точки заменяются подчёркиваниями → `NotificationConsumer.notification_message`).
#: Здесь по той же причине, что и имя группы: опечатка в нём — не ошибка
#: импорта, а падение потребителя на немаршрутизируемом конверте уже в бою.
NOTIFY_MESSAGE_TYPE = "notification.message"


def group_name_for(user_id) -> str:
    """Имя группы канального слоя для пользователя портала.

    Единственная точка правды: и потребитель (`consumers.py`), и оба издателя
    (`signals.py`, `services/websocket_service.py`) обязаны звать ОТСЮДА.
    """
    if user_id is None or str(user_id).strip() == "":
        raise ValueError("group_name_for требует пользователя")
    return f"user_{user_id}"
