from django.apps import AppConfig


class NotificationsConfig(AppConfig):
    """Настройка раздела уведомлений портала.

    Обработчиков сигналов у раздела НЕТ — см. разбор ниже (Plane №866).
    Уведомления раздела ОМ создаются явными вызовами
    (`apps/operations/notify_service.py`), а не побочным эффектом сохранения
    модели.
    """

    name = "organization_management.apps.notifications"
    # 🔴 ОБРАБОТЧИКОВ СИГНАЛОВ У РАЗДЕЛА БОЛЬШЕ НЕТ, И `ready()` НИЧЕГО НЕ
    # ПОДКЛЮЧАЕТ (Plane №866, решение заказчика 06.09.2026: «снять как мёртвый
    # порт»).
    #
    # Что здесь стояло. `ready()` импортировал `signals.py` с тремя
    # обработчиками — новая заявка на прикомандирование, смена статуса
    # сотрудника, правка карточки, — и глушил любой отказ. Отказ был
    # постоянным: модуль импортировал `EmployeeStatusLog` из
    # `apps.statuses.models`, а такой модели в этом репозитории НЕТ ВОВСЕ — её
    # нет ни в моделях, ни в миграциях, ни в истории git. То есть ни один из
    # трёх обработчиков не подключался НИ РАЗУ, и уведомления по этим событиям
    # не создавались нигде — ни в базе, ни в сокете.
    #
    # Почему снято, а не оживлено. Файл написан по-английски и ссылается на
    # модель чужого проекта; живые уведомления раздела ОМ идут другим путём
    # (`apps/operations/notify_service.py`), а оживление означало бы ЗАМЕТНУЮ
    # смену поведения — люди начали бы получать уведомления, которых сегодня
    # нет. Это вопрос о продукте, и заказчик ответил на него прямо.
    #
    # 🔴 ПОВЕДЕНИЕ ЭТИМ НЕ ИЗМЕНИЛОСЬ НИ НА ЙОТУ: снят код, который не
    # выполнялся. Если обработчики понадобятся — их заводят заново и осознанно,
    # а не воскрешают этот файл; проба
    # `tests_notification_signals_are_gone.py` покраснеет и напомнит об этом
    # решении.
    default_auto_field = "django.db.models.BigAutoField"
