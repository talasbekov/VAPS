"""Водяной знак материализации (порт Watermark из Backend/VAPS
apps/core/models.py).

Фоновые работы раздела — догон побочных эффектов статусов, поиск отставших
сдач — идут ДЕНЬ ЗА ДНЁМ и переживают простой: после суток без запуска работа
обязана пройти пропущенные дни по порядку, а не «за сегодня». Помнить, докуда
дошли, ей нужно в БД, а не в памяти процесса: перезапуск не должен ни повторять
уже сделанное, ни проглатывать пропущенное.

ТАБЛИЦА РЯДОМ, своя (ops_watermarks) — тот же приём strangler, что и с журналом
и статусами: у старого проекта своего учёта материализации нет вовсе, а
ближайший по смыслу Celery-beat помнит расписание, а не пройденные ДЕЛОВЫЕ дни.

Строка на работу, ключ — имя работы. Одна общая строка «последний обработанный
день» была бы ложью: у догона эффектов и у поиска отставших свои горизонты
(вторая ещё и ждёт контрольного часа), и общий знак затянул бы одну работу за
другой.

Отличия от источника: int-pk (у старой структуры всё целочисленное) и CHECK на
непустой ключ — в источнике его нет. Пустой ключ означал бы «водяной знак ни за
чем», и две работы, обе забывшие ключ, молча поделили бы одну строку: одна
угоняла бы знак другой, и каждая пропускала бы дни соседа.
"""
from django.db import models


class OpsWatermark(models.Model):
    """Докуда работа `key` доматериализовала деловые дни.

    Даты БЕЗ значения по умолчанию намеренно: «никогда не запускалась» — это
    ОТСУТСТВИЕ строки, а не строка с датой NOW(). Откуда начинать при первом
    запуске, решает сама работа (свежая выкатка не отматывает историю назад),
    и молчаливый дефолт отнял бы у неё это решение.
    """

    key = models.CharField(max_length=100, unique=True)
    last_materialized_date = models.DateField()
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "ops_watermarks"
        verbose_name = "Водяной знак материализации"
        verbose_name_plural = "Водяные знаки материализации"
        constraints = [
            models.CheckConstraint(
                condition=~models.Q(key__regex=r"^\s*$"),
                name="chk_ops_watermark_key",
            ),
        ]

    def __str__(self):
        return f"{self.key}: {self.last_materialized_date}"
