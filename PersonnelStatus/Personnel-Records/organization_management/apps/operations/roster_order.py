"""Канон порядка личного состава (порт apps/core/sorting.py из Backend/VAPS).

ОДИН ПОРЯДОК НА ВЕСЬ РАЗДЕЛ. Списки, печатная форма и выгрузки обязаны
перечислять людей одинаково: расхождение между экраном и подписанной бумагой
читается как расхождение в данных, и проверять его будут не глазами, а
разбирательством.

Сегодня состав в документе идёт в порядке employee_id — то есть в порядке
появления строк в базе. Для читателя это отсутствие порядка: старший по должности
может стоять между двумя рядовыми только потому, что его завели позже.

ПОРЯДОК: сначала СВОИ по уровню должности (меньше число — выше должность), внутри
уровня по фамилии; затем блок приданных, затем блок откомандированных.

ГРУППА — ВХОД, А НЕ ВЫВОД. Канон не решает, кто приданный: это знание про
прикомандирования на дату, и живёт оно в статусах. Модуль остаётся ЧИСТЫМ (ни
Django, ни ORM, ни обращения к справочникам) — так его может звать и построитель
снимка, и рендерер документа, и тесты без базы.
"""
from enum import IntEnum

# Уровень для того, чья должность не нашлась в справочнике. Больше любого
# настоящего уровня, поэтому такой человек встаёт в КОНЕЦ СВОЕЙ ГРУППЫ — не в
# начало (он не старший) и не в конец списка (он не перестал быть своим оттого,
# что справочник неполон). Падать здесь нельзя вовсе: неполный справочник —
# обычное состояние на пилоте, а расход печатают каждый день.
UNKNOWN_LEVEL = 10**9


class RosterGroup(IntEnum):
    """Блок, в котором человек стоит. Значение И ЕСТЬ порядок блоков.

    Блоки идут именно так, потому что документ читают сверху вниз: свои — это
    те, за кого подразделение отвечает; приданные — те, кто у него сегодня
    сверх штата; откомандированные — те, кого у него сегодня нет. Смешать их
    значило бы заставить читателя выяснять принадлежность по каждой строке.
    """

    OWN = 0
    ATTACHED = 1
    DETACHED = 2


def _surname_key(full_name):
    """Ключ сравнения по фамилии: регистр не важен, «ё» равна «е».

    «Ё» стоит В КОДИРОВКЕ РАНЬШЕ «А» (U+0401 против U+0410), поэтому наивное
    сравнение строк уводит Ёлкина в самое начало списка — перед Абрамовым. Это
    не теоретическая придирка: одна такая фамилия ломает алфавит на глазах у
    того, кто документ подписывает.

    Сравнение регистронезависимо: «фон Дер» и «Фон дер» — одна фамилия,
    записанная по-разному, и раскидывать их по разным концам алфавита незачем.
    """
    return (full_name or "").strip().casefold().replace("ё", "е")


def sort_key(entry):
    """Ключ канона для одной записи состава.

    Запись — любой объект с полями group / position_level / full_name /
    employee_id (словарь снимка подходит как есть).

    ПОСЛЕДНИЙ КЛЮЧ — employee_id, и он обязателен. Однофамильцы на одном уровне
    должности бывают, и без разрыва ничьей документ, собранный дважды из одних
    данных, выходил бы разным — а его сравнивают с предыдущим, чтобы увидеть,
    что изменилось за сутки.
    """
    group = entry.get("group", RosterGroup.OWN)
    level = entry.get("position_level")
    return (
        int(group),
        UNKNOWN_LEVEL if level is None else level,
        _surname_key(entry.get("full_name")),
        entry.get("employee_id"),
    )


def order_roster(entries):
    """Состав в каноническом порядке. Вход не мутируется."""
    return sorted(entries, key=sort_key)
