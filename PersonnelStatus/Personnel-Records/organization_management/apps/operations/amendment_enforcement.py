"""Принуждение к поправке: ретро-правка накрытого сданного дня ОБЯЗАНА
породить поправку (порт submissions/amendment_enforcement.py из Backend/VAPS).

Инвариант один и он несущий: сданный день заявляет расход, и правка статуса
задним числом делает заявление неверным. Либо расход перестаёт соответствовать
данным — и тогда у одного дня две правды, — либо правку запрещают вовсе.
Раздел выбирает третье: правка проходит, но ОБЯЗАНА вытеснить сданное новой
версией. Поправка здесь не наказание и не согласование, а способ сохранить
единственность правды.

Поправка ставится АВТОМАТИЧЕСКИ, а не требуется от оператора отдельным
действием: забытая поправка неотличима от честной сдачи, и обнаружилась бы
она у того, кто читает расход, а не у того, кто правил.

ЗАТРОНУТЫЕ ДНИ — ОБЪЕДИНЕНИЕ полуинтервалов, не их габарит. Правка, разнесённая
на два непересекающихся периода, габаритом накрыла бы дни в промежутке между
ними — и день, о котором никто ничего не менял, вышел бы поправленным с
чужой санкцией. Верхняя граница исключена: полуинтервал [начало, конец) везде
в разделе значит одно и то же.

ЧИСТОГО МОДУЛЯ ЗДЕСЬ НЕТ намеренно: обнаружение — это запрос к сданному, и
разносить «какие дни» и «какие из них сданы» по разным модулям значило бы
завести владельца, который знает половину ответа. Часы не читаются: дни
приходят интервалами правки.

ОТЛИЧИЕ ОТ ИСТОЧНИКА — прямой вызов вместо слота-инверсии. Там statuses и
submissions разные приложения, стрелка между ними односторонняя, и обращение
наверх приходилось разворачивать поздним связыванием через
`register_amendment_handler`. Здесь раздел один пакет, цикла импортов нет
(сдача не знает о правке статусов), и слот был бы церемонией без адресата.
"""
from datetime import timedelta

from organization_management.apps.operations.day_submission_service import amend_day
from organization_management.apps.operations.selectors import DailySubmissionSelector

# Причина автоматической поправки. Санкцией едет причина САМОЙ правки: она
# объясняет, что и почему изменили, а эта строка — лишь как поправка
# появилась. Поменять их местами значило бы записать в объяснение дня
# служебный текст, одинаковый у всех поправок раздела.
AUTO_AMENDMENT_REASON = "Авто-поправка: ретро-правка статуса под сданным днём."


def affected_days(intervals):
    """Дни, накрытые полуинтервалами [начало, конец), — объединением.

    Пустой и вывернутый интервал не дают ни одного дня: у них нет ни одного
    дня внутри, и трактовать их как «весь диапазон» было бы догадкой.
    """
    days = set()
    for date_start, date_end in intervals:
        day = date_start
        while day < date_end:
            days.add(day)
            day += timedelta(days=1)
    return days


def enforce_amendment_on_retro_edit(
    employee_id, intervals, *, actor, reason, triggered_by_status_id=None
):
    """Поправить каждый сданный день, накрытый ретро-правкой.

    Вызывается ВНУТРИ транзакции правки: поправка обязана лечь тем же
    коммитом, что и сама правка. Иначе между ними существует момент, в
    котором сданный день уже не соответствует данным, а объяснения этому
    ещё нет, — и любой сбой на этом промежутке оставляет расхождение
    навсегда.

    Возвращает список созданных поправок — по одной на накрытый день;
    вызывающему они нужны не для отчёта, а чтобы решить, писать ли о правке
    в журнал как об обычной или как о задевшей сданное.
    """
    return [
        amend_day(
            division_id=submission.division_id,
            business_date=submission.business_date,
            actor=actor,
            reason=AUTO_AMENDMENT_REASON,
            sanction=reason,
            triggered_by_status_id=triggered_by_status_id,
        )
        for submission in DailySubmissionSelector.covering(
            employee_id, affected_days(intervals)
        )
    ]
