"""Где лежат байты вложения и по какому адресу их отдаёт веб-сервер (порт
контракта хранения из Backend/VAPS apps/documents/services.py).

Модуль отвечает на ОДИН вопрос — «путь», — и потому не читает базу, не пишет
файлов и ничего не проверяет. Разделение не ради красоты: путь нужен и записи,
и сверке, и отдаче, а каждая из этих троих появляется своим срезом. Собери его
на месте — и три места начнут расходиться в том, где именно лежит файл.

РАСКЛАДКА ПЛОСКАЯ: {корень}/{storage_key}, без подкаталогов и без расширения.
Подкаталоги по дате или по подразделению просились бы сами, но они кодируют в
пути ФАКТЫ (когда, чей), и переезд документа между подразделениями или правка
даты превращались бы в переезд файла. Имя, тип и дата живут в строке — там их
можно менять, не трогая диск.

ИМЯ НА ДИСКЕ НЕ ПРОИЗВОДНО ОТ ИМЕНИ ФАЙЛА. Это граница безопасности, а не
удобство: `original_name` приходит от клиента и содержит что угодно, включая
«..» и разделители пути. Собранный из него путь уводил бы запись за пределы
каталога. Здесь он не участвует вовсе — только в заголовке отдачи.
"""
from pathlib import Path

from django.conf import settings


def storage_root():
    """Корень приватного хранилища."""
    return Path(settings.OPS_PRIVATE_STORAGE_ROOT)


def storage_path(attachment):
    """Путь к байтам вложения — производен от storage_key, и только от него."""
    return storage_root() / str(attachment.storage_key)


def xaccel_redirect_path(attachment):
    """Адрес внутренней локации nginx для отдачи байтов вложения.

    Хвостовой слэш локации срезается: `/ops-private/` из окружения дал бы
    `//{key}`, а двойной слэш в начале пути браузер и часть прокси читают как
    начало АВТОРИТЕТА (`//host/...`) — заголовок перестал бы указывать внутрь.
    """
    location = str(settings.OPS_XACCEL_LOCATION).rstrip("/")
    return f"{location}/{attachment.storage_key}"
