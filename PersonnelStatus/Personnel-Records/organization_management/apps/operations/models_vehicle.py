"""Реестр транспорта Гаража особого назначения (Plane №215).

ЗАЧЕМ. Документ «04 Список броней в ГОН» из списка №156 нечем наполнить: в
системе нет автопарка вовсе. Ближайшее, что есть, — строки «Выделяемый
транспорт» внутри сводки ГВО, и это свободный текст без ГРНЗ и класса брони:
по нему нельзя ни отобрать машины нужного класса, ни посчитать их, ни
сказать, где машина стоит. Решение заказчика 27.08.2026 по вопросу №170 —
завести реестр, а не выдумывать данные в документе.

ПОЛЯ ВЗЯТЫ ИЗ ОБРАЗЦА, а не придуманы:
`docs/PersonnelStatus/04 Список броней в ГОН 05.91.2025 г. обнов.docx` —
одна таблица на восемь колонок: № п/п, марка автомобиля, классификация по
кузову, год выпуска, ГРНЗ, класс брони, дислокация, примечание. Номер строки
в модели не хранится: это порядок В ДОКУМЕНТЕ, а не признак машины.

ВЛАДЕЛЬЦА ПАРКА отдельной сущностью нет. В шапке образца он назван один —
РГП «Автохозяйство УДП РК», — и заводить под него справочник значило бы
строить иерархию, которой ещё никто не пользуется.
"""
from django.db import models

from organization_management.apps.operations.models import TimeStampedModel


class OpsVehicle(TimeStampedModel):
    """Одна машина реестра ГОН."""

    #: Марка автомобиля целиком, как в образце: «Mercedes-Benz S680 Maybach
    #: 4 М (брон.)». Разбирать её на марку и модель незачем — отбора по
    #: модели документ не просит, а разбор чужой строки теряет пометки вроде
    #: «(брон.)», которые в ней значимы.
    brand = models.CharField(max_length=200)
    #: Классификация по кузову: в образце «седан (223)» — тип и код кузова
    #: одной строкой, как их пишет автохозяйство.
    body_class = models.CharField(max_length=100, blank=True)
    #: Год выпуска. Числом, а не строкой: по нему сортируют и отбирают.
    #: Пусто допустимо — в образце год стоит не у каждой строки.
    production_year = models.PositiveSmallIntegerField(null=True, blank=True)
    #: Государственный регистрационный номерной знак.
    plate = models.CharField(max_length=32)
    #: Класс брони: в образце VR7. Свободная строка, а не перечисление:
    #: классов брони больше, чем встречается в одном документе, и запирать
    #: справочник в выбор из трёх значений значит чинить его миграцией при
    #: первой же новой машине.
    armor_class = models.CharField(max_length=32, blank=True)
    #: Дислокация — где машина стоит («Алматы»). В образце чаще пусто.
    deployment = models.CharField(max_length=200, blank=True)
    #: Примечание — в образце «Автохозяйство».
    note = models.TextField(blank=True)
    #: Мягкое скрытие, как у охраняемых лиц: удаление стёрло бы машину из
    #: истории мероприятий, где она уже выделена.
    is_active = models.BooleanField(default=True)

    class Meta:
        db_table = "ops_vehicles"
        ordering = ["brand", "plate", "id"]
        verbose_name = "транспорт ГОН"
        verbose_name_plural = "Транспорт ГОН"
        constraints = [
            # ГРНЗ уникален СРЕДИ ДЕЙСТВУЮЩИХ, а не вообще: две живые машины
            # с одним номером — это опечатка, а не парк. У снятых номер
            # повторяться может: номер переходит к другой машине, и запрет
            # мешал бы завести её, не стирая историю прежней.
            models.UniqueConstraint(
                fields=["plate"],
                condition=models.Q(is_active=True),
                name="uniq_ops_vehicle_active_plate",
            ),
        ]

    def __str__(self):
        return f"{self.brand} ({self.plate})"
