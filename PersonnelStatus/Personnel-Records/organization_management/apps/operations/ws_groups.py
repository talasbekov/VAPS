"""Адресация уведомлений раздела в канальном слое (порт apps/notifications/
groups.py из Backend/VAPS).

Это ОБЩИЙ ДОГОВОР, а не вспомогательная функция: следующий срез вкручивает
`group_send` в notify() и обязан звать ОТСЮДА. Две реализации «как зовётся
группа получателя», разошедшиеся между собой, ничего не роняют — они молча
доставляют в группу, которую никто не слушает.
"""
from hashlib import sha256

# Поле `type` конверта КАНАЛЬНОГО СЛОЯ: по нему channels выбирает обработчик
# (точки заменяются подчёркиваниями → OpsNotificationConsumer.notify_message).
# Вынесено сюда по той же причине, что и имя группы: отправитель должен слать
# ЭТУ строку, а опечатка в ней — не ошибка импорта, а падение потребителя на
# немаршрутизируемом конверте в проде. Код вида уведомления, который видит
# клиент, — другое поле, оно едет ВНУТРИ event["message"].
NOTIFY_MESSAGE_TYPE = "ops.notify.message"


def group_name_for(recipient: str) -> str:
    """Имя группы канального слоя для получателя — детерминированное и всегда
    допустимое.

    Хэш, а не сырой получатель: channels проверяет имя группы по
    `^[a-zA-Z\\d\\-_.]+$` с потолком в 100 символов
    (`BaseChannelLayer.valid_group_name`), а получатель — произвольная строка
    до 100 символов (сегодня это str(User.pk), но поле заведено под будущий
    внешний КУ, где достижимы и `@`, и `:`, и кириллица). Каждый такой символ
    роняет `group_add` в рантайме.

    Замена «плохих» символов отвергнута: `a@b` и `a_b` схлопнулись бы в одно
    имя, и уведомления одного получателя поехали бы другому. 32 hex-символа
    sha256 держат имя далеко под потолком.

    Пустой получатель — ValueError (зеркало гварда notify()): это ошибка
    вызывающего, а не состояние рантайма.
    """
    if not recipient or not recipient.strip():
        raise ValueError("group_name_for требует получателя")
    digest = sha256(recipient.strip().encode("utf-8")).hexdigest()
    return f"ops.notif.{digest[:32]}"
