"""Выгрузка расхода за период: одна таблица, СТРОКА НА ДАТУ.

Дневной документ отвечает на вопрос «кто где был в этот день» и раскладывается
строкой на подразделение. Период отвечает на другой вопрос — «как это менялось»
— и потому раскладывается строкой на ДАТУ. Свести их в один рендерер нечем: у
одного ось «подразделение», у другого «время», и общая функция печатала бы одну
из осей поперёк смысла.

ЧЕРЕЗ СВОЙ РЕНДЕРЕР, А НЕ СКЛЕЙКОЙ ДНЕВНЫХ. Склеенные подряд шестьдесят
дневных таблиц — это шестьдесят шапок и шестьдесят итогов в одном файле, и ни
один потребитель CSV не прочитает такое как таблицу: ни отсортировать, ни
сложить, ни построить график. Ради того период и смотрят одним файлом.

Диалект — тот же, что у дневного .csv, и это не совпадение: файлы открывает тот
же человек в том же Excel. Разойдись они разделителем или кодировкой — вторая
выгрузка открылась бы мусором ровно у того, для кого делалась.

СОСТАВА ЗДЕСЬ НЕТ, как и в дневном .csv: поимённые списки за два месяца — это
не таблица, а её отсутствие. Кому нужен состав, тот берёт день.
"""
import csv
import io

from organization_management.apps.operations.expense_layout import (
    ATTACHED_LABEL,
    column_label,
)

DATE_HEAD = "Дата"
STAFF_HEAD = "По штату"
LIST_HEAD = "По списку"
VACANCIES_HEAD = "Вакансии"


def _title(pages):
    first, last = pages[0]["business_date"], pages[-1]["business_date"]
    if first == last:
        return f"Расход личного состава за {first}"
    return f"Расход личного состава за период {first} — {last}"


def _columns_of(pages):
    """Порядок колонок берётся у ПЕРВОЙ страницы и держится для всех.

    Строки таблицы обязаны иметь одинаковую ширину и одинаковый смысл ячеек;
    пересчитывай мы порядок на каждой странице, справочник, дополненный посреди
    периода, сдвинул бы половину столбцов относительно шапки — и файл выглядел
    бы заполненным, оставаясь неверным.
    """
    return list(pages[0]["totals"]["columns"])


def generate_period_csv(pages):
    """Страницы периода → байты .csv. Пустой период — только шапка, не отказ.

    Пустого периода не бывает (границы включительны, и даже один день даёт
    страницу), но рендерер об этом не знает и знать не должен: он печатает то,
    что дали.
    """
    buffer = io.StringIO()
    writer = csv.writer(buffer, delimiter=";")

    if not pages:
        writer.writerow([DATE_HEAD, STAFF_HEAD, LIST_HEAD, VACANCIES_HEAD])
        return buffer.getvalue().encode("utf-8-sig")

    columns = _columns_of(pages)
    writer.writerow([_title(pages)])
    writer.writerow(
        [
            DATE_HEAD,
            STAFF_HEAD,
            LIST_HEAD,
            VACANCIES_HEAD,
            *(column_label(column) for column in columns),
            ATTACHED_LABEL,
        ]
    )

    for page in pages:
        totals = page["totals"]
        writer.writerow(
            [
                page["business_date"],
                totals["staff_total"],
                totals["list_total"],
                totals["vacancies"],
                # .get, а не [...]: колонка, появившаяся в справочнике посреди
                # периода, отсутствует у ранних страниц — и её отсутствие это
                # ноль, а не обрыв выгрузки на середине.
                *(totals["columns"].get(column, 0) for column in columns),
                totals["attached"],
            ]
        )

    # Итоговой строки СУММ здесь нет намеренно: сложить расходы разных дней не
    # во что (человек в отпуске три дня дал бы «три отпуска»). Строка «ИТОГО»
    # выглядела бы осмысленной и была бы неверной, а это хуже её отсутствия.
    return buffer.getvalue().encode("utf-8-sig")
