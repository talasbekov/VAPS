"""Отправка уведомления раздела (порт notify() из Backend/VAPS
apps/notifications/services.py).

Единственная точка записи ops_notifications — как record(...) у журнала.

Две вещи здесь неочевидны и обе намеренны.

ПЕРВАЯ: запись идёт СИНХРОННО, внутри транзакции вызывающего. Уведомление —
следствие делового факта, и жить оно должно вместе с ним: откат операции обязан
унести и уведомление о ней, иначе получатель узнаёт о том, чего не случилось.
Отложить запись «до коммита» значило бы развести их.

ВТОРАЯ: сбой отправки НЕ роняет вызывающую операцию — он пишется в журнал
процесса и глотается (возвращается None). Уведомление — побочный канал: сдача
дня принята, статус создан, и падать из-за того, что кому-то не сообщили, они
не должны. Это верно ДЛЯ ВЫЗЫВАЮЩИХ, у которых уведомление побочно; там, где
уведомление и ЕСТЬ вся операция (догон отставших), None надо превращать в
ошибку самому — иначе водяной знак уедет за день, о котором не сообщили.

ТРЕТЬЯ (этот срез): созданная строка ДОПОЛНИТЕЛЬНО объявляется в сокет, и
разделение здесь и есть весь смысл. Запись остаётся синхронной и внутри
транзакции вызывающего (см. ПЕРВОЕ, не тронуто), а `group_send` уезжает в
`transaction.on_commit` — откатившаяся деловая операция не может подать знак о
строке, которой не будет. Договор «побочный канал» распространяется на эту
ветку дословно: недоступный канальный слой пишется в журнал и глотается и НИ
ПРИ КАКИХ обстоятельствах не меняет то, что вернул notify(), — по этому
возврату догон решает, откатывать ли ему целый день.

ЧЕТВЁРТАЯ: доставку целиком гасит `settings.OPS_WS_ENABLED=0` — и гасит она
ТОЛЬКО знак. Строка пишется, возвращается и читается лентой как ни в чём не
бывало: выключатель существует ради того, чтобы снять рисковую инфраструктуру
(Channels + Redis), не тронув деловую операцию.
"""
import logging
from functools import partial

from asgiref.sync import async_to_sync
from channels.layers import get_channel_layer
