logger = logging.getLogger(__name__)


def _local_isoformat(value):
    """Момент — ровно в том виде, в каком его печатает лента чтения.

    Это и есть то, что делает DateTimeField у DRF: перевести в
    `timezone.get_current_timezone()` и позвать `.isoformat()`. Написано
    через `astimezone`, а не через `timezone.localtime(value)` — операция та
    же, но у `localtime` аргумент необязателен, и функция без аргумента читает
    стенные часы. Здесь такого пути не должно быть даже теоретически.

    Голый `.isoformat()` дал бы ДРУГУЮ строку для того же момента: created_at
    хранится в UTC, а лента печатает в часовом поясе проекта. Разойдись они —
    один и тот же ряд, пришедший сокетом и запросом, стал бы для клиента двумя
    разными, а курсор `?since=` поехал бы на пять часов.
    """
    return value.astimezone(timezone.get_current_timezone()).isoformat()


def _publish(notification):
    """Объявить `notification` в группу его получателя.

    Исполняется ТОЛЬКО как обработчик `transaction.on_commit`, никогда не
    построчно — см. notify().

    Свой `try/except` здесь не дублирует тот, что в notify(): обе ветки
    исполнения нуждаются в нём по разным причинам.

    * Внутри транзакции обработчик срабатывает ПОСЛЕ коммита, когда notify()
      давно вернул управление, и его `except` уже не на стеке. Улетевшее
      отсюда исключение всплыло бы у вызывающего ПОСЛЕ того, как деловое
      изменение применено, — худший из возможных исходов.
    * Вне транзакции (autocommit) `on_commit` зовёт обработчик НЕМЕДЛЕННО и
      построчно, то есть внутри `try` самого notify(). Без местного гварда
      мёртвый канальный слой проглотился бы ТАМ, notify() вернул бы None, а
      догон читает None как «уведомление не легло» → откат дня и остановка
      водяного знака. Сбой ЗНАКА остановил бы ДЕЛОВУЮ операцию.

    Конверт несёт проекцию ленты чтения ЗНАЧЕНИЯМИ — ряд, пришедший сокетом,
    ложится в тот же кэш, что и ряды `GET /api/operations/notifications/`.
    `api.serializers` сюда намеренно НЕ импортируется: сервис не должен знать
    про слой представления. Совпадение держит тест, а не импорт.

    Выключатель (`settings.OPS_WS_ENABLED`) проверяется САМОЙ ПЕРВОЙ строкой,
    намеренно до `try`. Смысл выключателя — не трогать рисковую инфраструктуру
    вовсе, а не аккуратно проглотить её сбой: глотать эта функция и так умеет.
    Гвард, поставленный после `get_channel_layer()`, всё равно открыл бы
    соединение к Redis и в любом зелёном тесте был бы неотличим от рабочего.
    Молчание здесь — и вся политика журнала для выключенного состояния: решение
    администратора не авария, а notify() зовётся по расписанию догона, и
    предупреждение на вызов затопило бы журнал. Сам notify() выключателем не
    затронут: погасив ЗНАК, нельзя останавливать ДЕЛОВУЮ операцию, которую
    догон ведёт по его возврату.
    """
    if not settings.OPS_WS_ENABLED:
        return

    try:
        # Здесь живут два разных поля `type` (см. ws_groups и ws_consumers):
        # ВНЕШНЕЕ (ниже, у конверта канального слоя) — маршрутизация; ЭТО —
        # код вида, который увидит клиент. Вложенный "payload" — тоже не
        # опечатка: внешний словарь это конверт, внутренний — данные факта.
        envelope = {
            "type": notification.kind,
            "payload": {
                "id": notification.id,
                "recipient": notification.recipient,
                "kind": notification.kind,
                # Каждое значение обязано быть примитивом JSON: channels_redis
                # пакует конверт msgpack-ом (а тот не умеет date/datetime), и
                # уже потребитель гонит по нему json.dumps. Голая дата рвётся
                # в рантайме и только на настоящем слое.
                "business_date": notification.business_date.isoformat(),
                "payload": notification.payload,
                # На только что созданной строке — None; приводится так же,
                # как created_at, чтобы остаться примитивом, если однажды
                # окажется заполненным.
                "read_at": (
                    _local_isoformat(notification.read_at)
                    if notification.read_at
                    else None
                ),
                "created_at": _local_isoformat(notification.created_at),
            },
        }
        async_to_sync(get_channel_layer().group_send)(
            # Адресуется ХРАНИМЫЙ получатель, а не аргумент вызова: notify()
            # обрезает края, и группа обязана следовать за обрезанным. Иначе
            # «  7  » уехал бы во вполне допустимую группу, которую никто не
            # слушает, — без единой ошибки, просто в никуда.
            group_name_for(notification.recipient),
            {"type": NOTIFY_MESSAGE_TYPE, "message": envelope},
        )
    except Exception:
        # По договору — лучшее усилие: истина это строка в базе, сокет лишь
        # знак «обнови». Поля те же, что уже пишет notify(), без ПДн: payload
        # называет отставшие подразделения и в журнал не едет.
        logger.exception(
            "WS-публикация не удалась: получатель=%r вид=%r дата=%r",
            notification.recipient,
            notification.kind,
            notification.business_date,
        )


def notify(recipient, kind, business_date, payload=None, *, dedupe_key=""):
    """Идемпотентно сообщить `recipient` о факте `kind` за `business_date`.

    «Одно на день»: первый вызов создаёт строку с `payload`, последующие —
    холостые, и побеждает ПЕРВЫЙ payload. Так и надо: повторный вызов приходит
    из догона, который переспрашивает уже пройденные дни, — переписав payload,
    он затёр бы то, что человек уже прочитал.

    🔴 `dedupe_key=None` — «СОБЫТИЕ, А НЕ СОСТОЯНИЕ ДНЯ» (Plane №677). Часть
    фактов за день случается много раз: три департамента отвечают штабу на
    запрос сил — это три разных ответа, а не три пересказа одного. Под общим
    ключом второй и третий проглатывались без следа, и штаб узнавал только про
    первый. С `None` каждый вызов заводит СВОЮ строку: NULL в уникальном
    ограничении Postgres считает различными, и `get_or_create` тут не годится
    — фильтр по `None` читается как `IS NULL` и нашёл бы прежнюю строку.
    Идемпотентности такому вызову и не нужно: он приходит из действия
    человека внутри транзакции, а не из догона, и откат уносит его вместе с
    делом.

    Непустая строка — «одно на такой ключ в день»: договор тот же, что у
    «одного на день», но с более узким ключом.

    Получатель обрезается по краям: «7» и «7 » — один человек, а для ключа
    «одно на день» это две разные строки, и пробел породил бы дубликат.

    Возвращает строку (созданную или найденную) либо None, если отправка не
    удалась. Пустой получатель — ValueError, а не None: это ошибка вызывающего,
    и глотать её вместе с инфраструктурными нельзя.

    СОЗДАННАЯ строка вдобавок объявляется в группу получателя по коммиту;
    холостой повтор — нет (см. комментарий у on_commit).
    """
    if not recipient or not recipient.strip():
        raise ValueError("notify требует получателя")
    recipient = recipient.strip()
    payload = payload or {}

    try:
        if dedupe_key is None:
            notification = OpsNotification.objects.create(
                recipient=recipient,
                kind=kind,
                business_date=business_date,
                dedupe_key=None,
                payload=payload,
            )
            created = True
        else:
            notification, created = OpsNotification.objects.get_or_create(
                recipient=recipient,
                kind=kind,
                business_date=business_date,
                dedupe_key=dedupe_key,
                defaults={"payload": payload},
            )
        if created:
            # Откладывается ТОЛЬКО знак, никогда не запись: синхронная запись
            # и есть ПЕРВОЕ из докстринга модуля.
            #
            # А знак откладывать ОБЯЗАНО: посланный построчно, он объявил бы
            # клиенту строку, которую откат следом уносит. Построчная отправка
            # проходит все счастливые тесты и рвётся только на откате — в
            # проде.
            #
            # `partial`, а не lambda: так в on_commit уезжает сам объект
            # функции, и его видно тому, кто читает (и статическому разбору
            # тоже); заодно снимается классическая ловушка позднего связывания.
            #
            # Условие `created` — потому что знак отслеживает ИЗМЕНЕНИЕ
            # СОСТОЯНИЯ, а не вызов: догон по устройству переспрашивает уже
            # пройденные дни (идемпотентность держится знаком), и «слать на
            # каждый вызов» превратило бы один повтор в шквал дубликатов о
            # строках, которые не менялись.
            #
            # Регистрация стоит ВНУТРИ try, чтобы сбой самой регистрации попал
            # под тот же договор «побочный канал».
            transaction.on_commit(partial(_publish, notification))
        return notification
    except Exception:
        # Точку сохранения от гонки двух одновременных вызовов get_or_create
        # снимает сам; всё остальное (БД недоступна, сериализация) пишется и
        # глотается, а не летит наверх в деловую операцию.
        logger.exception(
            "notify() не сработал: получатель=%r вид=%r дата=%r",
            recipient,
            kind,
            business_date,
        )
        return None


# ── Отметка прочитанным ──────────────────────────────────────────────────
#
# ДОСТРОЙКА, А НЕ ПОРТ. Поле read_at приехало вместе с моделью, но писателя у
# него нет НИ ЗДЕСЬ, НИ В ИСТОЧНИКЕ: там отметка прочитанным была частью
# истории про интерфейс центра уведомлений, и до сервера она не дошла. Лента
# отдавала поле, которое навсегда оставалось пустым, — то есть обещала
# состояние, которого не бывает.


def mark_read(notification, *, actor, at=None):
    """Отметить уведомление прочитанным. Возвращает строку.

    МОМЕНТ ПЕРВОГО ПРОЧТЕНИЯ, А НЕ ПОСЛЕДНЕГО ОТКРЫТИЯ. Повторный вызов момент
    НЕ двигает, и это не оптимизация: лента строится вокруг вопроса «что нового
    с моего последнего захода», и подвижная отметка возвращала бы старое
    уведомление в «свежие» каждый раз, когда человек его переоткрыл. Ровно
    поэтому здесь read_at, а не булев признак: булев ответил бы «да/нет» и
    вопроса о времени бы не поднял.

    ЧУЖОЕ УВЕДОМЛЕНИЕ НЕ ОТМЕЧАЕТСЯ. Проверка стоит здесь, а не только в
    маршруте: маршрут не единственный вход, а «прочитано» — это утверждение о
    КОНКРЕТНОМ человеке. Отметив чужое, мы сказали бы за него, что он видел то,
    чего не видел, и его собственная лента об этом факте замолчала бы.

    Время берётся у часов раздела, а не auto_now: отметка обязана быть
    воспроизводимой в тестах и согласованной с остальными моментами ленты.
    """
    if not actor or not str(actor).strip():
        raise ValueError("mark_read требует получателя")
    actor = str(actor).strip()
    if notification.recipient != actor:
        raise DomainError(
            "PERMISSION_DENIED",
            403,
            detail={"notification_id": notification.pk},
            message="Уведомление адресовано не вам.",
        )
    if notification.read_at is not None:
        # Холостой повтор: ни записи, ни сдвига момента. Возврат — та же
        # строка, чтобы вызывающему не приходилось различать два исхода.
        return notification
    notification.read_at = at or Clock.now()
    notification.save(update_fields=["read_at", "updated_at"])
    return notification


def mark_all_read(actor, *, until=None, at=None):
    """Отметить прочитанными все свои непрочитанные. Возвращает их число.

    ОДНИМ ЗАПРОСОМ, а не циклом по ленте. Лента накапливается неограниченно
    (догон шлёт по строке на день), и поштучная отметка дала бы число запросов,
    растущее с её длиной, — ровно ту зависимость, от которой раздел избавляется
    везде, где может.

    ТРОГАЮТСЯ ТОЛЬКО НЕПРОЧИТАННЫЕ. Безусловное обновление переписало бы моменты
    у прочитанных раньше, то есть сдвинуло бы вперёд всю историю прочтения —
    поштучная отметка первого прочтения бережёт этот момент ровно за тем же.

    `until` — ВЕРХНЯЯ ГРАНИЦА по времени появления, включительно. Она не
    удобство: клиент отмечает «всё, что я вижу», а между открытием ленты и
    нажатием могло прилететь новое уведомление. Без границы оно оказалось бы
    прочитанным, не будучи показанным, — то есть человек не узнал бы о нём
    никогда. Включительность здесь обратна курсору `since` у ленты: тот отвечает
    «строго новее уже виденного», этот — «всё вплоть до вот этого момента»,
    и оба конца принадлежат виденному.

    Возвращается ЧИСЛО отмеченных, а не строки: вызывающему нужно сказать
    человеку «прочитано N», а не показать их заново.
    """
    if not actor or not str(actor).strip():
        raise ValueError("mark_all_read требует получателя")
    queryset = OpsNotification.objects.filter(
        recipient=str(actor).strip(), read_at__isnull=True
    )
    if until is not None:
        queryset = queryset.filter(created_at__lte=until)
    return queryset.update(read_at=at or Clock.now())


class DeliveryTally:
    """Счёт рассылки: считается ДОСТАВЛЕННОЕ, а не попытки (Plane №829).

    🔴 ЗАЧЕМ ПОМОЩНИК. Один и тот же приём жил ТРЕМЯ копиями — в
    `ops/forces_notify.py` (заведён №561), `ops/placement_return_notify.py`
    (№809) и `ops/assignment_decline_notify.py`. Во всех трёх одна и та же
    тройка: `notify(...) is None` → строка в `undelivered` → `continue`, иначе
    `notified += 1`. Три копии — та граница, за которой копирование стоит
    дороже помощника: правило «доставленное, а не попытки» приходилось помнить
    и повторять в каждом новом модуле рассылки, а забыть его — ровно тот
    дефект, который карточки №561 и №809 уже закрывали по одному.

    🔴 ПОЧЕМУ ПРАВИЛО ВООБЩЕ НУЖНО. `notify()` по замыслу глотает любое
    исключение и возвращает `None`: рассылка не должна ронять бизнес-операцию.
    Значит безусловный `notified += 1` пишет в журнал аудита доставку, которой
    не было, — и разбор «почему не выделили / почему не заступил» идёт по
    ложному следу, потому что поле утверждает, что человека попросили.

    🔴 ЧЕГО ПОМОЩНИК НЕ ДЕЛАЕТ — И ЭТО НАМЕРЕННО. Он не собирает отчёт
    целиком. Форма отчёта у модулей законно разная: у рассылки запроса сил
    вместо `unlinked` свои `headlessDirectorates` и `withoutQuota`. Собрать
    «общий» словарь значило бы либо навязать всем лишние ключи, либо менять
    формат уже записанного аудита — а это отдельное решение, вынесенное в
    карточку №829 вторым пунктом. Здесь живёт ПРАВИЛО доставки и ФОРМАТ
    подписи, а не структура ответа.
    """

    def __init__(self):
        self.notified = 0
        #: Сотрудники без учётки: попросить некого, и это не отказ доставки.
        self.unlinked = []
        #: Кому не дошло — ПОИМЁННО. «Двоим не дошло» не говорит, кому, и
        #: чинить это некому.
        self.undelivered = []
        #: Уволенные: слать было НЕ НАДО. Третья графа, а не строка в
        #: `unlinked` (Plane №900) — см. `skip_dismissed`.
        self.dismissed = []

    def skip_unlinked(self, label) -> None:
        """Получателя нет вовсе — учётка к сотруднику не привязана."""
        self.unlinked.append(label)

    def skip_dismissed(self, label) -> None:
        """Сотрудник уволен — слать НЕ НАДО (Plane №900).

        🔴 ТРЕТЬЯ ГРАФА, А НЕ СТРОКА В `unlinked`. Графы этого счёта делятся
        по ПОЧИНКЕ, а не по итогу: «нет учётки» чинит кадровик, «не дошло»
        — тот, кто чинит базу. Уволенного не чинит никто: его в наряде уже
        нет, и всякий разбор такой строки кончался бы ничем — а строк этих
        со временем накапливается больше, чем настоящих.

        Молча выбросить его тоже нельзя: в расстановке он остался, и отчёт
        обязан объяснить, почему уведомлений меньше, чем назначенных.
        """
        self.dismissed.append(label)

    def deliver(self, recipient, kind, business_date, payload=None, *, dedupe_key="", label) -> bool:
        """Сообщить и посчитать ЧЕСТНО. Возвращает «легло ли».

        Подпись недоставленного — «имя · учётка», один формат на все модули:
        имя нужно тому, кто пойдёт звонить человеку, учётка — тому, кто пойдёт
        смотреть, почему запись не легла. Разноформатная графа заставила бы
        читателя журнала ветвиться (найдено ревью, задача №825).
        """
        if notify(recipient, kind, business_date, payload, dedupe_key=dedupe_key) is None:
            self.undelivered.append(f"{label} · {recipient}")
            return False
        self.notified += 1
        return True
