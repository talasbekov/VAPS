// Настройки (§29 мастер-промпта). Промпт объединяет аудит и настройки одним
// разделом, но требует РАЗДЕЛИТЬ ответственность: `/audit` — read-only
// operational audit, `/settings` — role-restricted administration. Здесь
// вторая половина.
//
// ЧТО ИМЕННО АДМИНИСТРИРУЕТСЯ. Список §29 («status types, conflict rules,
// rating rules, weather corrections, notification settings, demo feature
// flags, system settings, reset demo data, dictionaries») покрыт ровно в той
// части, под которой есть живой потребитель:
//
// * ПОЛИТИКА НАБЛЮДЕНИЙ §22.11 — допуски и пороги детекторов блока «Требует
//   внимания». Их читает аналитика службы, поэтому изменение здесь ВИДНО на
//   другом экране, а не остаётся украшением.
// * `reset demo data`, `feature flags`, persona/scenario — сознательно НЕ
//   сюда: §8.3 прямо называет их `mock-only-demo` runtime-функциями, которым
//   запрещено появляться в продуктовом API. Они и остаются в DemoToolbar.
// * `status types`/`dictionaries` уже администрируются разделом «Справочники»
//   (§30) — дублировать их вторым экраном значило бы завести второй источник
//   истины для одних и тех же значений.
// * `rating rules` — рейтингов в этой сборке нет (сознательный scope cut
//   A24), настройка без предмета была бы мёртвой (§35).
// * ПРАВИЛА КОНФЛИКТОВ §29 (`conflict rules`) — режим обязательного отдыха
//   §21.35. Их читает планирование дежурств, поэтому изменение здесь меняет
//   ИСХОД операции (назначение в период отдыха отвергается либо требует
//   обоснования), а не окраску экрана.

/** Единица измерения значения. Нужна, чтобы экран не подписывал «3» без смысла. */
export type SettingValueType = 'DAYS' | 'PERCENT' | 'COUNT' | 'HOURS' | 'MINUTES' | 'MODE'

/** Поле определения, которым управляет запись настройки. */
export type SettingField = 'PARAMETER' | 'WARNING_FROM' | 'CRITICAL_FROM' | 'MODE'

/**
 * Раздел политики. Разделы ВЕРСИОНИРУЮТСЯ ПОРОЗНЬ: у каждого свой потребитель
 * (наблюдения читает аналитика §22.11, правила конфликтов — планирование
 * дежурств §21.34), и общая версия означала бы, что правка порога наблюдений
 * меняет методику конфликтов. План утверждал бы о себе неправду.
 */
export type SettingSectionCode =
  | 'ATTENTION_POLICY'
  | 'CONFLICT_RULES'
  | 'PASSPORT_FRESHNESS'
  /**
   * §22.5 «Не хардкодь: последние 7/14/30/90 дней, квартал, срок хранения
   * отчёта». Глубина ПРОИЗВОЛЬНОГО периода аналитики и предел периода отчёта
   * вместе со сроком хранения — разные разделы, потому что у них разные
   * потребители: первый читает снимок аналитики, второй — отчётный реестр.
   * Общий раздел означал бы, что продление срока хранения файлов сдвигает
   * версию методики, по которой считался снимок службы.
   */
  | 'ANALYTICS_LIMITS'
  | 'REPORT_LIMITS'
  /**
   * §19.19/§22.17: период расчёта, минимальное количество оценок и правила
   * включения в aggregate «приходят от policy». Редакция раздела — это ещё и
   * ВЕРСИЯ МЕТОДИКИ, которой подписан каждый агрегат: правка порога делает
   * прежние значения несопоставимыми с новыми (§19.20), и сводка обязана об
   * этом сказать.
   */
  | 'RATING_POLICY'
  /**
   * §22.9: порог перегрузки и severity «приходят из Load Repository», а §22.5
   * запрещает хардкодить порог перегрузки. Раздел владеет ПОРОГАМИ нагрузки
   * (окно расчёта, warning/overload в минутах); его редакция — версия
   * методики, которой подписан каждый LoadMetric.
   */
  | 'LOAD_POLICY'

/** Вариант значения-перечисления (§21.35 `HARD_BLOCK` / `SOFT_OVERRIDE`). */
export interface SettingOption {
  value: string
  safeLabel: string
  /** Чем этот режим оборачивается для планирующего — следствие, а не синоним кода. */
  description: string
}

interface StoredSettingBase {
  settingCode: string
  sectionCode: SettingSectionCode
  /** Группа, к которой относится значение: детектор §22.11 либо правило §21.34. */
  groupCode: string
  field: SettingField
  safeLabel: string
  /** Что именно меняется — своими словами, не пересказ имени поля. */
  description: string
  updatedAt: string | null
  updatedBy: string | null
  /**
   * Редактируемость — свойство САМОГО правила, а не прав смотрящего: §21.34
   * «hard-conflict нельзя обойти» запрещает ослаблять запрет пересечения кому
   * бы то ни было. Правило показано, чтобы список правил был полон.
   */
  editable: boolean
  lockedReason: string | null
}

export interface NumericSetting extends StoredSettingBase {
  kind: 'NUMBER'
  valueType: Exclude<SettingValueType, 'MODE'>
  value: number
  /** Границы приходят с СЕРВЕРА вместе со значением: диапазон — часть
   * политики, а не догадка формы (иначе клиент и сервер разошлись бы). */
  minValue: number
  maxValue: number
}

export interface ChoiceSetting extends StoredSettingBase {
  kind: 'CHOICE'
  valueType: 'MODE'
  value: string
  /** Допустимые варианты — тоже с сервера: список в вёрстке разошёлся бы с
   * тем, что сервер готов принять. */
  options: readonly SettingOption[]
}

/** Запись настройки, как она лежит в слайсе (без прав смотрящего). */
export type StoredSetting = NumericSetting | ChoiceSetting

/**
 * Разрешение на правку КОНКРЕТНОЙ записи, посчитанное сервером. В компоненте
 * не остаётся ветки «если правило заперто — выключить»: причина отказа у
 * запертого правила и у нехватки права разная, и выбирать её должен тот, кто
 * знает обе (§21.28, тот же приём, что у действий месячного плана).
 */
export interface SettingAction {
  canEdit: boolean
  disabledReason: string | null
}

export type PolicySetting = StoredSetting & { action: SettingAction }

/**
 * Запись журнала изменений §29 («кто, когда, что, old/new, reason»).
 * Собственный журнал фичи, а НЕ запись в `/api/audit/logs/`: тот в этой сборке
 * read-only витрина фиксированных данных, и дописывание в чужой аггрегат
 * нарушило бы ARCH-FE-013 — тот же вывод, что у ленты обращения и журнала
 * переходов ОМ, которые тоже ведут свой журнал.
 */
export interface SettingChangeEvent {
  id: string
  settingCode: string
  sectionCode: SettingSectionCode
  safeLabel: string
  /**
   * Старое и новое — ГОТОВЫЕ подписи, а не сырые значения: у режима отдыха
   * запись «SOFT_OVERRIDE → HARD_BLOCK» требует от читателя журнала знания
   * кодов, а собирать подпись на экране значило бы держать словарь вариантов
   * в двух местах. Форматирует тот, кто владеет вариантами, — сервер.
   */
  oldValue: string
  newValue: string
  reason: string
  actorUserId: string
  changedAt: string
  /** Версия политики ПОСЛЕ изменения — по ней снимок аналитики сопоставляется
   * с методикой, по которой считался. */
  policyVersionAfter: string
}
