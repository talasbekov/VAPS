// Оперативный рейтинг участников охранных мероприятий (§19 мастер-промпта).
//
// ЧТО ЭТО НЕ ЕСТЬ. §19 открывается списком того, с чем оперативный рейтинг
// смешивать запрещено: повседневный кадровый рейтинг (`TalentRating`),
// фактическое время службы (`ServiceHoursEntry`), взыскания
// (`DisciplinaryAction`), благодарности (`Recognition`). Здесь заведено ровно
// два понятия — закрытая оценка по итогам мероприятия и серверная
// агрегированная сводка; остальные не заводятся, потому что источника у них
// нет, а пустая сущность выдавала бы себя за работающую (§35).
//
// ОБЪЁМ ЭТОГО СРЕЗА — только ЧТЕНИЕ агрегатов. Формы оценивания (§19.7-19.13),
// исправление оценки (§19.18) и sensitive-просмотр отдельных оценок (§19.21
// «контролёр рейтинга») не реализованы: у них своя цепочка прав, состояний и
// заданий. Права под них здесь НЕ заводятся — право без операции ничего не
// охраняет.

/** §19: шкала канонически 1–10 (прототипные `0–10` — ошибка, §19.1). */
export const RATING_SCALE_MIN = 1
export const RATING_SCALE_MAX = 10

/**
 * Закрытая оценка по итогам мероприятия (§19.2 `EventEvaluation`).
 *
 * ⚠️ НАРУЖУ НЕ ЕДЕТ НИ ОДНИМ ПОЛЕМ. §19.21 «закрытость должна обеспечиваться
 * API, а не только скрытием колонок»: в этом срезе нет ни одной операции,
 * которая отдавала бы отдельную оценку, оценщика или комментарий, — они живут
 * только в слайсе и участвуют в расчёте агрегата на сервере.
 */
export interface EventEvaluation {
  id: string
  securityEventId: string
  /** Кого оценивают. */
  employeeId: string
  /** Кто оценил — закрытое поле (§19.21). */
  evaluatorUserId: string
  /** Значение по шкале 1–10. */
  score: number
  /** Обязателен при оценке ниже 8 (§19.1) — закрытое поле. */
  comment: string | null
  /** Дата, на которую оценка относится: по ней период отсекает расчёт. */
  evaluatedAt: string
  /**
   * Исправление ведётся ОТДЕЛЬНОЙ неизменяемой записью (§19.1), а вытесненная
   * помечается ссылкой на неё. Агрегат исключает вытесненные — и делает это
   * СЕРВЕР: §19.19 прямо запрещает фронту «исключать исправленные оценки по
   * локальной логике».
   */
  supersededById: string | null
}

/**
 * Почему агрегата нет. Отдельное состояние, а не ноль: §19.2 «не считать
 * отсутствие рейтинга нулевым рейтингом», §19.19 «не показывай 0,0».
 */
export type RatingDataState =
  /** Агрегат рассчитан. */
  | 'READY'
  /** Оценок меньше минимума, заданного политикой. */
  | 'INSUFFICIENT_DATA'
  /** Политика расчёта не определена — считать не по чему (§19.19). */
  | 'POLICY_UNDEFINED'
  /** §19.3 `ENABLE_OPERATIONAL_RATINGS=false` — функция выключена целиком. */
  | 'FEATURE_DISABLED'

/**
 * Серверная агрегированная сводка (§19.19 `OperationalRatingSummary`).
 * Поля повторяют концептуальную модель промпта; `aggregateRating` может быть
 * только числом или `null`.
 */
export interface OperationalRatingSummary {
  employeeId: string
  /** Подпись сотрудника — безопасное поле, идентификатора в нём нет. */
  safeLabel: string
  aggregateRating: number | null
  evaluationsCount: number
  periodStartsAt: string | null
  periodEndsAt: string | null
  /** Версия МЕТОДИКИ, по которой считалось. Приходит из раздела политики: у
   * разных редакций разные пороги, и сравнивать их значения как однородные
   * нельзя (§19.20 «не соединяй несопоставимые периоды»). */
  calculationPolicyVersion: string | null
  calculatedAt: string
  dataState: RatingDataState
}

/** Политика расчёта (§19.19/§22.17: период, минимум оценок и включение в
 * aggregate приходят от policy, а не из кода). */
export interface RatingPolicy {
  periodDays: number
  minEvaluations: number
  /** Редакция раздела «Настроек» — она же версия методики. */
  policyVersion: string
}
