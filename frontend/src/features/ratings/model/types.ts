// Оперативный рейтинг участников охранных мероприятий (§19 мастер-промпта).
//
// ЧТО ЭТО НЕ ЕСТЬ. §19 открывается списком того, с чем оперативный рейтинг
// смешивать запрещено: повседневный кадровый рейтинг (`TalentRating`),
// фактическое время службы (`ServiceHoursEntry`), взыскания
// (`DisciplinaryAction`), благодарности (`Recognition`). Здесь заведено ровно
// два понятия — закрытая оценка по итогам мероприятия и серверная
// агрегированная сводка; остальные не заводятся, потому что источника у них
// нет, а пустая сущность выдавала бы себя за работающую (§35).
//
// ОБЪЁМ. Чтение агрегатов (§19.19-19.20, §22.16), рабочее пространство
// оценивания (§19.7-19.10, §19.14) и исправление СВОЕЙ отправленной оценки
// (§19.17-19.18: карточка, correction chain, замещающая запись).
// НЕ реализованы: групповая оценка (§19.13 — состав группы на момент
// мероприятия нигде не записан) и sensitive-просмотр ЧУЖИХ оценок (§19.21
// «контролёр рейтинга» — требует organization/event scope и срока полномочия
// одновременно). Права под них НЕ заводятся: право без операции ничего не
// охраняет.

/** §19: шкала канонически 1–10 (прототипные `0–10` — ошибка, §19.1). */
export const RATING_SCALE_MIN = 1
export const RATING_SCALE_MAX = 10

/**
 * Каноническая начальная оценка (§19.8). Значение приходит с сервера в
 * задании (`initialScore`); константа нужна ПРАВИЛУ комментария (§19.9
 * «для значения ниже 8 комментарий обязателен»), а не подстановке в форму.
 */
export const RATING_DEFAULT_SCORE = 8

/**
 * Направление оценивания (§19.12). Групповое направление объявлено, потому что
 * оно есть в модели промпта, но заданий этого направления в сборке НЕТ:
 * §19.13 требует показывать состав группы на момент мероприятия и фактический
 * состав, а таких снимков нигде не записано. Форма без них выдавала бы
 * групповую оценку за работающую (§35).
 */
export type EvaluationDirection = 'SENIOR_TO_EMPLOYEE' | 'SENIOR_TO_GROUP' | 'EMPLOYEE_TO_SENIOR'

/**
 * Как получена оценка (§19.8). Системная восьмёрка — не оценка человека:
 * «не приписывай её конкретному человеку как оценщику».
 */
export type EvaluationMethod = 'MANUAL' | 'SYSTEM_DEFAULT'

/** Состояние задания (§19.7). Наличие начального значения отправкой НЕ является. */
export type EvaluationWorkItemStatus = 'PENDING' | 'SUBMITTED'

/**
 * Задание на оценивание (§19.7 `EvaluationWorkItem`).
 *
 * Задания формирует РЕПОЗИТОРИЙ и хранит между перезагрузками: §19.7 прямо
 * запрещает фронту определять список target, генерировать идентификаторы и
 * создавать задание после refresh. Оценщик лежит в задании и приходит из
 * учётной записи запрашивающего — редактируемым полем он не передаётся.
 */
export interface EvaluationWorkItem {
  id: string
  securityEventId: string
  /** Прогон мероприятия (§19.12): оценка привязана к нему, а не к дате. */
  eventRunId: string
  /** Назначение, если оценивается конкретное назначение (§19.12). */
  assignmentId: string | null
  /** Кто должен оценить. Наружу не отдаётся — по нему отбирается очередь. */
  evaluatorUserId: string
  targetEmployeeId: string | null
  targetGroupId: string | null
  /** Безопасная подпись target (§19.14 «доступное имя target»). */
  targetSafeLabel: string
  /** Подразделение target — безопасное, без идентификаторов (§19.14). */
  targetSafeUnitLabel: string
  /** Пост или роль в мероприятии (§19.9). */
  postLabel: string
  /** Фактический интервал участия (§19.9) — факт мероприятия, не план. */
  actualStartsAt: string
  actualEndsAt: string
  /** Факт участия: `false` — участник заявлен, но не присутствовал. */
  participated: boolean
  evaluationDirection: EvaluationDirection
  /** Начальное значение (§19.8). Даёт СЕРВЕР, не `setState` формы. */
  initialScore: number
  status: EvaluationWorkItemStatus
  /** Растёт с каждой отправкой: тело мутации несёт ту редакцию, что видел человек. */
  revision: number
  /** Идентификатор отправленной оценки — появляется только после commit. */
  submittedEvaluationId: string | null
  submittedAt: string | null
}

/**
 * Исправление оценки (§19.18 `EvaluationCorrection`).
 *
 * Исправление — ОТДЕЛЬНАЯ запись, а не правка существующей: §19.18 «оценку
 * нельзя бесследно редактировать или удалять». Исходная оценка остаётся в
 * истории и лишь помечается ссылкой `supersededById`; из агрегата её исключает
 * СЕРВЕР (§19.19 запрещает делать это локальной логикой фронта).
 *
 * `correctedBy` — тот, кто исправил, и он НЕ становится оценщиком: §19.18
 * «нельзя изменить оценщика». Оценщик замещающей записи тот же, что у
 * исходной, иначе исправление переписывало бы авторство задним числом.
 */
export interface EvaluationCorrection {
  id: string
  originalEvaluationId: string
  replacementEvaluationId: string
  /** Причина исправления — обязательна (§19.18 шаг 6). Закрытое поле. */
  reason: string
  correctedBy: string
  correctedAt: string
  revision: number
}

/**
 * Основание оценки (§19.10). Перечень приходит С СЕРВЕРА: «основание не должно
 * быть произвольным frontend-only справочником». `requiresNote` — правило
 * policy для «Другое», а не догадка формы по коду.
 */
export interface EvaluationBasis {
  code: string
  label: string
  requiresNote: boolean
}

/**
 * Закрытая оценка по итогам мероприятия (§19.2 `EventEvaluation`).
 *
 * ⚠️ НАРУЖУ НЕ ЕДЕТ НИ ОДНИМ ПОЛЕМ. §19.21 «закрытость должна обеспечиваться
 * API, а не только скрытием колонок»: в этом срезе нет ни одной операции,
 * которая отдавала бы отдельную оценку, оценщика или комментарий, — они живут
 * только в слайсе и участвуют в расчёте агрегата на сервере.
 */
export interface EventEvaluation {
  id: string
  securityEventId: string
  /** Кого оценивают. */
  employeeId: string
  /**
   * Кто оценил — закрытое поле (§19.21). `null` у системной оценки: §19.8
   * «не приписывай её конкретному человеку как оценщику», и подставленный
   * технический пользователь был бы ровно таким приписыванием.
   */
  evaluatorUserId: string | null
  /** Значение по шкале 1–10. */
  score: number
  /** Обязателен при оценке ниже 8 (§19.1) — закрытое поле. */
  comment: string | null
  /**
   * Направление оценивания (§19.12). Хранится У ОЦЕНКИ, а не выводится из
   * ролей участников: роли меняются, а запись о том, кто кого оценивал в
   * мероприятии, меняться не должна.
   */
  evaluationDirection: EvaluationDirection
  /**
   * Как оценка появилась (§19.8). `SYSTEM_DEFAULT` — зафиксированная политикой
   * восьмёрка: у неё НЕТ человека-оценщика, и приписывать её кому-то нельзя.
   */
  method: EvaluationMethod
  /** Основание (§19.10). `null` у системной оценки — её никто не обосновывал. */
  basisCode: string | null
  /** Пояснение к основанию «Другое» — закрытое поле, как и комментарий. */
  basisNote: string | null
  /** Дата, на которую оценка относится: по ней период отсекает расчёт. */
  evaluatedAt: string
  /**
   * Исправление ведётся ОТДЕЛЬНОЙ неизменяемой записью (§19.1), а вытесненная
   * помечается ссылкой на неё. Агрегат исключает вытесненные — и делает это
   * СЕРВЕР: §19.19 прямо запрещает фронту «исключать исправленные оценки по
   * локальной логике».
   */
  supersededById: string | null
}

/**
 * Почему агрегата нет. Отдельное состояние, а не ноль: §19.2 «не считать
 * отсутствие рейтинга нулевым рейтингом», §19.19 «не показывай 0,0».
 */
export type RatingDataState =
  /** Агрегат рассчитан. */
  | 'READY'
  /** Оценок меньше минимума, заданного политикой. */
  | 'INSUFFICIENT_DATA'
  /** Политика расчёта не определена — считать не по чему (§19.19). */
  | 'POLICY_UNDEFINED'
  /** §19.3 `ENABLE_OPERATIONAL_RATINGS=false` — функция выключена целиком. */
  | 'FEATURE_DISABLED'

/**
 * Серверная агрегированная сводка (§19.19 `OperationalRatingSummary`).
 * Поля повторяют концептуальную модель промпта; `aggregateRating` может быть
 * только числом или `null`.
 */
export interface OperationalRatingSummary {
  employeeId: string
  /** Подпись сотрудника — безопасное поле, идентификатора в нём нет. */
  safeLabel: string
  aggregateRating: number | null
  evaluationsCount: number
  periodStartsAt: string | null
  periodEndsAt: string | null
  /** Версия МЕТОДИКИ, по которой считалось. Приходит из раздела политики: у
   * разных редакций разные пороги, и сравнивать их значения как однородные
   * нельзя (§19.20 «не соединяй несопоставимые периоды»). */
  calculationPolicyVersion: string | null
  calculatedAt: string
  dataState: RatingDataState
}

/**
 * Точка динамики (§19.20). Это ЗАПИСАННЫЙ агрегат закрытого периода, а не
 * значение, вычисленное «на лету»: §19.20 требует строить график только по
 * агрегированным серверным точкам и прямо запрещает пересчитывать старые точки
 * во frontend. Поэтому точка несёт СВОЮ `policyVersion` — ту, по которой её
 * посчитали тогда, а не текущую редакцию методики.
 *
 * Отдельные закрытые оценки в точку не входят ни одним полем (§19.20
 * «Не показывай на графике отдельные закрытые оценки»).
 */
export interface RatingDynamicsPoint {
  employeeId: string
  /** Код периода — то, что §19.20 называет `period` (напр. `2026-05`). */
  period: string
  periodStartsAt: string
  periodEndsAt: string
  /** `null` — агрегата за период нет. Не ноль (§19.19 «Не показывай 0,0»). */
  aggregateRating: number | null
  evaluationsCount: number
  /** Версия методики НА МОМЕНТ расчёта точки. */
  policyVersion: string
  /** Закрытый период имеет ровно два исхода: посчитан или данных не хватило. */
  dataState: Extract<RatingDataState, 'READY' | 'INSUFFICIENT_DATA'>
  /** Когда точка зафиксирована сервером. */
  recordedAt: string
}

/**
 * Граница смены методики (§19.20 «обозначь границу смены методики»). Считает
 * её СЕРВЕР: для клиента это факт из ответа, а не вывод из соседних точек —
 * иначе граница была бы фронтовой догадкой о том, что произошло на сервере.
 */
export interface RatingPolicyBoundary {
  /** Первый период НОВОЙ методики. */
  period: string
  fromPolicyVersion: string
  toPolicyVersion: string
}

/** Политика расчёта (§19.19/§22.17: период, минимум оценок и включение в
 * aggregate приходят от policy, а не из кода). */
export interface RatingPolicy {
  periodDays: number
  minEvaluations: number
  /** Редакция раздела «Настроек» — она же версия методики. */
  policyVersion: string
}
